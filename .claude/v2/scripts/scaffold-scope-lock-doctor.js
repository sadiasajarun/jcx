#!/usr/bin/env node
// scaffold-scope-lock-doctor.js — v128 (deterministic-primary page generation).
//
// THE ENFORCEMENT HALF of the deterministic-primary contract:
//   1. scaffold-page-from-story (et al.) generate deterministic pages FIRST —
//      guaranteed to compile, carry the story-spec data-testids, and make the
//      right API calls.
//   2. convert-pages (LLM) is demoted to VISUAL ENHANCEMENT ONLY — it restyles
//      those pages in place but is scope-locked: it must keep the data-testids,
//      the default export, and generally the data wiring.
//   3. A prompt instruction alone is an LLM-promise, not a guarantee
//      ([[feedback_template_wins_llm]]). This doctor makes the lock REAL:
//
//      --snapshot  (before convert-pages): copy every scaffold-marked page under
//                  app/pages/ into .scaffold-snapshots/ + record its contract
//                  (data-testids, default export) in manifest.json.
//      --enforce   (after the LAST LLM mutation node, before build): for each
//                  snapshotted page, verify the contract still holds. If the LLM
//                  deleted the file, dropped the default export, or lost ANY
//                  story-spec data-testid → RESTORE the deterministic snapshot.
//                  Visual polish is nice-to-have; a page that boots and passes
//                  its story spec is the floor. Floor wins.
//
// Idempotent: --snapshot overwrites the snapshot dir; --enforce only writes
// when a violation is found. Restores are logged loudly (one line per file).
'use strict';

var fs = require('fs');
var path = require('path');

var SNAP_DIR = '.scaffold-snapshots';
var MARKER_RE = /^\/\/ Generated by scaffold-/;

function parseArgs(argv) {
  var out = { mode: null };
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--target') out.target = argv[++i];
    else if (a === '--snapshot') out.mode = 'snapshot';
    else if (a === '--enforce') out.mode = 'enforce';
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.target || !out.mode) {
    console.error('Usage: scaffold-scope-lock-doctor --target FRONTEND_DIR (--snapshot | --enforce) [--verbose]');
    process.exit(1);
  }
  return out;
}

function walkTsx(dir, cb) {
  if (!fs.existsSync(dir)) return;
  fs.readdirSync(dir, { withFileTypes: true }).forEach(function (e) {
    if (e.name === 'node_modules' || e.name[0] === '.') return;
    var p = path.join(dir, e.name);
    if (e.isDirectory()) walkTsx(p, cb);
    else if (e.isFile() && /\.tsx$/.test(e.name)) cb(p);
  });
}

// Extract the STATIC data-testids of a page. Dynamic ones (template literals)
// can't be statically required, so the contract is the literal set only.
function testidsOf(src) {
  var ids = {};
  var re = /data-testid="([^"]+)"/g;
  var m;
  while ((m = re.exec(src))) ids[m[1]] = true;
  return Object.keys(ids);
}

function hasDefaultExport(src) {
  return /export\s+default\b/.test(src);
}

function snapshot(target, verbose) {
  var pagesDir = path.join(target, 'app', 'pages');
  if (!fs.existsSync(pagesDir)) { console.log('scaffold-scope-lock-doctor: no app/pages — skipping'); return; }
  var snapRoot = path.join(target, SNAP_DIR);
  // Fresh snapshot each run — stale entries from a previous pipeline attempt
  // must not resurrect pages that were legitimately replaced upstream.
  fs.rmSync(snapRoot, { recursive: true, force: true });
  var entries = [];
  walkTsx(pagesDir, function (f) {
    var src = fs.readFileSync(f, 'utf-8');
    if (!MARKER_RE.test(src)) return; // only scaffold-generated pages are locked
    var rel = path.relative(pagesDir, f).replace(/\\/g, '/');
    var dest = path.join(snapRoot, 'pages', rel);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, src);
    entries.push({ rel: rel, testids: testidsOf(src), hasDefault: hasDefaultExport(src) });
    if (verbose) console.log('  snap ' + rel + ' (' + entries[entries.length - 1].testids.length + ' testids)');
  });
  fs.mkdirSync(snapRoot, { recursive: true });
  fs.writeFileSync(path.join(snapRoot, 'manifest.json'), JSON.stringify({ pages: entries }, null, 2));
  console.log('scaffold-scope-lock-doctor: snapshot ' + entries.length + ' scaffold-generated pages');
}

function enforce(target, verbose) {
  var snapRoot = path.join(target, SNAP_DIR);
  var manifestFile = path.join(snapRoot, 'manifest.json');
  if (!fs.existsSync(manifestFile)) { console.log('scaffold-scope-lock-doctor: no snapshot manifest — skipping enforce'); return; }
  var manifest;
  try { manifest = JSON.parse(fs.readFileSync(manifestFile, 'utf-8')); } catch (e) {
    console.log('scaffold-scope-lock-doctor: manifest unreadable (' + e.message + ') — skipping enforce'); return;
  }
  var pagesDir = path.join(target, 'app', 'pages');
  var restored = 0, ok = 0;
  (manifest.pages || []).forEach(function (entry) {
    var cur = path.join(pagesDir, entry.rel);
    var snap = path.join(snapRoot, 'pages', entry.rel);
    if (!fs.existsSync(snap)) return;
    var violation = null;
    if (!fs.existsSync(cur)) {
      violation = 'file deleted';
    } else {
      var src = fs.readFileSync(cur, 'utf-8');
      if (entry.hasDefault && !hasDefaultExport(src)) {
        violation = 'lost default export';
      } else {
        var missing = (entry.testids || []).filter(function (id) { return src.indexOf(id) === -1; });
        if (missing.length > 0) violation = 'lost testids: ' + missing.slice(0, 5).join(', ') + (missing.length > 5 ? ' (+' + (missing.length - 5) + ')' : '');
      }
    }
    if (violation) {
      fs.mkdirSync(path.dirname(cur), { recursive: true });
      fs.copyFileSync(snap, cur);
      restored++;
      console.log('  RESTORED ' + entry.rel + ' — ' + violation);
    } else {
      ok++;
      if (verbose) console.log('  ok ' + entry.rel);
    }
  });
  console.log('scaffold-scope-lock-doctor: enforce — ' + ok + ' pages honor the contract, ' + restored + ' restored from snapshot');
}

function main() {
  var args = parseArgs(process.argv);
  if (!fs.existsSync(args.target)) { console.log('scaffold-scope-lock-doctor: target not found: ' + args.target); return; }
  if (args.mode === 'snapshot') snapshot(args.target, args.verbose);
  else enforce(args.target, args.verbose);
}

main();
