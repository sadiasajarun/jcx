#!/usr/bin/env node
// scaffold-django-app-registry.js — wires the generated model apps into the
// Django project: per-app apps.py + __init__.py, and fills the INSTALLED_APPS +
// root-urls include blocks (between scaffold markers) in config/. Analog of
// scaffold-app-module-registry (NestJS AppModule registration).
'use strict';
var fs = require('fs');
var path = require('path');
var L = require('./_django-lib');

function parseArgs(argv) {
  var out = { project: 'config' };
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--db') out.db = argv[++i];
    else if (a === '--target') out.target = argv[++i];
    else if (a === '--project') out.project = argv[++i];
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.db || !out.target) { console.error('Usage: scaffold-django-app-registry --db PROJECT_DATABASE.md --target BACKEND_DIR [--project config]'); process.exit(1); }
  return out;
}

function fillBlock(src, startMark, endMark, lines) {
  var s = src.indexOf(startMark), e = src.indexOf(endMark);
  if (s < 0 || e < 0) return src;
  var head = src.slice(0, s + startMark.length);
  var tail = src.slice(e);
  return head + '\n' + lines.join('\n') + '\n    ' + tail.replace(/^\s*/, '');
}

function main() {
  var args = parseArgs(process.argv);
  var entities = L.parseDatabase(fs.readFileSync(args.db, 'utf-8'));
  var apps = entities.map(function (e) { return e.table; }).filter(function (t) { return fs.existsSync(path.join(args.target, t, 'models.py')); });

  // per-app apps.py + __init__.py
  apps.forEach(function (t) {
    var dir = path.join(args.target, t);
    var initF = path.join(dir, '__init__.py');
    if (!fs.existsSync(initF)) fs.writeFileSync(initF, '');
    var cfg = L.toPascal(L.singularize(t)) + 'Config';
    fs.writeFileSync(path.join(dir, 'apps.py'),
      '# Generated by scaffold-django-app-registry\n' +
      'from django.apps import AppConfig\n\n\n' +
      'class ' + cfg + '(AppConfig):\n' +
      "    name = '" + t + "'\n" +
      "    default_auto_field = 'django.db.models.BigAutoField'\n");
  });

  // settings INSTALLED_APPS
  var settingsF = path.join(args.target, args.project, 'settings.py');
  if (fs.existsSync(settingsF)) {
    var s = fs.readFileSync(settingsF, 'utf-8');
    s = fillBlock(s, '# scaffold-django-app-registry-start', '# scaffold-django-app-registry-end',
      apps.map(function (t) { return "    '" + t + "',"; }));
    fs.writeFileSync(settingsF, s);
  }

  // root urls includes — /api/<table> → <table>.urls
  var urlsF = path.join(args.target, args.project, 'urls.py');
  if (fs.existsSync(urlsF)) {
    var u = fs.readFileSync(urlsF, 'utf-8');
    u = fillBlock(u, '# scaffold-django-app-registry-urls-start', '# scaffold-django-app-registry-urls-end',
      apps.map(function (t) { return "    path('api/" + t + "', include('" + t + ".urls')),"; }));
    fs.writeFileSync(urlsF, u);
  }

  console.log('scaffold-django-app-registry: registered ' + apps.length + ' app(s) into INSTALLED_APPS + root urls');
}

main();
