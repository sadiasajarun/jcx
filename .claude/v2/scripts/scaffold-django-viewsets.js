#!/usr/bin/env node
// scaffold-django-viewsets.js — DRF ModelViewSet + per-app router urls.
// Analog of scaffold-crud-module (NestJS controller+service). Reads
// PROJECT_DATABASE.md (the model set) and emits per table:
//   <table>/views.py  — <Model>ViewSet(ModelViewSet) (IsAuthenticated)
//   <table>/urls.py   — DefaultRouter(trailing_slash=False) registered at ''
// The root urls (scaffold-django-app-registry) mounts each at /api/<table>.
// trailing_slash=False matches NestJS routes (/api/applications, no slash) so
// differential-compare sees the same paths.
'use strict';
var fs = require('fs');
var path = require('path');
var L = require('./_django-lib');

var MARKER = '# Generated by scaffold-django-viewsets';

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--db') out.db = argv[++i];
    else if (a === '--target') out.target = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.db || !out.target) { console.error('Usage: scaffold-django-viewsets --db PROJECT_DATABASE.md --target BACKEND_DIR [--force]'); process.exit(1); }
  return out;
}

function renderViews(entity) {
  var model = L.toPascal(entity.name);
  return [
    MARKER,
    'from rest_framework import viewsets',
    'from rest_framework.permissions import IsAuthenticated',
    '',
    'from .models import ' + model,
    'from .serializers import ' + model + 'Serializer',
    '',
    '',
    'class ' + model + 'ViewSet(viewsets.ModelViewSet):',
    '    queryset = ' + model + '.objects.all()',
    '    serializer_class = ' + model + 'Serializer',
    '    permission_classes = [IsAuthenticated]',
    '',
  ].join('\n');
}

function renderUrls(entity) {
  var model = L.toPascal(entity.name);
  return [
    MARKER,
    'from rest_framework.routers import DefaultRouter',
    '',
    'from .views import ' + model + 'ViewSet',
    '',
    "router = DefaultRouter(trailing_slash=False)",
    "router.register(r'', " + model + "ViewSet, basename='" + entity.table + "')",
    '',
    'urlpatterns = router.urls',
    '',
  ].join('\n');
}

function writeIf(file, src, marker, force, verbose, label) {
  if (fs.existsSync(file) && !force && fs.readFileSync(file, 'utf-8').indexOf(marker) !== 0) return false;
  fs.writeFileSync(file, src);
  if (verbose) console.log('  ' + label);
  return true;
}

function main() {
  var args = parseArgs(process.argv);
  if (!fs.existsSync(args.db)) { console.error('scaffold-django-viewsets: no PROJECT_DATABASE.md'); process.exit(1); }
  var entities = L.parseDatabase(fs.readFileSync(args.db, 'utf-8'));
  var written = 0;
  entities.forEach(function (e) {
    var dir = path.join(args.target, e.table);
    if (!fs.existsSync(dir)) return; // model app must exist
    if (writeIf(path.join(dir, 'views.py'), renderViews(e), MARKER, args.force, args.verbose, e.table + '/views.py')) written++;
    writeIf(path.join(dir, 'urls.py'), renderUrls(e), MARKER, args.force, args.verbose, e.table + '/urls.py');
  });
  console.log('scaffold-django-viewsets: ' + written + ' viewset app(s) written');
}

main();
