#!/usr/bin/env node
// scaffold-fixtures-per-entity.js — v74 emits a test fixture per CRUD
// module (mirrors the canonical user.fixture.ts pattern). Each fixture
// exports `createTest<Entity>(dataSource, overrides?)` that inserts a
// row via the entity repository.
//
// Pattern lifted from test/fixtures/user.fixture.ts which uses runtime
// metadata to find the entity by class name. Same trick here.
'use strict';

var fs = require('fs');
var path = require('path');

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--spec') out.spec = argv[++i];
    else if (a === '--target') out.target = argv[++i];
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.spec || !out.target) { console.error('Usage: scaffold-fixtures-per-entity --spec MODULE_PLAN.yaml --target BACKEND_DIR'); process.exit(1); }
  return out;
}

function loadYaml() {
  try { return require('yaml'); } catch (_) {}
  return require(path.join(require('child_process').execSync('npm root -g', { encoding: 'utf-8' }).trim(), 'yaml'));
}

function cap(s) { return s ? s[0].toUpperCase() + s.slice(1) : s; }
function toPascal(s) {
  return s.split(/[-_\s]+/).filter(Boolean).map(function (w) { return cap(w.toLowerCase()); }).join('');
}
function toKebab(s) {
  return s.replace(/([a-z])([A-Z])/g, '$1-$2').replace(/[_\s]+/g, '-').toLowerCase();
}

function renderFixture(mod) {
  var entityPascal = mod.entity || toPascal(mod.name);
  var entityKebab = toKebab(entityPascal);

  // Build default values from fields
  var defaults = [];
  var fields = mod.fields || [];
  for (var i = 0; i < fields.length; i++) {
    var f = fields[i];
    if (!f.name) continue;
    if (/^(id|createdAt|updatedAt|deletedAt)$/i.test(f.name)) continue;
    var dv;
    if (f.type === 'number' || /Int|Number/.test(f.type)) dv = '0';
    else if (f.type === 'boolean') dv = 'false';
    else if (f.type === 'enum' && Array.isArray(f.enumValues) && f.enumValues.length) dv = "'" + f.enumValues[0] + "'";
    else if (f.type === 'Date' || /date/i.test(f.type)) dv = 'new Date()';
    else dv = "'test-" + f.name + "'";
    defaults.push('    ' + f.name + ': ' + dv + ',');
  }

  return [
    "/**",
    " * Generated by scaffold-fixtures-per-entity. Inserts a " + entityPascal + " row",
    " * directly via the repository. Useful for tests that need a pre-seeded record",
    " * without going through the full HTTP create flow.",
    " */",
    "import { DataSource } from 'typeorm';",
    "",
    "export interface Create" + entityPascal + "Input {",
    "  [key: string]: unknown;",
    "}",
    "",
    "export async function createTest" + entityPascal + "(",
    "  dataSource: DataSource,",
    "  overrides: Create" + entityPascal + "Input = {},",
    "): Promise<Record<string, unknown>> {",
    "  const meta = dataSource.entityMetadatas.find(",
    "    (m) => m.name === '" + entityPascal + "' || m.tableName === '" + (mod.plural || entityKebab + 's') + "',",
    "  );",
    "  if (!meta) {",
    "    throw new Error('createTest" + entityPascal + ": " + entityPascal + " entity not registered with the DataSource');",
    "  }",
    "  const repo = dataSource.getRepository(meta.target);",
    "  const row: Record<string, unknown> = {",
    defaults.join('\n'),
    "    ...overrides,",
    "  };",
    "  const saved = await repo.save(row as never);",
    "  return saved as unknown as Record<string, unknown>;",
    "}",
    "",
  ].join('\n');
}

function main() {
  var args = parseArgs(process.argv);
  if (!fs.existsSync(args.spec)) { console.error('scaffold-fixtures: MODULE_PLAN missing'); process.exit(1); }
  var yaml = loadYaml();
  var spec = yaml.parse(fs.readFileSync(args.spec, 'utf-8')) || {};
  var modules = spec.modules || [];

  var written = 0;
  var skipped = 0;
  for (var i = 0; i < modules.length; i++) {
    var mod = modules[i];
    if (!mod || !mod.name) continue;
    if (/^user$/i.test(mod.name)) continue; // canonical user.fixture already exists

    var content = renderFixture(mod);
    var dst = path.join(args.target, 'test/fixtures', toKebab(mod.name) + '.fixture.ts');
    if (fs.existsSync(dst)) { skipped++; continue; }
    if (args.dryRun) {
      console.log('  [dry] would write ' + path.relative(args.target, dst));
    } else {
      fs.mkdirSync(path.dirname(dst), { recursive: true });
      fs.writeFileSync(dst, content);
    }
    written++;
  }
  console.log('scaffold-fixtures-per-entity: wrote ' + written + ', skipped ' + skipped);
}

main();
