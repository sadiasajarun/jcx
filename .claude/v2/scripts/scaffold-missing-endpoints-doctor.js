#!/usr/bin/env node
// scaffold-missing-endpoints-doctor.js — v97
//
// Replacement for the route_to_agent fix-agent on integrate-2.yaml's
// `verify-missing-endpoints-yaml` node.
//
// CONTEXT:
//   integrate's LLM agent is supposed to write TWO files:
//     1. INTEGRATION_REPORT.md (metrics + skipped pages)
//     2. MISSING_ENDPOINTS.yaml (structured cross-gen signal — backend
//        phase reads it next iteration to auto-generate missing modules)
//
//   When (2) is missing, route_to_agent fires fix-agent (5-25 min, LLM)
//   to write a file containing `endpoints: []` or parse INTEGRATION_REPORT
//   for skipped entries. That's wildly over-engineered — the work is
//   deterministic given the report content.
//
// THIS DOCTOR:
//   1. Check if MISSING_ENDPOINTS.yaml exists with the required keys
//   2. If missing or malformed: write a canonical version with empty list
//   3. If INTEGRATION_REPORT.md has a "## Skipped" section, parse and
//      include those entries as missing_endpoints
//   4. Done in <1 second
//
// PER feedback_doctors_over_route_to_agent rule — replaces an LLM
// fix-agent call (avg 5-25 min) with a deterministic ~1-second script.
'use strict';

var fs = require('fs');
var path = require('path');

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--status-dir') out.statusDir = argv[++i];
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.statusDir) {
    console.error('Usage: scaffold-missing-endpoints-doctor --status-dir <STATUS_DIR>');
    process.exit(1);
  }
  return out;
}

function readSkippedFromIntegrationReport(reportPath) {
  if (!fs.existsSync(reportPath)) return [];
  var src = fs.readFileSync(reportPath, 'utf-8');
  var entries = [];
  // Look for "## Skipped (no matching hook)" section
  var skippedMatch = src.match(/## Skipped \(no matching hook\)([\s\S]*?)(?=\n##|$)/);
  if (!skippedMatch) return [];
  var section = skippedMatch[1];
  var lines = section.split('\n');
  // Each entry: "- <page-path>: <reason / which endpoint is missing>"
  var re = /^\s*-\s+(\S+?)(?::\s*(.*))?$/;
  for (var i = 0; i < lines.length; i++) {
    var m = lines[i].match(re);
    if (!m) continue;
    var pagePath = m[1];
    var reason = (m[2] || '').trim();
    // Best-effort: derive a resource name from the page path
    var resource = inferResource(pagePath);
    entries.push({ page: pagePath, reason: reason || 'no matching hook', resource: resource });
  }
  return entries;
}

function inferResource(pagePath) {
  // /admin/notices/list.tsx → notices
  // /worker/applications/[id].tsx → applications
  var basename = path.basename(pagePath, path.extname(pagePath));
  var parts = pagePath.replace(/\.[a-z]+$/i, '').split(/[\/\\]/);
  // Pick the segment most likely to be a resource (skip role + leaf)
  for (var i = parts.length - 2; i >= 0; i--) {
    var p = parts[i];
    if (/^(admin|worker|company|operator|super_admin|user|guest)$/i.test(p)) continue;
    if (/^(pages|app|src)$/i.test(p)) continue;
    if (p) return p.toLowerCase().replace(/_/g, '-');
  }
  return basename.toLowerCase().replace(/_/g, '-');
}

function groupByResource(entries) {
  var groups = {};
  entries.forEach(function (e) {
    var r = e.resource;
    if (!groups[r]) groups[r] = { resource: r, pages: [], reasons: new Set() };
    groups[r].pages.push(e.page);
    if (e.reason) groups[r].reasons.add(e.reason);
  });
  return Object.values(groups);
}

function emitMissingEndpointsYaml(statusDir, args) {
  var dst = path.join(statusDir, 'MISSING_ENDPOINTS.yaml');
  if (fs.existsSync(dst)) {
    var src = fs.readFileSync(dst, 'utf-8');
    if (/^generated_at:/m.test(src) && /^missing_endpoints:/m.test(src)) {
      console.log('scaffold-missing-endpoints-doctor: file already exists with required keys — skipping');
      return;
    }
    if (args.verbose) console.log('  existing file missing required keys — rewriting');
  }

  // Try to harvest entries from INTEGRATION_REPORT.md
  var reportPath = path.join(statusDir, 'INTEGRATION_REPORT.md');
  var skipped = readSkippedFromIntegrationReport(reportPath);
  var groups = groupByResource(skipped);

  // Stamp generated_at as a literal placeholder so the file is reproducible
  // (no real timestamp — pipeline scripts shouldn't introduce non-determinism
  // for downstream cache-keying).
  var lines = [
    '# Generated by scaffold-missing-endpoints-doctor — DO NOT EDIT BY HAND.',
    '# Replaces the route_to_agent fix-agent. Re-runs of this scaffold are',
    '# idempotent: if the file already has the required keys, no change.',
    'generated_at: integrate-phase-generated',
    'gen: 1',
    'missing_endpoints:'
  ];

  if (groups.length === 0) {
    lines.push('  # All pages were wired; no missing endpoints.');
    lines.push('  []');
  } else {
    groups.forEach(function (g) {
      lines.push('  - resource: ' + g.resource);
      lines.push('    module_name: ' + g.resource);
      lines.push('    reason: ' + (Array.from(g.reasons).join('; ') || 'inferred from skipped page'));
      lines.push('    consuming_pages:');
      g.pages.forEach(function (p) { lines.push('      - ' + p); });
      lines.push('    suggested_routes:');
      lines.push('      - { method: GET, path: \'/' + g.resource + '\' }');
      lines.push('      - { method: GET, path: \'/' + g.resource + '/:id\' }');
    });
  }
  lines.push('');

  var content = lines.join('\n');

  if (args.dryRun) {
    console.log('scaffold-missing-endpoints-doctor: would write ' + dst);
    if (args.verbose) console.log(content);
    return;
  }

  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.writeFileSync(dst, content);
  console.log('scaffold-missing-endpoints-doctor: wrote ' + dst +
    ' (' + (groups.length || 0) + ' resource group(s) from INTEGRATION_REPORT.md)');
}

function main() {
  var args = parseArgs(process.argv);
  if (!fs.existsSync(args.statusDir)) {
    console.log('scaffold-missing-endpoints-doctor: no status dir ' + args.statusDir + ' — skipping');
    return;
  }
  emitMissingEndpointsYaml(args.statusDir, args);
}

main();
