#!/usr/bin/env node
// scaffold-socket-client.js — FE half of the REALTIME capability (RULE-I5).
//
// Conditional: emits the socket.io-client integration ONLY when the backend has a
// @WebSocketGateway (the realtime capability is declared). The gateway's handshake
// auth reads the httpOnly JWT cookie, so the client connects with withCredentials.
//
// Emits (RR7 conventions: app/ dir, ~/ alias, single quotes, TS strict):
//   app/services/socketService.ts   — connect/get/disconnect singleton
//   app/contexts/SocketContext.tsx  — provider: connect on mount, disconnect on unmount
//   app/hooks/useSocket.ts          — useSocket() + useSocketEvent() (auto .off cleanup)
// + adds socket.io-client to package.json.
//
// Marker-idempotent; hand-authored files (no marker) are preserved.
'use strict';

var fs = require('fs');
var path = require('path');

var MARKER = '// Generated by scaffold-socket-client';

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--target') out.target = argv[++i];          // frontend dir
    else if (a === '--backend-dir') out.backendDir = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.target) { console.error('Usage: scaffold-socket-client --target FRONTEND_DIR [--backend-dir BACKEND_DIR]'); process.exit(1); }
  return out;
}

function backendHasGateway(backendDir) {
  if (!backendDir || !fs.existsSync(path.join(backendDir, 'src'))) return false;
  var found = false;
  (function walk(dir) {
    if (found) return;
    var ents;
    try { ents = fs.readdirSync(dir, { withFileTypes: true }); } catch (_) { return; }
    for (var i = 0; i < ents.length; i++) {
      if (found) return;
      var p = path.join(dir, ents[i].name);
      if (ents[i].isDirectory()) { if (ents[i].name !== 'node_modules') walk(p); }
      else if (/\.ts$/.test(ents[i].name)) {
        try { if (fs.readFileSync(p, 'utf-8').indexOf('@WebSocketGateway') !== -1) { found = true; return; } } catch (_) {}
      }
    }
  })(path.join(backendDir, 'src'));
  return found;
}

function socketService() {
  return [
    MARKER,
    "import { io, type Socket } from 'socket.io-client';",
    '',
    "let socket: Socket | null = null;",
    '',
    "// socket.io connects to the server ROOT (strip the trailing /api). withCredentials",
    "// sends the httpOnly JWT cookie the gateway's handleConnection authenticates (RULE-B7).",
    "function resolveUrl(): string {",
    "  const api = (import.meta.env.VITE_API_URL as string) || 'http://localhost:3000/api';",
    "  return api.replace(/\\/api\\/?$/, '');",
    "}",
    '',
    "export function connectSocket(namespace = ''): Socket {",
    "  if (socket && socket.connected) return socket;",
    "  socket = io(resolveUrl() + namespace, {",
    "    withCredentials: true,",
    "    transports: ['websocket'],",
    "    autoConnect: true,",
    "  });",
    "  return socket;",
    "}",
    '',
    "export function getSocket(): Socket | null {",
    "  return socket;",
    "}",
    '',
    "export function disconnectSocket(): void {",
    "  if (socket) {",
    "    socket.removeAllListeners();",
    "    socket.disconnect();",
    "    socket = null;",
    "  }",
    "}",
    '',
  ].join('\n');
}

function socketContext() {
  return [
    MARKER.replace('.ts', '.tsx'),
    "import { createContext, useContext, useEffect, useState, type ReactNode } from 'react';",
    "import type { Socket } from 'socket.io-client';",
    "import { connectSocket, disconnectSocket } from '~/services/socketService';",
    '',
    "interface SocketContextValue {",
    "  socket: Socket | null;",
    "  connected: boolean;",
    "}",
    '',
    "const SocketContext = createContext<SocketContextValue>({ socket: null, connected: false });",
    '',
    "interface SocketProviderProps {",
    "  children: ReactNode;",
    "}",
    '',
    "export function SocketProvider({ children }: SocketProviderProps) {",
    "  const [socket, setSocket] = useState<Socket | null>(null);",
    "  const [connected, setConnected] = useState(false);",
    '',
    "  useEffect(() => {",
    "    const s = connectSocket();",
    "    setSocket(s);",
    "    const onConnect = () => setConnected(true);",
    "    const onDisconnect = () => setConnected(false);",
    "    s.on('connect', onConnect);",
    "    s.on('disconnect', onDisconnect);",
    "    // RULE-I5: clean up listeners + disconnect on unmount (no leak).",
    "    return () => {",
    "      s.off('connect', onConnect);",
    "      s.off('disconnect', onDisconnect);",
    "      disconnectSocket();",
    "    };",
    "  }, []);",
    '',
    "  return <SocketContext.Provider value={{ socket, connected }}>{children}</SocketContext.Provider>;",
    "}",
    '',
    "export function useSocketContext(): SocketContextValue {",
    "  return useContext(SocketContext);",
    "}",
    '',
  ].join('\n');
}

function useSocketHook() {
  return [
    MARKER,
    "import { useEffect } from 'react';",
    "import { useSocketContext } from '~/contexts/SocketContext';",
    '',
    "export function useSocket() {",
    "  const { socket, connected } = useSocketContext();",
    "  return {",
    "    socket,",
    "    connected,",
    "    emit: (event: string, payload?: unknown) => socket?.emit(event, payload),",
    "  };",
    "}",
    '',
    "// Subscribe to a socket event with automatic cleanup (RULE-I5: socket.off on unmount).",
    "// Call at the top level of a component.",
    "export function useSocketEvent<T = unknown>(event: string, handler: (payload: T) => void): void {",
    "  const { socket } = useSocketContext();",
    "  useEffect(() => {",
    "    if (!socket) return;",
    "    const h = handler as (...args: unknown[]) => void;",
    "    socket.on(event, h);",
    "    return () => {",
    "      socket.off(event, h);",
    "    };",
    "  }, [socket, event, handler]);",
    "}",
    '',
  ].join('\n');
}

function ensureDep(target, dryRun, verbose) {
  var pkgPath = path.join(target, 'package.json');
  if (!fs.existsSync(pkgPath)) return;
  var pkg;
  try { pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8')); } catch (_) { return; }
  pkg.dependencies = pkg.dependencies || {};
  if (!pkg.dependencies['socket.io-client']) {
    pkg.dependencies['socket.io-client'] = '^4.7.0';
    if (!dryRun) fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
    if (verbose) console.log('  added socket.io-client to package.json');
  }
}

function writeFile(full, content, args) {
  if (fs.existsSync(full) && !args.force) {
    var cur = fs.readFileSync(full, 'utf-8');
    if (cur.indexOf('Generated by scaffold-socket-client') === -1) {
      if (args.verbose) console.log('  skip (hand-authored, no marker): ' + path.basename(full));
      return false;
    }
  }
  if (args.dryRun) { if (args.verbose) console.log('  [dry] ' + path.basename(full)); return true; }
  var dir = path.dirname(full);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(full, content);
  return true;
}

function main() {
  var args = parseArgs(process.argv);
  var app = path.join(args.target, 'app');
  if (!fs.existsSync(app)) { console.log('scaffold-socket-client: no app/ dir — skipping'); return; }
  if (!backendHasGateway(args.backendDir)) {
    console.log('scaffold-socket-client: backend has no @WebSocketGateway — skipping (conditional capability)');
    return;
  }
  console.log('scaffold-socket-client: backend gateway detected — emitting FE socket client');
  ensureDep(args.target, args.dryRun, args.verbose);
  var files = [
    [path.join(app, 'services/socketService.ts'), socketService()],
    [path.join(app, 'contexts/SocketContext.tsx'), socketContext()],
    [path.join(app, 'hooks/useSocket.ts'), useSocketHook()],
  ];
  var n = 0;
  for (var i = 0; i < files.length; i++) { if (writeFile(files[i][0], files[i][1], args)) n++; }
  console.log('scaffold-socket-client: ' + n + ' file(s) ' + (args.dryRun ? '(dry)' : 'written') +
    '. Wrap the app root in <SocketProvider> (integrate/convert wires this).');
}

main();
