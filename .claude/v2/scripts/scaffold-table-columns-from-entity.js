#!/usr/bin/env node
// scaffold-table-columns-from-entity.js — v78 per entity, emit a column
// config that DataTable can consume. Eliminates the LLM-written
// table-renderer drift (header/cell mismatched, missing columns, wrong
// formatting). Pairs with scaffold-data-table.
//
// Output: app/components/tables/<entity-kebab>-columns.tsx — array of
// { key, header, render? } per non-skip column.
//
// Skip rules:
//   - id, createdAt, updatedAt, deletedAt (BaseEntity boilerplate)
//   - relation properties (ManyToOne/etc — only emit the FK *Id column)
//   - password/passwordHash/secret/token-like fields (sensitive)
//
// Formatters:
//   - Date → toLocaleDateString
//   - Boolean → ✓ / —
//   - Enum → readable label (from enum string value)
//
// Idempotent. Marker: '// Generated by scaffold-table-columns-from-entity'.
'use strict';

var fs = require('fs');
var path = require('path');

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--backend-dir') out.backendDir = argv[++i];
    else if (a === '--target') out.target = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.backendDir || !out.target) {
    console.error('Usage: scaffold-table-columns-from-entity --backend-dir BACKEND --target FRONTEND [--force]');
    process.exit(1);
  }
  return out;
}

function toPascal(s) {
  return s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').split(/[-_\s]+/).filter(Boolean).map(function (w) {
    return w[0].toUpperCase() + w.slice(1).toLowerCase();
  }).join('');
}
function toKebab(s) {
  return s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/[_\s]+/g, '-').toLowerCase();
}

function findEntityFiles(modulesDir) {
  var out = [];
  if (!fs.existsSync(modulesDir)) return out;
  function walkInModule(modDir, currentDir) {
    fs.readdirSync(currentDir, { withFileTypes: true }).forEach(function (f) {
      var p = path.join(currentDir, f.name);
      if (f.isDirectory()) {
        if (f.name === 'dtos' || f.name === 'dto' || f.name === '__tests__') return;
        walkInModule(modDir, p);
      } else if (f.isFile() && /\.entity\.ts$/.test(f.name)) {
        out.push({ moduleName: path.basename(modDir), entityFile: p });
      }
    });
  }
  fs.readdirSync(modulesDir, { withFileTypes: true }).forEach(function (e) {
    if (!e.isDirectory()) return;
    walkInModule(path.join(modulesDir, e.name), path.join(modulesDir, e.name));
  });
  return out;
}

function parseEntity(content) {
  var classMatch = /export\s+class\s+(\w+)\s+extends\s+\w+/.exec(content);
  if (!classMatch) return null;
  var className = classMatch[1];
  var props = [];
  var lines = content.split('\n');
  var pending = [];
  var inClass = false;
  for (var i = 0; i < lines.length; i++) {
    var trimmed = lines[i].trim();
    if (!inClass) {
      if (/^export\s+class\s+\w+\s+extends/.test(lines[i])) inClass = true;
      continue;
    }
    if (!trimmed) continue;
    if (/^\}/.test(trimmed)) break;
    if (/^@/.test(trimmed)) { pending.push(trimmed); continue; }
    var m = /^(?:readonly\s+)?(\w+)\s*([?!])?:\s*([^;]+);?\s*$/.exec(trimmed);
    if (!m) { pending = []; continue; }
    var name = m[1], tsType = m[3].trim();
    var blob = pending.join(' ');
    pending = [];
    // Skip relations
    if (/@ManyToOne|@OneToMany|@ManyToMany|@OneToOne|@JoinColumn|@JoinTable/.test(blob)) continue;
    if (!/@Column|@PrimaryColumn|@PrimaryGeneratedColumn/.test(blob)) continue;
    // Skip BaseEntity fields
    if (/^(id|createdAt|updatedAt|deletedAt)$/.test(name)) continue;
    // Skip sensitive fields
    if (/^(password|passwordHash|secret|token|refreshToken|accessToken)$/i.test(name)) continue;
    var kind = 'string';
    if (/type:\s*['"]enum['"]/.test(blob)) kind = 'enum';
    else if (/^boolean$/.test(tsType)) kind = 'boolean';
    else if (/^number$/.test(tsType) || /int|numeric|decimal/i.test(blob)) kind = 'number';
    else if (/^Date$/.test(tsType) || /timestamp|date/i.test(blob)) kind = 'date';
    props.push({ name: name, tsType: tsType, kind: kind });
  }
  return { className: className, props: props };
}

function marker() { return '// Generated by scaffold-table-columns-from-entity — DO NOT EDIT BY HAND. Re-run if entity changes.'; }

function humanLabel(name) {
  var label = name.replace(/([a-z0-9])([A-Z])/g, '$1 $2');
  return label.charAt(0).toUpperCase() + label.slice(1);
}

function renderFor(p) {
  if (p.kind === 'date') {
    return '    render: (row: Row) => row.' + p.name + ' ? new Date(row.' + p.name + ' as string).toLocaleDateString() : \'\',';
  }
  if (p.kind === 'boolean') {
    return '    render: (row: Row) => (row.' + p.name + ' ? \'✓\' : \'—\'),';
  }
  // string/number/enum render as-is
  return null;
}

function emitColumns(className, props) {
  var lines = [];
  lines.push(marker());
  lines.push('import type { ' + className + 'Response } from \'~/types/' + toKebab(className) + '\';');
  lines.push('');
  lines.push('type Row = ' + className + 'Response & Record<string, unknown>;');
  lines.push('');
  lines.push('export interface Column<T> {');
  lines.push('  key: keyof T & string;');
  lines.push('  header: string;');
  lines.push('  render?: (row: T) => string;');
  lines.push('}');
  lines.push('');
  lines.push('export const ' + className.charAt(0).toLowerCase() + className.slice(1) + 'Columns: Column<Row>[] = [');
  props.forEach(function (p) {
    lines.push('  {');
    lines.push("    key: '" + p.name + "',");
    lines.push("    header: '" + humanLabel(p.name) + "',");
    var r = renderFor(p);
    if (r) lines.push(r);
    lines.push('  },');
  });
  lines.push('];');
  lines.push('');
  return lines.join('\n');
}

function writeIfManaged(file, content, force, dryRun) {
  if (fs.existsSync(file)) {
    var existing = fs.readFileSync(file, 'utf-8');
    if (!/Generated by scaffold-table-columns-from-entity/.test(existing) && !force) {
      return { written: false, reason: 'exists-handauthored' };
    }
    if (existing === content) return { written: false, reason: 'unchanged' };
  }
  if (dryRun) return { written: false, reason: 'dry-run' };
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return { written: true };
}

function main() {
  var args = parseArgs(process.argv);
  var modulesDir = path.join(args.backendDir, 'src/modules');
  var entities = findEntityFiles(modulesDir);
  if (entities.length === 0) {
    console.log('scaffold-table-columns-from-entity: no entities under ' + modulesDir);
    return;
  }
  var written = 0, skipped = 0;
  entities.forEach(function (e) {
    var content = fs.readFileSync(e.entityFile, 'utf-8');
    var parsed = parseEntity(content);
    if (!parsed || parsed.props.length === 0) return;
    var className = parsed.className.replace(/Entity$/, '');
    var kebab = toKebab(className);
    var dst = path.join(args.target, 'app/components/tables', kebab + '-columns.tsx');
    var r = writeIfManaged(dst, emitColumns(className, parsed.props), args.force, args.dryRun);
    if (r.written) written++; else skipped++;
    if (args.verbose) console.log('  ' + className + ' (' + parsed.props.length + ' cols): ' + (r.written ? 'wrote' : r.reason));
  });
  console.log('scaffold-table-columns-from-entity: ' + written + ' written, ' + skipped + ' skipped');
}

main();
