#!/usr/bin/env node
// scaffold-realtime-gateway.js — REALTIME capability primitive (Tier 2).
//
// Emits a NestJS @WebSocketGateway per MODULE_PLAN.yaml `realtime:` entry. This
// is a CAPABILITY, not a feature: "chat", "live-dashboard", "presence" all
// decompose onto this one primitive. The LLM only DECIDES which features need
// realtime (sets the `realtime:` section + flags); this scaffold deterministically
// emits the gateway grammar (cookie-JWT handshake auth per RULE-B7, room join/leave,
// one @SubscribeMessage per declared event, socket.io provider registration).
//
// Pairs with scaffold-room-membership (the room/permission capability). When an
// entry sets `rooms: true`, the gateway's join handler calls the RoomMembership
// guard/service if present — composition, not duplication. 1-on-1 vs group is NOT
// two gateways: a direct chat is a 2-member room, same code path.
//
// MODULE_PLAN.yaml shape:
//   realtime:
//     - name: chat              # → src/modules/chat/chat.gateway.ts
//       events: [message.send, typing, message.read]   # client→server inbound
//       rooms: true             # room-scoped (join/leave + membership check)
//       namespace: /chat        # optional socket.io namespace
//       cookie: access_token    # optional; JWT cookie name (default access_token)
'use strict';

var fs = require('fs');
var path = require('path');

var MARKER = '// Generated by scaffold-realtime-gateway';

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--spec') out.spec = argv[++i];
    else if (a === '--target') out.target = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.spec || !out.target) {
    console.error('Usage: scaffold-realtime-gateway --spec MODULE_PLAN.yaml --target BACKEND_DIR [--force]');
    process.exit(1);
  }
  return out;
}

function loadYaml() {
  try { return require('yaml'); } catch (_) {}
  try {
    return require(path.join(require('child_process').execSync('npm root -g', { encoding: 'utf-8' }).trim(), 'yaml'));
  } catch (_) { return null; }
}

function toPascal(s) {
  return String(s).split(/[-_\s]+/).filter(Boolean)
    .map(function (w) { return w[0].toUpperCase() + w.slice(1); }).join('');
}
function toKebab(s) {
  return String(s).replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/[_\s]+/g, '-').toLowerCase();
}
// 'message.send' / 'message:read' → 'messageSend' (handler method + event-const name)
function toCamelEvent(ev) {
  var parts = String(ev).split(/[.:\-_\s]+/).filter(Boolean);
  return parts.map(function (w, i) { return i === 0 ? w.toLowerCase() : w[0].toUpperCase() + w.slice(1); }).join('');
}

function renderGateway(rt) {
  var name = rt.name;
  var Pascal = toPascal(name);
  var kebab = toKebab(name);
  var events = Array.isArray(rt.events) ? rt.events.filter(Boolean) : [];
  var hasRooms = rt.rooms === true || rt.rooms === 'true';
  var ns = rt.namespace ? String(rt.namespace) : null;
  var cookieName = rt.cookie || 'access_token';

  var gwDecoratorArgs = "{ cors: { origin: (process.env.ALLOW_ORIGINS || '').split(',').filter(Boolean), credentials: true }" +
    (ns ? ", namespace: '" + ns + "'" : '') + " }";

  var L = [];
  L.push(MARKER);
  L.push("// REALTIME capability — " + name + " gateway. Cookie-JWT handshake auth (RULE-B7).");
  L.push("import {");
  L.push("  WebSocketGateway, WebSocketServer, SubscribeMessage,");
  L.push("  OnGatewayConnection, OnGatewayDisconnect, MessageBody, ConnectedSocket,");
  L.push("} from '@nestjs/websockets';");
  L.push("import { Logger } from '@nestjs/common';");
  L.push("import { Server, Socket } from 'socket.io';");
  L.push("import * as cookie from 'cookie';");
  L.push("import * as jwt from 'jsonwebtoken';");
  if (hasRooms) {
    L.push("import { RoomMembershipService } from '../room-membership/room-membership.service';");
  }
  L.push('');
  L.push("type AuthedSocket = Socket & { data: { user?: { id: string; role?: unknown } } };");
  L.push('');
  L.push("@WebSocketGateway(" + gwDecoratorArgs + ")");
  L.push("export class " + Pascal + "Gateway implements OnGatewayConnection, OnGatewayDisconnect {");
  L.push("  @WebSocketServer() server!: Server;");
  L.push("  private readonly logger = new Logger('" + Pascal + "Gateway');");
  if (hasRooms) {
    L.push('');
    L.push("  constructor(private readonly membership: RoomMembershipService) {}");
  }
  L.push('');
  // --- handshake auth ---
  L.push("  // RULE-B7: authenticate the socket from the httpOnly JWT cookie on connect.");
  L.push("  // No valid token → disconnect immediately (never trust an unauthenticated socket).");
  L.push("  handleConnection(client: AuthedSocket): void {");
  L.push("    try {");
  L.push("      const raw = client.handshake.headers.cookie || '';");
  L.push("      const token = cookie.parse(raw)['" + cookieName + "'] ||");
  L.push("        (client.handshake.auth && (client.handshake.auth as { token?: string }).token);");
  L.push("      const secret = process.env.JWT_SECRET;");
  L.push("      if (!token || !secret) { client.disconnect(true); return; }");
  L.push("      const payload = jwt.verify(token, secret) as { id?: string; sub?: string; role?: unknown };");
  L.push("      const id = payload.id || payload.sub;");
  L.push("      if (!id) { client.disconnect(true); return; }");
  L.push("      client.data.user = { id, role: payload.role };");
  L.push("      this.logger.log('connected ' + id + ' (' + client.id + ')');");
  L.push("    } catch {");
  L.push("      client.disconnect(true);");
  L.push("    }");
  L.push("  }");
  L.push('');
  L.push("  handleDisconnect(client: AuthedSocket): void {");
  L.push("    this.logger.log('disconnected ' + client.id);");
  L.push("  }");
  // --- room join/leave ---
  if (hasRooms) {
    L.push('');
    L.push("  // Join is membership-gated — composes the room-membership capability (RBAC).");
    L.push("  @SubscribeMessage('room.join')");
    L.push("  async onRoomJoin(@ConnectedSocket() client: AuthedSocket, @MessageBody() body: { roomId: string }) {");
    L.push("    const user = client.data.user;");
    L.push("    if (!user || !body || !body.roomId) return { ok: false, error: 'unauthenticated_or_bad_request' };");
    L.push("    const allowed = await this.membership.isMember(body.roomId, user.id);");
    L.push("    if (!allowed) return { ok: false, error: 'not_a_member' };");
    L.push("    await client.join(body.roomId);");
    L.push("    return { ok: true, roomId: body.roomId };");
    L.push("  }");
    L.push('');
    L.push("  @SubscribeMessage('room.leave')");
    L.push("  async onRoomLeave(@ConnectedSocket() client: AuthedSocket, @MessageBody() body: { roomId: string }) {");
    L.push("    if (body && body.roomId) await client.leave(body.roomId);");
    L.push("    return { ok: true };");
    L.push("  }");
  }
  // --- declared events ---
  for (var i = 0; i < events.length; i++) {
    var ev = events[i];
    var method = 'on' + toPascal(toCamelEvent(ev));
    L.push('');
    L.push("  @SubscribeMessage('" + ev + "')");
    L.push("  async " + method + "(@ConnectedSocket() client: AuthedSocket, @MessageBody() body: Record<string, unknown>) {");
    L.push("    const user = client.data.user;");
    L.push("    if (!user) return { ok: false, error: 'unauthenticated' };");
    if (hasRooms) {
      L.push("    const roomId = body && (body['roomId'] as string);");
      L.push("    // Broadcast to the room when room-scoped, else echo to the sender.");
      L.push("    const payload = { ...body, from: user.id, event: '" + ev + "', at: new Date().toISOString() };");
      L.push("    if (roomId) {");
      L.push("      const allowed = await this.membership.isMember(roomId, user.id);");
      L.push("      if (!allowed) return { ok: false, error: 'not_a_member' };");
      L.push("      this.server.to(roomId).emit('" + ev + "', payload);");
      L.push("    } else {");
      L.push("      client.emit('" + ev + "', payload);");
      L.push("    }");
      L.push("    return { ok: true };");
    } else {
      L.push("    const payload = { ...body, from: user.id, event: '" + ev + "', at: new Date().toISOString() };");
      L.push("    this.server.emit('" + ev + "', payload);");
      L.push("    return { ok: true };");
    }
    L.push("  }");
  }
  L.push("}");
  L.push('');
  return { kebab: kebab, Pascal: Pascal, code: L.join('\n'), hasRooms: hasRooms };
}

// Register the gateway as a provider in <name>.module.ts (create a minimal module
// if the feature has no CRUD module of its own).
function registerInModule(target, gw, dryRun, verbose) {
  var modDir = path.join(target, 'src/modules', gw.kebab);
  var modPath = path.join(modDir, gw.kebab + '.module.ts');
  var gwImport = "import { " + gw.Pascal + "Gateway } from './" + gw.kebab + ".gateway';";
  var memImport = gw.hasRooms
    ? "import { RoomMembershipModule } from '../room-membership/room-membership.module';" : null;

  if (!fs.existsSync(modPath)) {
    var lines = [];
    lines.push(MARKER);
    lines.push("import { Module } from '@nestjs/common';");
    lines.push(gwImport);
    if (memImport) lines.push(memImport);
    lines.push('');
    lines.push("@Module({");
    if (memImport) lines.push("  imports: [RoomMembershipModule],");
    lines.push("  providers: [" + gw.Pascal + "Gateway],");
    lines.push("})");
    lines.push("export class " + gw.Pascal + "Module {}");
    lines.push('');
    if (dryRun) { if (verbose) console.log('  [dry] would create ' + modPath); return modPath; }
    if (!fs.existsSync(modDir)) fs.mkdirSync(modDir, { recursive: true });
    fs.writeFileSync(modPath, lines.join('\n'));
    return modPath;
  }
  // Module exists (e.g. a CRUD module) — inject the gateway provider idempotently.
  var content = fs.readFileSync(modPath, 'utf-8');
  if (content.indexOf(gw.Pascal + 'Gateway') !== -1) return modPath; // already wired
  if (content.indexOf("from '@nestjs/common'") === -1) return modPath;
  var inject = gwImport + (memImport && content.indexOf('RoomMembershipModule') === -1 ? '\n' + memImport : '');
  var imps = content.match(/^import .*?;\s*$/gm);
  if (imps && imps.length) {
    var last = imps[imps.length - 1];
    var at = content.indexOf(last) + last.length;
    content = content.slice(0, at) + '\n' + inject + content.slice(at);
  } else {
    content = inject + '\n' + content;
  }
  content = content.replace(/providers:\s*\[([^\]]*)\]/, function (m, inner) {
    var items = inner.split(',').map(function (s) { return s.trim(); }).filter(Boolean);
    items.push(gw.Pascal + 'Gateway');
    return 'providers: [' + items.join(', ') + ']';
  });
  if (gw.hasRooms && content.indexOf('RoomMembershipModule') !== -1 && /imports:\s*\[/.test(content) === false) {
    // ensure imports array carries RoomMembershipModule if we just imported it
    content = content.replace(/@Module\(\{/, "@Module({\n  imports: [RoomMembershipModule],");
  }
  if (dryRun) { if (verbose) console.log('  [dry] would inject gateway into ' + modPath); return modPath; }
  fs.writeFileSync(modPath, content);
  return modPath;
}

// A self-contained capability owns its deps: add the websocket stack to
// package.json so scaffold-ensure-deps-installed picks them up on npm install.
function ensureDeps(target, dryRun, verbose) {
  var pkgPath = path.join(target, 'package.json');
  if (!fs.existsSync(pkgPath)) return;
  var pkg;
  try { pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8')); } catch (e) { return; }
  pkg.dependencies = pkg.dependencies || {};
  pkg.devDependencies = pkg.devDependencies || {};
  var deps = {
    '@nestjs/websockets': '^10.0.0',
    '@nestjs/platform-socket.io': '^10.0.0',
    'socket.io': '^4.7.0',
    'cookie': '^0.6.0',
    'jsonwebtoken': '^9.0.0',
  };
  var devDeps = { '@types/cookie': '^0.6.0', '@types/jsonwebtoken': '^9.0.0' };
  var changed = false;
  Object.keys(deps).forEach(function (d) {
    if (!pkg.dependencies[d] && !pkg.devDependencies[d]) { pkg.dependencies[d] = deps[d]; changed = true; }
  });
  Object.keys(devDeps).forEach(function (d) {
    if (!pkg.dependencies[d] && !pkg.devDependencies[d]) { pkg.devDependencies[d] = devDeps[d]; changed = true; }
  });
  if (changed && !dryRun) fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
  if (changed && verbose) console.log('  added websocket deps to package.json');
}

function main() {
  var args = parseArgs(process.argv);
  if (!fs.existsSync(args.spec)) { console.log('scaffold-realtime-gateway: no MODULE_PLAN — skipping'); return; }
  var yaml = loadYaml();
  if (!yaml) { console.log('scaffold-realtime-gateway: yaml unavailable — skipping'); return; }
  var spec;
  try { spec = yaml.parse(fs.readFileSync(args.spec, 'utf-8')); } catch (e) { console.log('scaffold-realtime-gateway: bad YAML — skipping'); return; }
  var list = spec && Array.isArray(spec.realtime) ? spec.realtime.filter(function (r) { return r && r.name; }) : [];
  if (list.length === 0) { console.log('scaffold-realtime-gateway: no `realtime:` entries — skipping'); return; }

  console.log('scaffold-realtime-gateway: ' + list.length + ' gateway(s)');
  ensureDeps(args.target, args.dryRun, args.verbose);
  for (var i = 0; i < list.length; i++) {
    var gw = renderGateway(list[i]);
    var gwDir = path.join(args.target, 'src/modules', gw.kebab);
    var gwPath = path.join(gwDir, gw.kebab + '.gateway.ts');
    var exists = fs.existsSync(gwPath);
    if (exists && !args.force) {
      var cur = fs.readFileSync(gwPath, 'utf-8');
      if (cur.indexOf(MARKER) === 0 || cur.indexOf(MARKER) !== -1) {
        if (args.verbose) console.log('  skip (marker present): ' + gw.kebab);
      } else {
        if (args.verbose) console.log('  skip (hand-authored, no marker): ' + gw.kebab);
        continue;
      }
    }
    if (args.dryRun) {
      console.log('  [dry] ' + gw.kebab + '.gateway.ts (' + (gw.hasRooms ? 'room-scoped' : 'broadcast') + ')');
    } else {
      if (!fs.existsSync(gwDir)) fs.mkdirSync(gwDir, { recursive: true });
      fs.writeFileSync(gwPath, gw.code);
    }
    registerInModule(args.target, gw, args.dryRun, args.verbose);
    console.log('  ' + gw.kebab + ' (events=' + ((list[i].events || []).length) + ', rooms=' + gw.hasRooms + ')');
  }
  console.log('scaffold-realtime-gateway: done');
}

main();
