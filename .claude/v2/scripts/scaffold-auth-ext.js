#!/usr/bin/env node
// scaffold-auth-ext.js — AUTH-EXTENSIONS capability primitive (Tier 2, NestJS/TypeORM).
//
// Extends the base auth-module with the integration adapters that are pure external-API
// boilerplate (must be reliable, not LLM-guessed): social-login verification (Kakao/Apple
// token bridge), SMS OTP (Solapi) with rate-limit, and SMTP email (nodemailer). Each is
// conditional on MODULE_PLAN flags. The adapters are deterministic; wiring into the
// project's User entity / signup flow is the LLM seam.
//
// MODULE_PLAN.yaml shape:
//   auth_ext:
//     social: [kakao, apple]     # provider-token verifiers (native-SDK token bridge)
//     sms_otp: solapi            # phone-verify + password-reset OTP
//     email: smtp                # admin reset / verification-code mail
//     otp_ttl_seconds: 180
//     otp_max_attempts: 5
'use strict';

var fs = require('fs');
var path = require('path');
var MARKER = '// Generated by scaffold-auth-ext';

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--spec') out.spec = argv[++i];
    else if (a === '--target') out.target = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.spec || !out.target) { console.error('Usage: scaffold-auth-ext --spec MODULE_PLAN.yaml --target BACKEND_DIR'); process.exit(1); }
  return out;
}
function loadYaml() {
  try { return require('yaml'); } catch (_) {}
  try { return require(path.join(require('child_process').execSync('npm root -g', { encoding: 'utf-8' }).trim(), 'yaml')); } catch (_) { return null; }
}

function fileKakaoVerifier() {
  return [
    MARKER,
    "// Verify a Kakao access token (from the native SDK via the webview token bridge):",
    "// call Kakao's userinfo endpoint; a 200 with an id proves the token is valid.",
    "import { Injectable, UnauthorizedException } from '@nestjs/common';",
    '',
    "export interface SocialIdentity { provider: 'KAKAO' | 'APPLE'; providerId: string; email?: string; nickname?: string; }",
    '',
    "@Injectable()",
    "export class KakaoVerifier {",
    "  async verify(accessToken: string): Promise<SocialIdentity> {",
    "    const res = await fetch('https://kapi.kakao.com/v2/user/me', { headers: { Authorization: 'Bearer ' + accessToken } });",
    "    if (!res.ok) throw new UnauthorizedException('invalid kakao token');",
    "    const j: any = await res.json();",
    "    if (!j?.id) throw new UnauthorizedException('invalid kakao token');",
    "    const acc = j.kakao_account || {};",
    "    return { provider: 'KAKAO', providerId: String(j.id), email: acc.email, nickname: acc.profile?.nickname };",
    "  }",
    "}",
    '',
  ].join('\n');
}

function fileAppleVerifier() {
  return [
    MARKER,
    "// Verify an Apple identity token (JWT) against Apple's public JWKS. Validates",
    "// signature + issuer + audience(APPLE_CLIENT_ID), returns the stable `sub`.",
    "import { Injectable, UnauthorizedException } from '@nestjs/common';",
    "import * as jwt from 'jsonwebtoken';",
    "import * as jwksClient from 'jwks-rsa';",
    "import type { SocialIdentity } from './kakao.verifier';",
    '',
    "@Injectable()",
    "export class AppleVerifier {",
    "  private readonly jwks = jwksClient({ jwksUri: 'https://appleid.apple.com/auth/keys', cache: true });",
    '',
    "  private getKey = (header: any, cb: (e: Error | null, key?: string) => void) => {",
    "    this.jwks.getSigningKey(header.kid, (err, key) => cb(err, key?.getPublicKey()));",
    "  };",
    '',
    "  async verify(identityToken: string): Promise<SocialIdentity> {",
    "    const payload: any = await new Promise((resolve, reject) => {",
    "      jwt.verify(identityToken, this.getKey, { issuer: 'https://appleid.apple.com', audience: process.env.APPLE_CLIENT_ID, algorithms: ['RS256'] }, (err, decoded) => (err ? reject(err) : resolve(decoded)));",
    "    }).catch(() => { throw new UnauthorizedException('invalid apple token'); });",
    "    if (!payload?.sub) throw new UnauthorizedException('invalid apple token');",
    "    return { provider: 'APPLE', providerId: String(payload.sub), email: payload.email };",
    "  }",
    "}",
    '',
  ].join('\n');
}

function fileSolapiClient() {
  return [
    MARKER,
    "// Solapi SMS adapter — HMAC-SHA256 signed REST send. Used for phone-verify + password",
    "// -reset OTP. send() throws on provider failure so the caller surfaces 'try again'.",
    "import { Injectable, Logger, BadRequestException } from '@nestjs/common';",
    "import * as crypto from 'crypto';",
    '',
    "@Injectable()",
    "export class SolapiClient {",
    "  private readonly logger = new Logger('SolapiClient');",
    '',
    "  private headers(): Record<string, string> {",
    "    const apiKey = process.env.SOLAPI_API_KEY, apiSecret = process.env.SOLAPI_API_SECRET;",
    "    if (!apiKey || !apiSecret) throw new Error('SOLAPI_API_KEY/SECRET required');",
    "    const date = new Date().toISOString();",
    "    const salt = crypto.randomBytes(32).toString('hex');",
    "    const signature = crypto.createHmac('sha256', apiSecret).update(date + salt).digest('hex');",
    "    return { Authorization: `HMAC-SHA256 apiKey=${apiKey}, date=${date}, salt=${salt}, signature=${signature}`, 'Content-Type': 'application/json' };",
    "  }",
    '',
    "  async send(to: string, text: string): Promise<void> {",
    "    const res = await fetch('https://api.solapi.com/messages/v4/send', {",
    "      method: 'POST', headers: this.headers(),",
    "      body: JSON.stringify({ message: { to, from: process.env.SOLAPI_SENDER, text } }),",
    "    });",
    "    if (!res.ok) {",
    "      const j = await res.json().catch(() => ({}));",
    "      this.logger.warn('solapi send failed: ' + res.status + ' ' + JSON.stringify(j));",
    "      throw new BadRequestException({ code: 'SMS_SEND_FAILED', message: 'could not send verification code, try again' });",
    "    }",
    "  }",
    "}",
    '',
  ].join('\n');
}

function fileSmtpClient() {
  return [
    MARKER,
    "// SMTP adapter via nodemailer (admin password-reset, email verification code).",
    "import { Injectable, Logger } from '@nestjs/common';",
    "import * as nodemailer from 'nodemailer';",
    '',
    "@Injectable()",
    "export class SmtpClient {",
    "  private readonly logger = new Logger('SmtpClient');",
    "  private transport = nodemailer.createTransport({",
    "    host: process.env.SMTP_HOST, port: Number(process.env.SMTP_PORT || 587),",
    "    auth: { user: process.env.SMTP_USER, pass: process.env.SMTP_PASS },",
    "  });",
    '',
    "  async send(to: string, subject: string, html: string): Promise<boolean> {",
    "    try {",
    "      await this.transport.sendMail({ from: process.env.SMTP_FROM, to, subject, html });",
    "      return true;",
    "    } catch (e) {",
    "      this.logger.warn('smtp send failed: ' + (e as Error).message);",
    "      return false;",
    "    }",
    "  }",
    "}",
    '',
  ].join('\n');
}

function fileOtpService(ttl, maxAttempts) {
  return [
    MARKER,
    "import { Injectable, BadRequestException } from '@nestjs/common';",
    "import * as crypto from 'crypto';",
    "import { SolapiClient } from '../../infrastructure/sms/solapi.client';",
    '',
    "const OTP_TTL_MS = " + ttl + " * 1000;",
    "const OTP_MAX_ATTEMPTS = " + maxAttempts + ";",
    '',
    "interface OtpEntry { codeHash: string; expiresAt: number; attempts: number; }",
    '',
    "// Phone OTP request/verify with TTL + attempt cap. v1 keeps state in-process (single",
    "// instance); move to Redis for multi-instance. Rate-limit per phone is the caller's job.",
    "@Injectable()",
    "export class OtpService {",
    "  private readonly store = new Map<string, OtpEntry>();",
    "  constructor(private readonly sms: SolapiClient) {}",
    '',
    "  private hash(code: string): string { return crypto.createHash('sha256').update(code).digest('hex'); }",
    '',
    "  async request(phone: string): Promise<void> {",
    "    const code = ('' + crypto.randomInt(0, 1_000_000)).padStart(6, '0');",
    "    this.store.set(phone, { codeHash: this.hash(code), expiresAt: Date.now() + OTP_TTL_MS, attempts: 0 });",
    "    await this.sms.send(phone, '[Verification] code: ' + code);",
    "  }",
    '',
    "  verify(phone: string, code: string): boolean {",
    "    const e = this.store.get(phone);",
    "    if (!e || Date.now() > e.expiresAt) throw new BadRequestException({ code: 'OTP_EXPIRED', message: 'code expired, request a new one' });",
    "    if (e.attempts >= OTP_MAX_ATTEMPTS) { this.store.delete(phone); throw new BadRequestException({ code: 'OTP_LOCKED', message: 'too many attempts' }); }",
    "    e.attempts += 1;",
    "    if (this.hash(code) !== e.codeHash) throw new BadRequestException({ code: 'OTP_INVALID', message: 'incorrect code' });",
    "    this.store.delete(phone);",
    "    return true;",
    "  }",
    "}",
    '',
  ].join('\n');
}

function fileAuthExtModule(opts) {
  var imports = [MARKER, "import { Module } from '@nestjs/common';"];
  var providers = [], exportsArr = [];
  if (opts.kakao) { imports.push("import { KakaoVerifier } from '../../infrastructure/auth/kakao.verifier';"); providers.push('KakaoVerifier'); exportsArr.push('KakaoVerifier'); }
  if (opts.apple) { imports.push("import { AppleVerifier } from '../../infrastructure/auth/apple.verifier';"); providers.push('AppleVerifier'); exportsArr.push('AppleVerifier'); }
  if (opts.sms) { imports.push("import { SolapiClient } from '../../infrastructure/sms/solapi.client';"); imports.push("import { OtpService } from './otp.service';"); providers.push('SolapiClient', 'OtpService'); exportsArr.push('OtpService'); }
  if (opts.email) { imports.push("import { SmtpClient } from '../../infrastructure/mail/smtp.client';"); providers.push('SmtpClient'); exportsArr.push('SmtpClient'); }
  imports.push('');
  imports.push("@Module({");
  imports.push("  providers: [" + providers.join(', ') + "],");
  imports.push("  exports: [" + exportsArr.join(', ') + "],");
  imports.push("})");
  imports.push("export class AuthExtModule {}");
  imports.push('');
  return imports.join('\n');
}

function ensureDeps(target, opts, dryRun, verbose) {
  var pkgPath = path.join(target, 'package.json');
  if (!fs.existsSync(pkgPath)) return;
  var pkg; try { pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8')); } catch (_) { return; }
  pkg.dependencies = pkg.dependencies || {}; pkg.devDependencies = pkg.devDependencies || {};
  var deps = {}, devDeps = {};
  if (opts.apple) { deps['jsonwebtoken'] = '^9.0.0'; deps['jwks-rsa'] = '^3.1.0'; devDeps['@types/jsonwebtoken'] = '^9.0.0'; }
  if (opts.email) { deps['nodemailer'] = '^6.9.0'; devDeps['@types/nodemailer'] = '^6.4.0'; }
  var changed = false;
  Object.keys(deps).forEach(function (d) { if (!pkg.dependencies[d] && !pkg.devDependencies[d]) { pkg.dependencies[d] = deps[d]; changed = true; } });
  Object.keys(devDeps).forEach(function (d) { if (!pkg.dependencies[d] && !pkg.devDependencies[d]) { pkg.devDependencies[d] = devDeps[d]; changed = true; } });
  if (changed && !dryRun) fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
  if (changed && verbose) console.log('  added auth-ext deps to package.json');
}

function writeFile(target, rel, content, args) {
  var full = path.join(target, rel);
  if (fs.existsSync(full) && !args.force) {
    var cur = fs.readFileSync(full, 'utf-8');
    if (cur.indexOf(MARKER) === -1) { if (args.verbose) console.log('  skip (hand-authored): ' + rel); return false; }
  }
  if (args.dryRun) { if (args.verbose) console.log('  [dry] ' + rel); return true; }
  var dir = path.dirname(full);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(full, content);
  return true;
}

function main() {
  var args = parseArgs(process.argv);
  if (!fs.existsSync(args.spec)) { console.log('scaffold-auth-ext: no MODULE_PLAN — skipping'); return; }
  var yaml = loadYaml();
  if (!yaml) { console.log('scaffold-auth-ext: yaml unavailable — skipping'); return; }
  var spec; try { spec = yaml.parse(fs.readFileSync(args.spec, 'utf-8')); } catch (e) { console.log('scaffold-auth-ext: bad YAML — skipping'); return; }
  var ax = spec && spec.auth_ext;
  if (!ax) { console.log('scaffold-auth-ext: no `auth_ext:` — skipping'); return; }

  var social = Array.isArray(ax.social) ? ax.social.map(function (s) { return String(s).toLowerCase(); }) : [];
  var opts = {
    kakao: social.indexOf('kakao') >= 0,
    apple: social.indexOf('apple') >= 0,
    sms: !!ax.sms_otp,
    email: !!ax.email,
  };
  var ttl = Number(ax.otp_ttl_seconds) || 180;
  var maxAttempts = Number(ax.otp_max_attempts) || 5;

  console.log('scaffold-auth-ext: ' + ['kakao', 'apple', 'sms', 'email'].filter(function (k) { return opts[k]; }).join('+'));
  ensureDeps(args.target, opts, args.dryRun, args.verbose);
  var files = [];
  if (opts.kakao) files.push(['src/infrastructure/auth/kakao.verifier.ts', fileKakaoVerifier()]);
  if (opts.apple) files.push(['src/infrastructure/auth/apple.verifier.ts', fileAppleVerifier()]);
  if (opts.sms) { files.push(['src/infrastructure/sms/solapi.client.ts', fileSolapiClient()]); files.push(['src/modules/auth-ext/otp.service.ts', fileOtpService(ttl, maxAttempts)]); }
  if (opts.email) files.push(['src/infrastructure/mail/smtp.client.ts', fileSmtpClient()]);
  files.push(['src/modules/auth-ext/auth-ext.module.ts', fileAuthExtModule(opts)]);
  var n = 0;
  files.forEach(function (f) { if (writeFile(args.target, f[0], f[1], args)) n++; });
  console.log('scaffold-auth-ext: ' + n + ' file(s) ' + (args.dryRun ? '(dry)' : 'written') + '. Register AuthExtModule; wire verifiers/OtpService into the signup/login flow.');
}

main();
