#!/usr/bin/env node
// scaffold-husky-precommit.js — v78 ship .husky/pre-commit + .lintstagedrc
// at project root + register husky/lint-staged in root package.json (or
// frontend/package.json if no root package.json exists).
//
// Hook runs lint-staged which: typechecks staged TS files, prettier
// formats JSON/MD, eslint --fix on JS/TS. Each subproject already has
// its own typecheck via `npm run check` — we delegate.
//
// Idempotent. Marker: shebang line + a comment in hook file.
'use strict';

var fs = require('fs');
var path = require('path');

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--target') out.target = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--dry-run') out.dryRun = true;
  }
  if (!out.target) { console.error('Usage: scaffold-husky-precommit --target PROJECT_ROOT'); process.exit(1); }
  return out;
}

function writeIfManaged(file, content, force, dryRun, markerRe) {
  if (fs.existsSync(file)) {
    var existing = fs.readFileSync(file, 'utf-8');
    if (!markerRe.test(existing) && !force) return { written: false, reason: 'exists-handauthored' };
    if (existing === content) return { written: false, reason: 'unchanged' };
  }
  if (dryRun) return { written: false, reason: 'dry-run' };
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  try { fs.chmodSync(file, 0o755); } catch (_) {}
  return { written: true };
}

var PRE_COMMIT = [
  '#!/usr/bin/env sh',
  '# Generated by scaffold-husky-precommit — DO NOT EDIT BY HAND. Re-run to refresh.',
  '. "$(dirname -- "$0")/_/husky.sh"',
  '',
  'npx lint-staged',
  '',
].join('\n');

var LINTSTAGED = JSON.stringify({
  "_marker": "Generated by scaffold-husky-precommit — DO NOT EDIT BY HAND.",
  "*.{ts,tsx}": ["prettier --write"],
  "*.{js,jsx}": ["prettier --write"],
  "*.{json,md,yml,yaml}": ["prettier --write"]
}, null, 2) + '\n';

function ensureRootPkg(target, dryRun) {
  var pkgPath = path.join(target, 'package.json');
  var pkg;
  if (fs.existsSync(pkgPath)) {
    try { pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8')); } catch (_) { return { changed: false, reason: 'parse-error' }; }
  } else {
    pkg = { name: 'workspace-root', private: true, version: '0.0.0' };
  }
  pkg.devDependencies = pkg.devDependencies || {};
  pkg.scripts = pkg.scripts || {};
  var added = [];
  ['husky', 'lint-staged', 'prettier'].forEach(function (dep) {
    if (!pkg.devDependencies[dep] && !(pkg.dependencies || {})[dep]) {
      var ver = dep === 'husky' ? '^9.0.0' : dep === 'lint-staged' ? '^15.0.0' : '^3.0.0';
      pkg.devDependencies[dep] = ver;
      added.push(dep);
    }
  });
  if (!pkg.scripts.prepare) pkg.scripts.prepare = 'husky';
  if (dryRun) return { changed: false, reason: 'dry-run', added: added };
  fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
  return { changed: true, added: added };
}

function main() {
  var args = parseArgs(process.argv);
  var rHook = writeIfManaged(path.join(args.target, '.husky/pre-commit'), PRE_COMMIT, args.force, args.dryRun, /Generated by scaffold-husky-precommit/);
  var rLint = writeIfManaged(path.join(args.target, '.lintstagedrc.json'), LINTSTAGED, args.force, args.dryRun, /Generated by scaffold-husky-precommit/);
  var rPkg = ensureRootPkg(args.target, args.dryRun);
  console.log('scaffold-husky-precommit: hook=' + (rHook.written ? 'wrote' : rHook.reason) + ' / lintstaged=' + (rLint.written ? 'wrote' : rLint.reason) + ' / deps=' + (rPkg.changed ? '+' + rPkg.added.join(',') : rPkg.reason));
}

main();
