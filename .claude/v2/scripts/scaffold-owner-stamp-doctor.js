#!/usr/bin/env node
// scaffold-owner-stamp-doctor.js — v128.
//
// PROBLEM (v127 evidence, live-reproduced): 50 `null value in column "<fk>" of
// relation "<table>" violates not-null constraint` failures across 11 e2e
// suites (worker_id ×3 tables, user_id, actor_id, created_by ×2, …). The
// owned-resource create endpoints inherit BaseController.create:
//     async create(@Body() dto) { return this.service.create(dto); }
// which persists the DTO verbatim. The owner FK (worker_id / user_id /
// actor_id / created_by) is NEVER supplied — the DTO either marks it optional,
// omits a validator (so class-validator ignores it), or doesn't declare it at
// all — so it inserts NULL and the NOT-NULL constraint 500s. A test that logs
// in and POSTs can't pass, AND it's a real app bug: the creator's identity must
// come from the JWT, not a client-supplied body field.
//
// FIX (deterministic, [[feedback_template_wins_llm]]): for every module whose
// entity has a NOT-NULL FK column whose NAME identifies the authenticated
// principal (worker_id, user_id, actor_id, owner_id, created_by, author_id,
// uploaded_by, requester_id, submitted_by — NOT parent FKs like application_id
// / company_id), inject a controller create() override that stamps that field
// from @CurrentUser('id') when the body didn't already set it (nullish — an
// admin POSTing an explicit recipient id is preserved).
//
// Scope guard: ONLY the principal-identifying FK names below are stamped.
// Parent/relation FKs (application_id, company_id, document_id, …) are a
// SEPARATE class (child-resource creates need the parent id from body/route +
// the test must seed a parent) and are intentionally left untouched here.
//
// Idempotent: skips any controller that already defines a create( override
// (hand-written or a prior run of this doctor — it writes a marker comment).
//
// Usage:
//   scaffold-owner-stamp-doctor --target <RUN_DIR> [--backend-dir backend] [--dry-run] [--verbose]
'use strict';

var fs = require('fs');
var path = require('path');

// Column names that mean "the authenticated user who performed this action".
// Conservative allowlist — parent/relation FKs are deliberately excluded.
var OWNER_FK_COLUMNS = [
  'user_id', 'worker_id', 'actor_id', 'owner_id',
  'created_by', 'created_by_id', 'author_id',
  'uploaded_by', 'uploaded_by_id', 'requester_id',
  'submitted_by', 'submitted_by_id',
];

var MARKER = '// Generated by scaffold-owner-stamp-doctor';

function parseArgs(argv) {
  var out = { backendDir: 'backend' };
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--target') out.target = argv[++i];
    else if (a === '--backend-dir') out.backendDir = argv[++i];
    else if (a === '--verbose' || a === '-v') out.verbose = true;
    else if (a === '--dry-run') out.dryRun = true;
  }
  if (!out.target) {
    console.error('Usage: scaffold-owner-stamp-doctor --target <RUN_DIR> [--backend-dir backend] [--dry-run] [--verbose]');
    process.exit(1);
  }
  return out;
}

function snakeToCamel(s) {
  return s.replace(/_([a-z])/g, function (_, c) { return c.toUpperCase(); });
}

// Find NOT-NULL owner FK columns declared in an entity file.
// A column is NOT NULL when its @Column({...}) options do NOT contain
// `nullable: true` and do NOT contain `default`.
function ownerFksInEntity(entitySrc) {
  var found = [];
  // Match @Column({ name: 'worker_id', ... })  and  @Column({ ... }) prop
  // We scan each @Column(...) decorator's option object + the following column.
  var colRe = /@Column\(\s*\{([^}]*)\}\s*\)/g;
  var m;
  while ((m = colRe.exec(entitySrc)) !== null) {
    var opts = m[1];
    var nameMatch = opts.match(/name:\s*['"]([a-z0-9_]+)['"]/);
    if (!nameMatch) continue;
    var col = nameMatch[1];
    if (OWNER_FK_COLUMNS.indexOf(col) === -1) continue;
    if (/nullable:\s*true/.test(opts)) continue;   // nullable → fine, skip
    if (/default:/.test(opts)) continue;            // has default → fine, skip
    if (found.indexOf(col) === -1) found.push(col);
  }
  return found;
}

function parseBaseControllerGenerics(ctrlSrc) {
  // extends BaseController<Entity, CreateDto, UpdateDto>
  var m = ctrlSrc.match(/extends\s+BaseController<\s*([A-Za-z0-9_]+)\s*,\s*([A-Za-z0-9_]+)\s*,\s*([A-Za-z0-9_]+)/);
  if (!m) return null;
  return { entity: m[1], createDto: m[2], updateDto: m[3] };
}

// Ensure a named import is present on the `@nestjs/common` import line.
function ensureCommonImports(src, names) {
  var re = /import\s*\{([^}]*)\}\s*from\s*['"]@nestjs\/common['"]\s*;/;
  var m = src.match(re);
  if (!m) {
    // no common import at all — add one
    return "import { " + names.join(', ') + " } from '@nestjs/common';\n" + src;
  }
  var existing = m[1].split(',').map(function (s) { return s.trim(); }).filter(Boolean);
  names.forEach(function (n) { if (existing.indexOf(n) === -1) existing.push(n); });
  return src.replace(re, 'import { ' + existing.join(', ') + " } from '@nestjs/common';");
}

function ensureCurrentUserImport(src) {
  if (/CurrentUser/.test(src) && /current-user\.decorator/.test(src)) return src;
  // insert after the @nestjs/common import (or at top)
  var imp = "import { CurrentUser } from '../../core/decorators/current-user.decorator';\n";
  var re = /import\s*\{[^}]*\}\s*from\s*['"]@nestjs\/common['"]\s*;\n/;
  if (re.test(src)) return src.replace(re, function (line) { return line + imp; });
  return imp + src;
}

function buildOverride(generics, ownerCols) {
  var lines = [];
  lines.push('');
  lines.push('  ' + MARKER + ' — stamp owner FK(s) from the authenticated user');
  lines.push('  @Post()');
  // __ownerId is `?` so the override stays assignable to BaseController.create
  // (base signature has a single param; an extra REQUIRED param trips TS2416).
  lines.push('  async create(@Body() createDto: ' + generics.createDto + ', @CurrentUser(\'id\') __ownerId?: string): Promise<' + generics.entity + '> {');
  lines.push('    const __dto: any = createDto;');
  ownerCols.forEach(function (col) {
    var prop = snakeToCamel(col);
    lines.push('    __dto.' + prop + ' = __dto.' + prop + ' ?? __ownerId;');
  });
  lines.push('    return this.service.create(__dto);');
  lines.push('  }');
  return lines.join('\n');
}

// Insert the override right after the constructor's closing brace.
function insertAfterConstructor(src, override) {
  // find `super(...)` then the next line that is just `}` (the ctor close)
  var idx = src.indexOf('super(');
  if (idx === -1) return null;
  var close = src.indexOf('}', idx);
  if (close === -1) return null;
  // advance to end of that line
  var nl = src.indexOf('\n', close);
  if (nl === -1) nl = close + 1;
  return src.slice(0, nl + 1) + override + '\n' + src.slice(nl + 1);
}

function main() {
  var args = parseArgs(process.argv);
  var modulesDir = path.join(args.target, args.backendDir, 'src', 'modules');
  if (!fs.existsSync(modulesDir)) {
    console.log('scaffold-owner-stamp-doctor: no backend/src/modules — nothing to do');
    return;
  }
  var stamped = 0, skipped = 0, modulesWith = 0;

  fs.readdirSync(modulesDir, { withFileTypes: true })
    .filter(function (e) { return e.isDirectory(); })
    .forEach(function (e) {
      var mod = e.name;
      var dir = path.join(modulesDir, mod);
      var entityFile = path.join(dir, mod + '.entity.ts');
      var ctrlFile = path.join(dir, mod + '.controller.ts');
      if (!fs.existsSync(entityFile) || !fs.existsSync(ctrlFile)) return;

      var entitySrc = fs.readFileSync(entityFile, 'utf-8');
      var ownerCols = ownerFksInEntity(entitySrc);
      if (ownerCols.length === 0) return;
      modulesWith++;

      var ctrlSrc = fs.readFileSync(ctrlFile, 'utf-8');
      if (ctrlSrc.indexOf(MARKER) !== -1 || /async\s+create\s*\(/.test(ctrlSrc) || /\bcreate\s*\(\s*@Body/.test(ctrlSrc)) {
        skipped++;
        if (args.verbose) console.log('  skip (already has create override): ' + mod + ' [' + ownerCols.join(',') + ']');
        return;
      }
      var generics = parseBaseControllerGenerics(ctrlSrc);
      if (!generics) {
        skipped++;
        if (args.verbose) console.log('  skip (not a BaseController<E,C,U>): ' + mod);
        return;
      }

      var override = buildOverride(generics, ownerCols);
      var next = ensureCommonImports(ctrlSrc, ['Post', 'Body']);
      next = ensureCurrentUserImport(next);
      next = insertAfterConstructor(next, override);
      if (!next) {
        skipped++;
        if (args.verbose) console.log('  skip (no constructor anchor): ' + mod);
        return;
      }
      stamped++;
      console.log('  stamped ' + mod + ' create() ← ' + ownerCols.map(snakeToCamel).join(', ') + (args.dryRun ? ' (dry-run)' : ''));
      if (!args.dryRun) fs.writeFileSync(ctrlFile, next);
    });

  console.log('scaffold-owner-stamp-doctor: ' + stamped + ' stamped, ' + skipped + ' skipped (of ' + modulesWith + ' modules with owner FKs)' + (args.dryRun ? ' (dry-run)' : ''));
}

main();
