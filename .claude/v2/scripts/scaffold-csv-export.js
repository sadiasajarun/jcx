#!/usr/bin/env node
// scaffold-csv-export.js — CSV-EXPORT capability primitive (Tier 2, NestJS).
//
// Admin "export to CSV/Excel" (settlement ledger, user list, payments). RFC-4180 escaping
// is the deterministic grammar people get wrong (commas/quotes/newlines in cell values,
// BOM for Excel + Korean). Emits a reusable CsvExportService + a controller helper.
//
// MODULE_PLAN.yaml shape:
//   exports:
//     - { name: settlement, route: /admin/settlement/export, columns: [bookingId, instructorName, amount, status] }
'use strict';

var fs = require('fs');
var path = require('path');
var MARKER = '// Generated by scaffold-csv-export';

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--spec') out.spec = argv[++i];
    else if (a === '--target') out.target = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.spec || !out.target) { console.error('Usage: scaffold-csv-export --spec MODULE_PLAN.yaml --target BACKEND_DIR'); process.exit(1); }
  return out;
}
function loadYaml() {
  try { return require('yaml'); } catch (_) {}
  try { return require(path.join(require('child_process').execSync('npm root -g', { encoding: 'utf-8' }).trim(), 'yaml')); } catch (_) { return null; }
}

function fileCsvService() {
  return [
    MARKER,
    "import { Injectable, StreamableFile } from '@nestjs/common';",
    '',
    "// RFC-4180 CSV with a UTF-8 BOM so Excel renders Korean/multibyte correctly.",
    "@Injectable()",
    "export class CsvExportService {",
    "  private cell(v: unknown): string {",
    "    const s = v == null ? '' : String(v);",
    "    return /[\",\\n\\r]/.test(s) ? '\"' + s.replace(/\"/g, '\"\"') + '\"' : s;",
    "  }",
    '',
    "  toCsv(rows: Record<string, unknown>[], columns?: string[]): string {",
    "    const cols = columns && columns.length ? columns : (rows[0] ? Object.keys(rows[0]) : []);",
    "    const head = cols.map((c) => this.cell(c)).join(',');",
    "    const body = rows.map((r) => cols.map((c) => this.cell(r[c])).join(',')).join('\\r\\n');",
    "    return '\\uFEFF' + head + (body ? '\\r\\n' + body : '');",
    "  }",
    '',
    "  // Build a downloadable file response. Set the controller's @Header or res headers:",
    "  //   Content-Type: text/csv; charset=utf-8",
    "  //   Content-Disposition: attachment; filename=\"<name>.csv\"",
    "  toFile(rows: Record<string, unknown>[], columns?: string[]): StreamableFile {",
    "    return new StreamableFile(Buffer.from(this.toCsv(rows, columns), 'utf-8'));",
    "  }",
    "}",
    '',
  ].join('\n');
}

function fileCsvModule() {
  return [
    MARKER,
    "import { Module } from '@nestjs/common';",
    "import { CsvExportService } from './csv-export.service';",
    '',
    "@Module({",
    "  providers: [CsvExportService],",
    "  exports: [CsvExportService],",
    "})",
    "export class CsvExportModule {}",
    '',
  ].join('\n');
}

function writeFile(target, rel, content, args) {
  var full = path.join(target, rel);
  if (fs.existsSync(full) && !args.force) {
    var cur = fs.readFileSync(full, 'utf-8');
    if (cur.indexOf(MARKER) === -1) { if (args.verbose) console.log('  skip (hand-authored): ' + rel); return false; }
  }
  if (args.dryRun) { if (args.verbose) console.log('  [dry] ' + rel); return true; }
  var dir = path.dirname(full);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(full, content);
  return true;
}

function main() {
  var args = parseArgs(process.argv);
  if (!fs.existsSync(args.spec)) { console.log('scaffold-csv-export: no MODULE_PLAN — skipping'); return; }
  var yaml = loadYaml();
  if (!yaml) { console.log('scaffold-csv-export: yaml unavailable — skipping'); return; }
  var spec; try { spec = yaml.parse(fs.readFileSync(args.spec, 'utf-8')); } catch (e) { console.log('scaffold-csv-export: bad YAML — skipping'); return; }
  var exp = spec && Array.isArray(spec.exports) ? spec.exports : null;
  if (!exp || exp.length === 0) { console.log('scaffold-csv-export: no `exports:` — skipping'); return; }

  console.log('scaffold-csv-export: CsvExportService for ' + exp.length + ' declared export(s)');
  var n = 0;
  [
    ['src/infrastructure/export/csv-export.service.ts', fileCsvService()],
    ['src/infrastructure/export/csv-export.module.ts', fileCsvModule()],
  ].forEach(function (f) { if (writeFile(args.target, f[0], f[1], args)) n++; });
  console.log('scaffold-csv-export: ' + n + ' file(s) ' + (args.dryRun ? '(dry)' : 'written') + '. Import CsvExportModule; in admin controllers return csv.toFile(rows, columns).');
}

main();
