#!/usr/bin/env node
// scaffold-cron-jobs.js — SCHEDULED-JOBS capability primitive (Tier 2, NestJS/TypeORM).
//
// Two job kinds, both deterministic grammar the LLM gets wrong:
//   - RECURRING (@nestjs/schedule @Cron) — cleanup/batch jobs on a cron expression.
//   - DELAYED   (BullMQ delayed job)      — per-entity timers (e.g. "expire this booking
//                                            in 24h", "auto-confirm in 72h"), enqueued
//                                            when the entity is created.
// The scheduling/queue wiring + idempotency-guard shape is emitted deterministically;
// each job BODY is a seam the LLM fills with the project's transition logic.
//
// MODULE_PLAN.yaml shape:
//   cron:
//     - { name: expire-bookings,   type: delayed, delay_seconds: 86400 }   # 24h
//     - { name: auto-confirm,      type: delayed, delay_seconds: 259200 }  # 72h
//     - { name: quiet-hours-batch, type: cron,    schedule: "0 8 * * *" }
//     - { name: slot-lock-cleanup, type: cron,    schedule: "0 * * * *" }
'use strict';

var fs = require('fs');
var path = require('path');

var MARKER = '// Generated by scaffold-cron-jobs';

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--spec') out.spec = argv[++i];
    else if (a === '--target') out.target = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.spec || !out.target) { console.error('Usage: scaffold-cron-jobs --spec MODULE_PLAN.yaml --target BACKEND_DIR'); process.exit(1); }
  return out;
}
function loadYaml() {
  try { return require('yaml'); } catch (_) {}
  try { return require(path.join(require('child_process').execSync('npm root -g', { encoding: 'utf-8' }).trim(), 'yaml')); } catch (_) { return null; }
}
function toPascal(s) { return String(s).split(/[-_\s]+/).filter(Boolean).map(function (w) { return w[0].toUpperCase() + w.slice(1); }).join(''); }
function toKebab(s) { return String(s).replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/[_\s]+/g, '-').toLowerCase(); }
function toCamel(s) { var p = toPascal(s); return p[0].toLowerCase() + p.slice(1); }

function fileCronService(cronJobs) {
  var L = [MARKER];
  L.push("import { Injectable, Logger } from '@nestjs/common';");
  L.push("import { Cron } from '@nestjs/schedule';");
  L.push('');
  L.push("// RECURRING jobs. Each method is idempotent — re-running must be safe (use");
  L.push("// conditional UPDATE/DELETE, not blind mutation). TZ is process TZ (set TZ=Asia/Seoul).");
  L.push("@Injectable()");
  L.push("export class CronService {");
  L.push("  private readonly logger = new Logger('CronService');");
  for (var i = 0; i < cronJobs.length; i++) {
    var j = cronJobs[i];
    L.push('');
    L.push("  @Cron('" + j.schedule + "')");
    L.push("  async " + toCamel(j.name) + "(): Promise<void> {");
    L.push("    this.logger.log('cron " + j.name + " tick');");
    L.push("    // IDEMPOTENT job body — implement the " + j.name + " logic here (conditional");
    L.push("    // UPDATE/DELETE so a duplicate tick is a no-op). e.g. delete-where-expired.");
    L.push("  }");
  }
  L.push("}");
  L.push('');
  return L.join('\n');
}

function fileProcessor(j) {
  var Pascal = toPascal(j.name);
  var kebab = toKebab(j.name);
  var delay = Number(j.delay_seconds) || 0;
  return [
    MARKER,
    "import { Processor, WorkerHost } from '@nestjs/bullmq';",
    "import { Injectable, Logger } from '@nestjs/common';",
    "import { InjectQueue } from '@nestjs/bullmq';",
    "import { Queue, Job } from 'bullmq';",
    '',
    "export const " + kebab.toUpperCase().replace(/-/g, '_') + "_QUEUE = '" + kebab + "';",
    "export const " + Pascal + "_DELAY_MS = " + delay + " * 1000;",
    '',
    "// DELAYED per-entity timer. Enqueue when the source entity is created:",
    "//   await this." + toCamel(j.name) + ".enqueue(entityId);",
    "// The worker runs once after the delay. Idempotency: guard on the entity's current",
    "// state (a conditional UPDATE that affects 0 rows = already handled → no-op).",
    "@Injectable()",
    "export class " + Pascal + "Enqueuer {",
    "  constructor(@InjectQueue(" + kebab.toUpperCase().replace(/-/g, '_') + "_QUEUE) private readonly queue: Queue) {}",
    "  async enqueue(entityId: string): Promise<void> {",
    "    await this.queue.add('" + kebab + "', { entityId }, { delay: " + Pascal + "_DELAY_MS, jobId: '" + kebab + ":' + entityId, removeOnComplete: true });",
    "  }",
    "}",
    '',
    "@Processor(" + kebab.toUpperCase().replace(/-/g, '_') + "_QUEUE)",
    "export class " + Pascal + "Processor extends WorkerHost {",
    "  private readonly logger = new Logger('" + Pascal + "Processor');",
    "  async process(job: Job<{ entityId: string }>): Promise<void> {",
    "    this.logger.log('" + kebab + " fired for ' + job.data.entityId);",
    "    // IDEMPOTENT: apply the timed transition for job.data.entityId via a conditional",
    "    // UPDATE (0 rows affected → already transitioned, skip side effects).",
    "  }",
    "}",
    '',
  ].join('\n');
}

function fileJobsModule(cronJobs, delayedJobs) {
  var L = [MARKER];
  L.push("import { Module } from '@nestjs/common';");
  L.push("import { ScheduleModule } from '@nestjs/schedule';");
  L.push("import { BullModule } from '@nestjs/bullmq';");
  if (cronJobs.length) L.push("import { CronService } from './cron.service';");
  var providers = cronJobs.length ? ['CronService'] : [];
  var imports = [];
  for (var i = 0; i < delayedJobs.length; i++) {
    var j = delayedJobs[i];
    var Pascal = toPascal(j.name);
    var kebab = toKebab(j.name);
    var QUEUE = kebab.toUpperCase().replace(/-/g, '_') + '_QUEUE';
    L.push("import { " + Pascal + "Processor, " + Pascal + "Enqueuer, " + QUEUE + " } from './" + kebab + ".processor';");
    providers.push(Pascal + 'Processor', Pascal + 'Enqueuer');
    imports.push("    BullModule.registerQueue({ name: " + QUEUE + " }),");
  }
  L.push('');
  L.push("// Redis connection for BullMQ (delayed jobs). REDIS_URL or host/port env.");
  L.push("@Module({");
  L.push("  imports: [");
  L.push("    ScheduleModule.forRoot(),");
  if (delayedJobs.length) {
    L.push("    BullModule.forRoot({ connection: { url: process.env.REDIS_URL || 'redis://localhost:6379' } }),");
    imports.forEach(function (s) { L.push(s); });
  }
  L.push("  ],");
  L.push("  providers: [" + providers.join(', ') + "],");
  L.push("  exports: [" + providers.filter(function (p) { return /Enqueuer$/.test(p); }).join(', ') + "],");
  L.push("})");
  L.push("export class JobsModule {}");
  L.push('');
  return L.join('\n');
}

function ensureDeps(target, dryRun, verbose) {
  var pkgPath = path.join(target, 'package.json');
  if (!fs.existsSync(pkgPath)) return;
  var pkg; try { pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8')); } catch (_) { return; }
  pkg.dependencies = pkg.dependencies || {};
  var deps = { '@nestjs/schedule': '^4.0.0', '@nestjs/bullmq': '^10.0.0', 'bullmq': '^5.0.0' };
  var changed = false;
  Object.keys(deps).forEach(function (d) { if (!pkg.dependencies[d]) { pkg.dependencies[d] = deps[d]; changed = true; } });
  if (changed && !dryRun) fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
  if (changed && verbose) console.log('  added @nestjs/schedule + bullmq deps to package.json');
}

function writeFile(target, rel, content, args) {
  var full = path.join(target, rel);
  if (fs.existsSync(full) && !args.force) {
    var cur = fs.readFileSync(full, 'utf-8');
    if (cur.indexOf(MARKER) === -1) { if (args.verbose) console.log('  skip (hand-authored): ' + rel); return false; }
  }
  if (args.dryRun) { if (args.verbose) console.log('  [dry] ' + rel); return true; }
  var dir = path.dirname(full);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(full, content);
  return true;
}

function main() {
  var args = parseArgs(process.argv);
  if (!fs.existsSync(args.spec)) { console.log('scaffold-cron-jobs: no MODULE_PLAN — skipping'); return; }
  var yaml = loadYaml();
  if (!yaml) { console.log('scaffold-cron-jobs: yaml unavailable — skipping'); return; }
  var spec; try { spec = yaml.parse(fs.readFileSync(args.spec, 'utf-8')); } catch (e) { console.log('scaffold-cron-jobs: bad YAML — skipping'); return; }
  var list = spec && Array.isArray(spec.cron) ? spec.cron.filter(function (j) { return j && j.name; }) : [];
  if (list.length === 0) { console.log('scaffold-cron-jobs: no `cron:` entries — skipping'); return; }

  var cronJobs = list.filter(function (j) { return (j.type || 'cron') === 'cron' && j.schedule; });
  var delayedJobs = list.filter(function (j) { return j.type === 'delayed'; });
  console.log('scaffold-cron-jobs: ' + cronJobs.length + ' recurring + ' + delayedJobs.length + ' delayed job(s)');
  ensureDeps(args.target, args.dryRun, args.verbose);
  var n = 0;
  if (cronJobs.length) { if (writeFile(args.target, 'src/modules/jobs/cron.service.ts', fileCronService(cronJobs), args)) n++; }
  for (var i = 0; i < delayedJobs.length; i++) {
    if (writeFile(args.target, 'src/modules/jobs/' + toKebab(delayedJobs[i].name) + '.processor.ts', fileProcessor(delayedJobs[i]), args)) n++;
  }
  if (writeFile(args.target, 'src/modules/jobs/jobs.module.ts', fileJobsModule(cronJobs, delayedJobs), args)) n++;
  console.log('scaffold-cron-jobs: ' + n + ' file(s) ' + (args.dryRun ? '(dry)' : 'written') + '. Register JobsModule in AppModule. Set TZ + REDIS_URL.');
}

main();
