#!/usr/bin/env node
// scaffold-store-tests.js — v74 emits Vitest tests for each Redux slice
// under app/redux/features/. Tests assert the reducer correctly handles
// initial state + the three thunk lifecycle actions (pending / fulfilled
// / rejected) for the slice's exported thunks.
'use strict';

var fs = require('fs');
var path = require('path');

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--target') out.target = argv[++i];
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.target) { console.error('Usage: scaffold-store-tests --target FRONTEND_DIR'); process.exit(1); }
  return out;
}

function detectSliceName(content) {
  var m = /createSlice\(\s*\{\s*name:\s*['"]([^'"]+)['"]/.exec(content);
  return m ? m[1] : null;
}

function detectExtraReducerThunks(content) {
  // Match `.addCase(fetchXxx.pending, ...)` patterns
  var thunks = new Set();
  var re = /\.addCase\(\s*(\w+)\.(pending|fulfilled|rejected)/g;
  var m;
  while ((m = re.exec(content)) !== null) thunks.add(m[1]);
  return Array.from(thunks);
}

// v89: discover REAL exports from the service file. Slice references like
// `addCase(loginThunk.pending)` may use names the service doesn't actually
// export (LLM vocab drift). Importing non-existent names → TS2305 →
// frontend typecheck fails. Solution: only import what's actually exported.
function discoverServiceExports(serviceFilePath) {
  if (!fs.existsSync(serviceFilePath)) return new Set();
  try {
    var content = fs.readFileSync(serviceFilePath, 'utf-8');
    var exports = new Set();
    // Match `export const X = ...` and `export { X, Y }`
    var re1 = /export\s+const\s+(\w+)\s*=/g;
    var re2 = /export\s*\{\s*([^}]+)\s*\}/g;
    var m;
    while ((m = re1.exec(content)) !== null) exports.add(m[1]);
    while ((m = re2.exec(content)) !== null) {
      m[1].split(',').forEach(function (n) {
        var name = n.trim().replace(/\s+as\s+\w+/, '');
        if (name) exports.add(name);
      });
    }
    return exports;
  } catch (_) { return new Set(); }
}

function renderSliceTest(sliceFile, target) {
  var content = fs.readFileSync(sliceFile, 'utf-8');
  var sliceName = detectSliceName(content);
  if (!sliceName) return null;
  var sliceThunks = detectExtraReducerThunks(content);
  var base = path.basename(sliceFile, '.ts');
  var importRel = '~/redux/features/' + base;
  var servicePathRel = importRel.replace('/redux/features/', '/services/httpServices/').replace(/Slice$/, 'Service');
  var serviceFilePath = path.join(target, 'app/services/httpServices', base.replace(/Slice$/, 'Service') + '.ts');

  // v89: only import thunks that the service ACTUALLY exports. Slice's
  // .addCase() references can drift from the real export names.
  var serviceExports = discoverServiceExports(serviceFilePath);
  var importableThunks = sliceThunks.filter(function (t) { return serviceExports.has(t); });

  var lines = [
    "/** Generated by scaffold-store-tests for " + base + " */",
    "import { describe, expect, it } from 'vitest';",
    "import reducer from '" + importRel + "';",
  ];
  if (importableThunks.length) {
    lines.push("import { " + importableThunks.join(', ') + " } from '" + servicePathRel + "';");
  }
  lines.push('');
  lines.push("describe('" + sliceName + " slice', () => {");
  lines.push("  it('returns initial state on @@INIT', () => {");
  lines.push("    const state = reducer(undefined, { type: '@@INIT' });");
  lines.push("    expect(state).toBeDefined();");
  lines.push("  });");

  // v89: emit test cases for ALL slice thunks, but use LITERAL action-type
  // strings instead of `<thunk>.pending`/`<thunk>.rejected` references. This
  // sidesteps the missing-import problem AND covers thunks the slice expects
  // even when the service doesn't export them yet (test will fail at runtime
  // — surfacing the contract break instead of hiding it via typecheck error).
  sliceThunks.forEach(function (thunk) {
    var actionBase = thunk.replace(/Thunk$/, '');
    lines.push('');
    lines.push("  it('handles " + thunk + "/pending action', () => {");
    lines.push("    const state = reducer(undefined, { type: '" + sliceName + "/" + actionBase + "/pending' });");
    lines.push("    expect(state).toBeDefined();");
    lines.push("  });");
    lines.push('');
    lines.push("  it('handles " + thunk + "/rejected action', () => {");
    lines.push("    const state = reducer(undefined, { type: '" + sliceName + "/" + actionBase + "/rejected', error: { message: 'fail' } });");
    lines.push("    expect(state).toBeDefined();");
    lines.push("  });");
  });

  lines.push('});');
  return lines.join('\n');
}

function main() {
  var args = parseArgs(process.argv);
  var slicesDir = path.join(args.target, 'app/redux/features');
  if (!fs.existsSync(slicesDir)) {
    console.log('scaffold-store-tests: no slices dir — skipping');
    return;
  }
  var entries = fs.readdirSync(slicesDir, { withFileTypes: true });
  var written = 0;
  for (var i = 0; i < entries.length; i++) {
    var e = entries[i];
    if (!e.isFile() || !/Slice\.ts$/.test(e.name)) continue;
    var src = path.join(slicesDir, e.name);
    var rendered = renderSliceTest(src, args.target);
    if (!rendered) continue;
    var testName = e.name.replace(/\.ts$/, '.test.ts');
    var dst = path.join(args.target, 'tests/stores', testName);
    if (fs.existsSync(dst)) continue;
    if (args.dryRun) {
      console.log('  [dry] would write ' + path.relative(args.target, dst));
    } else {
      fs.mkdirSync(path.dirname(dst), { recursive: true });
      fs.writeFileSync(dst, rendered);
    }
    written++;
  }
  console.log('scaffold-store-tests: wrote ' + written + ' slice tests');
}

main();
