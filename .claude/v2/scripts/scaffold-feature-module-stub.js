#!/usr/bin/env node
// scaffold-feature-module-stub.js — v89
//
// Generate missing `<name>.module.ts` files for any module dir that has
// entity+service+controller (or any combination) but no module file.
//
// v88 evidence: 10 module dirs (notification, notice, faq, application-document,
// verification-code, refresh-token, password-reset-token, etc.) had entities +
// services + repositories but no .module.ts file. Their entities never reached
// TypeOrmModule.forFeature() so DI on them throws at runtime.
//
// STRATEGY:
//   - Walk backend/src/modules/<dir>
//   - For each dir that lacks <dir>.module.ts:
//     - Scan dir for *.entity.ts (TypeOrmModule.forFeature targets)
//     - Scan dir for *.controller.ts (controllers array)
//     - Scan dir for *.service.ts (providers array)
//     - Scan dir for *.repository.ts (providers array)
//     - Emit a minimal NestJS module that wires these
//
// Idempotent — only writes if file doesn't exist.
'use strict';

var fs = require('fs');
var path = require('path');

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--target') out.target = argv[++i];
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.target) {
    console.error('Usage: scaffold-feature-module-stub --target <BACKEND_DIR>');
    process.exit(1);
  }
  return out;
}

function kebabToPascal(s) {
  return s.split('-').map(function (p) { return p.charAt(0).toUpperCase() + p.slice(1); }).join('');
}

function findFilesInDir(dir, suffix) {
  return fs.readdirSync(dir).filter(function (f) { return f.endsWith(suffix); });
}

function extractClassNames(filePath) {
  var content = fs.readFileSync(filePath, 'utf-8');
  var classes = [];
  var re = /export\s+class\s+(\w+)/g;
  var m;
  while ((m = re.exec(content)) !== null) classes.push(m[1]);
  return classes;
}

function renderModule(moduleName, moduleDir) {
  var pascalBase = kebabToPascal(moduleName);
  var className = pascalBase + 'Module';

  var imports = ["import { Module } from '@nestjs/common';"];
  var typeOrmEntities = [];
  var controllers = [];
  var providers = [];

  // Entities
  findFilesInDir(moduleDir, '.entity.ts').forEach(function (f) {
    var classNames = extractClassNames(path.join(moduleDir, f));
    classNames.forEach(function (cn) {
      typeOrmEntities.push(cn);
      imports.push("import { " + cn + " } from './" + f.replace('.ts', '') + "';");
    });
  });
  // Controllers
  findFilesInDir(moduleDir, '.controller.ts').forEach(function (f) {
    var classNames = extractClassNames(path.join(moduleDir, f));
    classNames.forEach(function (cn) {
      controllers.push(cn);
      imports.push("import { " + cn + " } from './" + f.replace('.ts', '') + "';");
    });
  });
  // Services + Repositories (providers)
  ['.service.ts', '.repository.ts'].forEach(function (suffix) {
    findFilesInDir(moduleDir, suffix).forEach(function (f) {
      var classNames = extractClassNames(path.join(moduleDir, f));
      classNames.forEach(function (cn) {
        providers.push(cn);
        imports.push("import { " + cn + " } from './" + f.replace('.ts', '') + "';");
      });
    });
  });

  if (typeOrmEntities.length > 0) {
    imports.push("import { TypeOrmModule } from '@nestjs/typeorm';");
  }

  var lines = ['// Generated by scaffold-feature-module-stub'];
  lines = lines.concat(imports);
  lines.push('');
  lines.push('@Module({');
  if (typeOrmEntities.length > 0) {
    lines.push('  imports: [TypeOrmModule.forFeature([' + typeOrmEntities.join(', ') + '])],');
  }
  if (controllers.length > 0) {
    lines.push('  controllers: [' + controllers.join(', ') + '],');
  }
  if (providers.length > 0) {
    lines.push('  providers: [' + providers.join(', ') + '],');
    // Export services AND repositories so other modules (workflows, satellite
    // controllers, schedulers) can inject them via @Inject without having to
    // re-register the entity. v92 evidence: AffiliationRequestWorkflowModule
    // imported AffiliationRequestModule expecting to get the Repository, but
    // exports only listed the Service → DI failed → backend wouldn't boot.
    var services = providers.filter(function (p) { return /Service$/.test(p); });
    var repositories = providers.filter(function (p) { return /Repository$/.test(p); });
    var exported = services.concat(repositories);
    if (exported.length > 0) {
      lines.push('  exports: [' + exported.join(', ') + '],');
    }
  }
  lines.push('})');
  lines.push('export class ' + className + ' {}');
  lines.push('');
  return lines.join('\n');
}

function main() {
  var args = parseArgs(process.argv);
  var modulesDir = path.join(args.target, 'src/modules');
  if (!fs.existsSync(modulesDir)) {
    console.log('scaffold-feature-module-stub: no src/modules — skipping');
    return;
  }
  var entries = fs.readdirSync(modulesDir, { withFileTypes: true });
  var written = 0, skipped = 0;
  entries.forEach(function (e) {
    if (!e.isDirectory()) return;
    var moduleName = e.name;
    var moduleDir = path.join(modulesDir, moduleName);
    var modulePath = path.join(moduleDir, moduleName + '.module.ts');
    if (fs.existsSync(modulePath)) { skipped++; return; }
    // Skip satellite dirs owned by other scaffolds. scaffold-workflow-module
    // emits files into `<entity>-workflow/` and registers them in the
    // PARENT entity module's controllers+providers — emitting a stub here
    // creates a competing module that imports the parent, which leaves the
    // Workflow controller in a DI scope where its provider isn't reachable
    // (v99b evidence: 26 of 42 e2e suites failed at
    // "Nest can't resolve dependencies of the AffiliationRequestWorkflowController").
    // Same applies to other "-workflow" / "-upload" satellite dirs.
    if (findFilesInDir(moduleDir, '.workflow.ts').length > 0) {
      skipped++;
      if (args.verbose) console.log('  skipping ' + moduleName + ' (satellite workflow dir; owned by scaffold-workflow-module)');
      return;
    }
    // Only emit if the dir has at least one entity/controller/service/repository
    var hasContent = ['.entity.ts', '.controller.ts', '.service.ts', '.repository.ts'].some(function (suffix) {
      return findFilesInDir(moduleDir, suffix).length > 0;
    });
    if (!hasContent) return; // empty dir
    var content = renderModule(moduleName, moduleDir);
    if (args.dryRun) {
      console.log('  [dry] would write ' + path.relative(args.target, modulePath));
    } else {
      fs.writeFileSync(modulePath, content);
      if (args.verbose) console.log('  wrote ' + path.relative(args.target, modulePath));
    }
    written++;
  });
  console.log('scaffold-feature-module-stub: ' + written + ' module file(s) written, ' + skipped + ' already existed');
}

main();
