#!/usr/bin/env node
// scaffold-zod-schema-from-dto.js — v78 walks backend DTOs and emits
// matching `app/schemas/<entity>.schema.ts` zod schemas on the frontend.
// One source of truth (the DTO + its class-validator decorators) feeds
// both BE runtime validation and FE form validation.
//
// Parses class-validator decorators:
//   @IsString @IsEmail @IsUUID @IsEnum(X) @IsBoolean @IsNumber @IsDate
//   @IsOptional @IsNotEmpty @MinLength(n) @MaxLength(n)
//   @Min(n) @Max(n) @Matches(/.../) @IsUrl
//
// Output schema name: createUserSchema (from CreateUserDto), etc.
// Also exports `type CreateUserSchemaInput = z.infer<typeof createUserSchema>`.
//
// Idempotent. Marker: '// Generated by scaffold-zod-schema-from-dto'.
'use strict';

var fs = require('fs');
var path = require('path');

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--backend-dir') out.backendDir = argv[++i];
    else if (a === '--target') out.target = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.backendDir || !out.target) {
    console.error('Usage: scaffold-zod-schema-from-dto --backend-dir BACKEND --target FRONTEND [--force]');
    process.exit(1);
  }
  return out;
}

function walk(dir, filterFn, out) {
  out = out || [];
  if (!fs.existsSync(dir)) return out;
  fs.readdirSync(dir, { withFileTypes: true }).forEach(function (e) {
    var f = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (/^(node_modules|dist|\.git|coverage|test|__tests__)$/.test(e.name)) return;
      walk(f, filterFn, out);
    } else if (e.isFile() && filterFn(f)) out.push(f);
  });
  return out;
}

function toCamel(s) {
  var parts = s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').split(/[-_\s]+/).filter(Boolean);
  return parts.map(function (w, i) {
    var word = w.toLowerCase();
    return i === 0 ? word : word[0].toUpperCase() + word.slice(1);
  }).join('');
}

function parseDtoFields(content) {
  // Returns: [{ name, optional, validators: { isString, isEmail, isUUID, isEnum, enumName, ... } }]
  var fields = [];
  var lines = content.split('\n');
  var pending = [];
  var inClass = false;
  // v90: track paren-depth for multi-line decorators like
  //   @ApiProperty({
  //     description: 'foo',
  //     enum: BarEnum,
  //   })
  // Without this, lines 2-4 fall through to the field-name regex and emit
  // phantom fields named 'description', 'enum', etc. → contract drift in
  // CONTRACT_VALIDATION.md (v88 had 14 violations from this).
  var decoratorParenDepth = 0;
  var decoratorAccum = '';
  for (var i = 0; i < lines.length; i++) {
    var line = lines[i];
    if (!inClass) {
      if (/^export\s+class\s+\w+/.test(line)) inClass = true;
      continue;
    }
    var trimmed = line.trim();
    if (!trimmed) continue;
    if (decoratorParenDepth === 0 && /^\}/.test(trimmed)) break;
    // Inside multi-line decorator: accumulate, track paren depth, skip
    // field parsing until balanced.
    if (decoratorParenDepth > 0) {
      decoratorAccum += ' ' + trimmed;
      var opensInLine = (trimmed.match(/\(/g) || []).length;
      var closesInLine = (trimmed.match(/\)/g) || []).length;
      decoratorParenDepth += opensInLine - closesInLine;
      if (decoratorParenDepth <= 0) {
        // decorator complete — fold accumulator into pending and reset
        pending.push(decoratorAccum.trim());
        decoratorAccum = '';
        decoratorParenDepth = 0;
      }
      continue;
    }
    if (/^@/.test(trimmed)) {
      // Could be single-line (@IsString()) or start of multi-line.
      var opens = (trimmed.match(/\(/g) || []).length;
      var closes = (trimmed.match(/\)/g) || []).length;
      var net = opens - closes;
      if (net <= 0) {
        // self-contained decorator on one line
        pending.push(trimmed);
      } else {
        // multi-line decorator starts here
        decoratorParenDepth = net;
        decoratorAccum = trimmed;
      }
      continue;
    }
    var m = /^(?:readonly\s+)?(\w+)\s*([?!])?:\s*([^;]+);?\s*$/.exec(trimmed);
    if (!m) { pending = []; continue; }
    var blob = pending.join(' ');
    pending = [];
    var v = {
      isString: /@IsString\b/.test(blob),
      isEmail: /@IsEmail\b/.test(blob),
      isUUID: /@IsUUID\b/.test(blob),
      isURL: /@IsUrl\b/.test(blob),
      isNumber: /@IsNumber|@IsInt\b/.test(blob),
      isBoolean: /@IsBoolean\b/.test(blob),
      isDate: /@IsDate(String)?\b/.test(blob),
      isEnum: /@IsEnum\b/.test(blob),
      enumName: (function () { var x = /@IsEnum\(\s*(\w+)\s*\)/.exec(blob); return x ? x[1] : null; })(),
      // v93: @IsArray + per-item validator @{IsString|IsUUID|...}({ each: true }).
      // Without this, an array DTO field gets typed as a scalar in zod and
      // CONTRACT_VALIDATION flags HIGH mismatch (v92 evidence: submitApplication
      // attachmentDocumentIds backend=string[] vs frontend=z.string()).
      isArray: /@IsArray\b/.test(blob),
      hasEach: /\{\s*each:\s*true\b/.test(blob),
      minLength: (function () { var x = /@MinLength\(\s*(\d+)\s*\)/.exec(blob); return x ? parseInt(x[1], 10) : null; })(),
      maxLength: (function () { var x = /@MaxLength\(\s*(\d+)\s*\)/.exec(blob); return x ? parseInt(x[1], 10) : null; })(),
      min: (function () { var x = /@Min\(\s*(-?\d+)\s*\)/.exec(blob); return x ? parseInt(x[1], 10) : null; })(),
      max: (function () { var x = /@Max\(\s*(-?\d+)\s*\)/.exec(blob); return x ? parseInt(x[1], 10) : null; })(),
      isNotEmpty: /@IsNotEmpty\b/.test(blob),
    };
    var optional = m[2] === '?' || /@IsOptional\b/.test(blob);
    fields.push({ name: m[1], type: m[3].trim(), optional: optional, v: v });
  }
  return fields;
}

function findClassName(content) {
  var m = /export\s+class\s+(\w+)/.exec(content);
  return m ? m[1] : null;
}

function zodFor(f) {
  var v = f.v;
  // v93: derive INNER (per-element) zod chain first, then wrap in z.array(...)
  // when the field is an array. Without this, @IsArray @IsString({each:true})
  // string[] becomes z.string() (scalar) and contract-validation flags HIGH.
  var inner;
  if (v.isEnum && v.enumName) {
    // Use z.nativeEnum if FE has the enum, else z.string (post enum-sync makes this safe)
    inner = 'z.nativeEnum(' + v.enumName + ')';
  } else if (v.isEmail) {
    inner = 'z.string().email()';
  } else if (v.isUUID) {
    inner = 'z.string().uuid()';
  } else if (v.isURL) {
    inner = 'z.string().url()';
  } else if (v.isBoolean) {
    inner = 'z.boolean()';
  } else if (v.isNumber) {
    inner = 'z.number()';
    if (v.min !== null) inner += '.min(' + v.min + ')';
    if (v.max !== null) inner += '.max(' + v.max + ')';
  } else if (v.isDate) {
    inner = 'z.string()'; // ISO date string
  } else if (v.isString || /^string/.test(f.type)) {
    inner = 'z.string()';
    if (v.minLength !== null) inner += '.min(' + v.minLength + ')';
    else if (v.isNotEmpty && !v.minLength) inner += '.min(1)';
    if (v.maxLength !== null) inner += '.max(' + v.maxLength + ')';
  } else {
    inner = 'z.unknown()';
  }
  var chain = (v.isArray || /\[\]\s*$/.test(f.type)) ? 'z.array(' + inner + ')' : inner;
  if (f.optional) chain += '.optional()';
  return chain;
}

function generatedMarker() {
  return '// Generated by scaffold-zod-schema-from-dto — DO NOT EDIT BY HAND. Re-run when DTOs change.';
}

function emitSchemaFile(moduleName, dtoSchemas, enumImports) {
  var lines = [];
  lines.push(generatedMarker());
  lines.push("import { z } from 'zod';");
  Object.keys(enumImports).sort().forEach(function (name) {
    lines.push("import { " + name + " } from '~/enums/" + enumImports[name] + ".enum';");
  });
  lines.push('');
  dtoSchemas.forEach(function (d) {
    lines.push('export const ' + d.schemaName + ' = z.object({');
    d.fields.forEach(function (f) {
      lines.push('  ' + f.name + ': ' + zodFor(f) + ',');
    });
    lines.push('});');
    lines.push('');
    lines.push('export type ' + d.typeName + 'Input = z.infer<typeof ' + d.schemaName + '>;');
    lines.push('');
  });
  return lines.join('\n');
}

function enumToKebab(name) {
  // 'UserStatusEnum' → 'user-status' (matching scaffold-enum-sync filename without .enum.ts)
  var stripped = name.replace(/Enum$/, '');
  return stripped.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
}

function writeIfManaged(file, content, force, dryRun) {
  if (fs.existsSync(file)) {
    var existing = fs.readFileSync(file, 'utf-8');
    if (!/Generated by scaffold-zod-schema-from-dto/.test(existing) && !force) {
      return { written: false, reason: 'exists-handauthored' };
    }
    if (existing === content) return { written: false, reason: 'unchanged' };
  }
  if (dryRun) return { written: false, reason: 'dry-run' };
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return { written: true };
}

function main() {
  var args = parseArgs(process.argv);
  var modulesDir = path.join(args.backendDir, 'src/modules');
  var dtoFiles = walk(modulesDir, function (f) { return /\.dto\.ts$/.test(f); }, []);
  if (dtoFiles.length === 0) {
    console.log('scaffold-zod-schema-from-dto: no DTOs under ' + modulesDir);
    return;
  }
  // Group by module dir
  var byModule = {};
  dtoFiles.forEach(function (d) {
    var rel = path.relative(modulesDir, d);
    var moduleName = rel.split(path.sep)[0];
    if (!byModule[moduleName]) byModule[moduleName] = [];
    byModule[moduleName].push(d);
  });
  var written = 0, skipped = 0;
  Object.keys(byModule).sort().forEach(function (moduleName) {
    var dtoSchemas = [];
    var enumImports = {}; // EnumName -> kebab-file-base
    byModule[moduleName].forEach(function (df) {
      var content = fs.readFileSync(df, 'utf-8');
      var className = findClassName(content);
      if (!className) return;
      var fields = parseDtoFields(content);
      if (fields.length === 0) return;
      // schemaName: createUserSchema (from CreateUserDto)
      var base = className.replace(/Dto$/, '');
      var schemaName = base.charAt(0).toLowerCase() + base.slice(1) + 'Schema';
      dtoSchemas.push({ schemaName: schemaName, typeName: base, fields: fields });
      fields.forEach(function (f) {
        if (f.v.isEnum && f.v.enumName) enumImports[f.v.enumName] = enumToKebab(f.v.enumName);
      });
    });
    if (dtoSchemas.length === 0) return;
    var content = emitSchemaFile(moduleName, dtoSchemas, enumImports);
    var dst = path.join(args.target, 'app/schemas', moduleName + '.schema.ts');
    var r = writeIfManaged(dst, content, args.force, args.dryRun);
    if (r.written) written++; else skipped++;
    if (args.verbose) console.log('  ' + moduleName + ' (' + dtoSchemas.length + ' DTOs): ' + (r.written ? 'wrote' : r.reason));
  });
  console.log('scaffold-zod-schema-from-dto: ' + written + ' written, ' + skipped + ' skipped');
}

main();
