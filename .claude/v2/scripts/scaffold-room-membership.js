#!/usr/bin/env node
// scaffold-room-membership.js — ROOM-MEMBERSHIP / room-scoped-permission capability (Tier 2).
//
// The permission half of the chat decomposition (and of any "group with per-member
// roles" feature: project teams, shared docs, channels). It is ORTHOGONAL to the
// realtime capability and composes the EXISTING app-level RBAC (RULE-B8 / RolesGuard)
// — it does NOT reinvent it. App-role answers "can this user use chat at all?"; this
// capability answers "is this user a member of THIS room, and with what room-role?".
//
// 1-on-1 vs group is one model: a direct chat is a Room(type='direct') with exactly
// two memberships. The `direct` flag only changes room-creation rules, not the schema.
//
// MODULE_PLAN.yaml shape:
//   rooms:
//     - name: chat-room          # → Room + RoomMembership entities/service/guard
//       member_roles: [owner, admin, member]   # room-scoped roles (default member)
//       modes: [direct, group]   # supported room kinds (default group)
//
// Emits under src/modules/room-membership/ (one shared capability module, even if
// several features declare rooms — they share Room/RoomMembership):
//   room.entity.ts, room-membership.entity.ts, room-role.enum.ts,
//   room-membership.repository.ts, room-membership.service.ts,
//   room-member.guard.ts, room-membership.module.ts
'use strict';

var fs = require('fs');
var path = require('path');

var MARKER = '// Generated by scaffold-room-membership';
var DIR = 'src/modules/room-membership';

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--spec') out.spec = argv[++i];
    else if (a === '--target') out.target = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.spec || !out.target) {
    console.error('Usage: scaffold-room-membership --spec MODULE_PLAN.yaml --target BACKEND_DIR [--force]');
    process.exit(1);
  }
  return out;
}
function loadYaml() {
  try { return require('yaml'); } catch (_) {}
  try {
    return require(path.join(require('child_process').execSync('npm root -g', { encoding: 'utf-8' }).trim(), 'yaml'));
  } catch (_) { return null; }
}

// Collect declared room-roles across all `rooms:` entries (dedup, default member).
function collectRoles(list) {
  var set = [];
  for (var i = 0; i < list.length; i++) {
    var rs = list[i].member_roles || list[i].roles || ['owner', 'member'];
    for (var j = 0; j < rs.length; j++) {
      var r = String(rs[j]).trim().toLowerCase();
      if (r && set.indexOf(r) === -1) set.push(r);
    }
  }
  if (set.indexOf('member') === -1) set.push('member');
  return set;
}

function fileRoleEnum(roles) {
  var L = [MARKER, ''];
  L.push("export enum RoomRole {");
  for (var i = 0; i < roles.length; i++) {
    L.push("  " + roles[i].toUpperCase() + " = '" + roles[i] + "',");
  }
  L.push("}");
  L.push('');
  return L.join('\n');
}

function fileRoomEntity() {
  return [
    MARKER,
    "import { Entity, Column, OneToMany } from 'typeorm';",
    "import { BaseEntity } from '../../core/base/base.entity';",
    "import { RoomMembership } from './room-membership.entity';",
    '',
    "@Entity('rooms')",
    "export class Room extends BaseEntity {",
    "  // 'direct' = degenerate 2-member room (1:1); 'group' = N members.",
    "  @Column({ type: 'varchar', length: 16, default: 'group' })",
    "  type!: string;",
    '',
    "  @Column({ type: 'varchar', length: 200, nullable: true })",
    "  name!: string | null;",
    '',
    "  @Column({ name: 'created_by', type: 'uuid' })",
    "  createdBy!: string;",
    '',
    "  @OneToMany(() => RoomMembership, (m) => m.room)",
    "  memberships!: RoomMembership[];",
    "}",
    '',
  ].join('\n');
}

function fileMembershipEntity() {
  return [
    MARKER,
    "import { Entity, Column, ManyToOne, JoinColumn, Index, Unique } from 'typeorm';",
    "import { BaseEntity } from '../../core/base/base.entity';",
    "import { Room } from './room.entity';",
    "import { RoomRole } from './room-role.enum';",
    '',
    "@Entity('room_memberships')",
    "@Unique(['roomId', 'userId'])",
    "export class RoomMembership extends BaseEntity {",
    "  @Index()",
    "  @Column({ name: 'room_id', type: 'uuid' })",
    "  roomId!: string;",
    '',
    "  @Index()",
    "  @Column({ name: 'user_id', type: 'uuid' })",
    "  userId!: string;",
    '',
    "  @Column({ name: 'room_role', type: 'varchar', length: 32, default: RoomRole.MEMBER })",
    "  roomRole!: RoomRole;",
    '',
    "  @ManyToOne(() => Room, (r) => r.memberships, { onDelete: 'CASCADE' })",
    "  @JoinColumn({ name: 'room_id' })",
    "  room!: Room;",
    "}",
    '',
  ].join('\n');
}

function fileRepository() {
  return [
    MARKER,
    "import { Injectable } from '@nestjs/common';",
    "import { InjectRepository } from '@nestjs/typeorm';",
    "import { Repository } from 'typeorm';",
    "import { BaseRepository } from '../../core/base/base.repository';",
    "import { RoomMembership } from './room-membership.entity';",
    '',
    "@Injectable()",
    "export class RoomMembershipRepository extends BaseRepository<RoomMembership> {",
    "  constructor(",
    "    @InjectRepository(RoomMembership)",
    "    private readonly repo: Repository<RoomMembership>,",
    "  ) {",
    "    super(repo);",
    "  }",
    '',
    "  findMember(roomId: string, userId: string): Promise<RoomMembership | null> {",
    "    return this.repo.findOne({ where: { roomId, userId } });",
    "  }",
    '',
    "  findByRoom(roomId: string): Promise<RoomMembership[]> {",
    "    return this.repo.find({ where: { roomId } });",
    "  }",
    "}",
    '',
  ].join('\n');
}

function fileService() {
  return [
    MARKER,
    "import { Injectable, ForbiddenException } from '@nestjs/common';",
    "import { RoomMembershipRepository } from './room-membership.repository';",
    "import { RoomRole } from './room-role.enum';",
    '',
    "@Injectable()",
    "export class RoomMembershipService {",
    "  constructor(private readonly repo: RoomMembershipRepository) {}",
    '',
    "  async isMember(roomId: string, userId: string): Promise<boolean> {",
    "    return !!(await this.repo.findMember(roomId, userId));",
    "  }",
    '',
    "  async getRole(roomId: string, userId: string): Promise<RoomRole | null> {",
    "    const m = await this.repo.findMember(roomId, userId);",
    "    return m ? m.roomRole : null;",
    "  }",
    '',
    "  // Throws unless the user is a member (optionally with one of `roles`).",
    "  async assertMember(roomId: string, userId: string, roles?: RoomRole[]): Promise<void> {",
    "    const m = await this.repo.findMember(roomId, userId);",
    "    if (!m) throw new ForbiddenException('not a member of this room');",
    "    if (roles && roles.length && roles.indexOf(m.roomRole) === -1) {",
    "      throw new ForbiddenException('insufficient room role');",
    "    }",
    "  }",
    "}",
    '',
  ].join('\n');
}

// Guard for REST routes carrying a room id param. Composes — runs AFTER the global
// JwtAuthGuard/RolesGuard (app-role), enforcing room-scoped membership/role.
function fileGuard() {
  return [
    MARKER,
    "import {",
    "  CanActivate, ExecutionContext, Injectable, ForbiddenException,",
    "  SetMetadata,",
    "} from '@nestjs/common';",
    "import { Reflector } from '@nestjs/core';",
    "import { RoomMembershipService } from './room-membership.service';",
    "import { RoomRole } from './room-role.enum';",
    '',
    "export const ROOM_ROLES_KEY = 'roomRoles';",
    "// @RoomRoles(RoomRole.OWNER, RoomRole.ADMIN) on a route requiring elevated room-role.",
    "export const RoomRoles = (...roles: RoomRole[]) => SetMetadata(ROOM_ROLES_KEY, roles);",
    '',
    "@Injectable()",
    "export class RoomMemberGuard implements CanActivate {",
    "  constructor(",
    "    private readonly membership: RoomMembershipService,",
    "    private readonly reflector: Reflector,",
    "  ) {}",
    '',
    "  async canActivate(ctx: ExecutionContext): Promise<boolean> {",
    "    const req = ctx.switchToHttp().getRequest();",
    "    const user = req.user;",
    "    const roomId = req.params?.roomId || req.params?.id || req.body?.roomId;",
    "    if (!user?.id || !roomId) throw new ForbiddenException('room context required');",
    "    const roles = this.reflector.getAllAndOverride<RoomRole[]>(ROOM_ROLES_KEY, [",
    "      ctx.getHandler(), ctx.getClass(),",
    "    ]);",
    "    await this.membership.assertMember(roomId, user.id, roles);",
    "    return true;",
    "  }",
    "}",
    '',
  ].join('\n');
}

function fileModule() {
  return [
    MARKER,
    "import { Module } from '@nestjs/common';",
    "import { TypeOrmModule } from '@nestjs/typeorm';",
    "import { Room } from './room.entity';",
    "import { RoomMembership } from './room-membership.entity';",
    "import { RoomMembershipRepository } from './room-membership.repository';",
    "import { RoomMembershipService } from './room-membership.service';",
    "import { RoomMemberGuard } from './room-member.guard';",
    '',
    "@Module({",
    "  imports: [TypeOrmModule.forFeature([Room, RoomMembership])],",
    "  providers: [RoomMembershipRepository, RoomMembershipService, RoomMemberGuard],",
    "  exports: [RoomMembershipService, RoomMemberGuard],",
    "})",
    "export class RoomMembershipModule {}",
    '',
  ].join('\n');
}

function writeFile(target, rel, content, args) {
  var full = path.join(target, DIR, rel);
  if (fs.existsSync(full) && !args.force) {
    var cur = fs.readFileSync(full, 'utf-8');
    if (cur.indexOf(MARKER) === -1) {
      if (args.verbose) console.log('  skip (hand-authored, no marker): ' + rel);
      return false;
    }
  }
  if (args.dryRun) { if (args.verbose) console.log('  [dry] ' + rel); return true; }
  var dir = path.dirname(full);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(full, content);
  return true;
}

function main() {
  var args = parseArgs(process.argv);
  if (!fs.existsSync(args.spec)) { console.log('scaffold-room-membership: no MODULE_PLAN — skipping'); return; }
  var yaml = loadYaml();
  if (!yaml) { console.log('scaffold-room-membership: yaml unavailable — skipping'); return; }
  var spec;
  try { spec = yaml.parse(fs.readFileSync(args.spec, 'utf-8')); } catch (e) { console.log('scaffold-room-membership: bad YAML — skipping'); return; }

  // Trigger when `rooms:` is declared OR any realtime entry sets rooms:true.
  var rooms = spec && Array.isArray(spec.rooms) ? spec.rooms.filter(function (r) { return r && r.name; }) : [];
  var realtimeWantsRooms = spec && Array.isArray(spec.realtime) &&
    spec.realtime.some(function (r) { return r && (r.rooms === true || r.rooms === 'true'); });
  if (rooms.length === 0 && !realtimeWantsRooms) {
    console.log('scaffold-room-membership: no `rooms:` and no realtime room-scoping — skipping');
    return;
  }
  if (rooms.length === 0) rooms = [{ name: 'room', member_roles: ['owner', 'member'] }];

  var roles = collectRoles(rooms);
  console.log('scaffold-room-membership: emitting Room + RoomMembership (roles=[' + roles.join(',') + '])');

  var files = [
    ['room-role.enum.ts', fileRoleEnum(roles)],
    ['room.entity.ts', fileRoomEntity()],
    ['room-membership.entity.ts', fileMembershipEntity()],
    ['room-membership.repository.ts', fileRepository()],
    ['room-membership.service.ts', fileService()],
    ['room-member.guard.ts', fileGuard()],
    ['room-membership.module.ts', fileModule()],
  ];
  var n = 0;
  for (var i = 0; i < files.length; i++) {
    if (writeFile(args.target, files[i][0], files[i][1], args)) n++;
  }
  console.log('scaffold-room-membership: ' + n + ' file(s) ' + (args.dryRun ? '(dry)' : 'written') +
    '. Register RoomMembershipModule in AppModule (app-module-registry handles this).');
}

main();
