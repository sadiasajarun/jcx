#!/usr/bin/env node
// scaffold-django-seed.js — Django management command `seed` from _fixtures.yaml.
// Analog of scaffold-seed-script (NestJS). Emits core/management/commands/seed.py
// which upserts the fixture users (bcrypt password_hash) via the ORM so login-proof
// has accounts. Idempotent (update_or_create by email). Reads FIXTURES_PATH env or
// the conventional .claude-project/<proj>/user_stories/_fixtures.yaml.
'use strict';
var fs = require('fs');
var path = require('path');

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--target') out.target = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.target) { console.error('Usage: scaffold-django-seed --target BACKEND_DIR [--force]'); process.exit(1); }
  return out;
}

var BODY = [
  '# Generated by scaffold-django-seed — `python manage.py seed`.',
  '# Upserts fixture users (bcrypt password_hash) so login-proof has accounts.',
  'import os',
  '',
  'import bcrypt',
  'import yaml',
  'from django.core.management.base import BaseCommand',
  '',
  '',
  'def _find_fixtures():',
  '    p = os.environ.get("FIXTURES_PATH")',
  '    if p and os.path.exists(p):',
  '        return p',
  '    here = os.getcwd()',
  '    for root, _dirs, files in os.walk(os.path.join(here, "..")):',
  '        if "_fixtures.yaml" in files and "user_stories" in root:',
  '            return os.path.join(root, "_fixtures.yaml")',
  '    return None',
  '',
  '',
  'class Command(BaseCommand):',
  '    help = "Seed fixture users from _fixtures.yaml"',
  '',
  '    def handle(self, *args, **opts):',
  '        from users.models import User',
  '        fpath = _find_fixtures()',
  '        if not fpath:',
  '            self.stdout.write("seed: no _fixtures.yaml found — skipping")',
  '            return',
  '        data = yaml.safe_load(open(fpath))',
  '        users = (data or {}).get("users") or {}',
  '        n = 0',
  '        for key, u in users.items():',
  '            if not u or not u.get("email") or not u.get("password"):',
  '                continue',
  '            ph = bcrypt.hashpw(str(u["password"]).encode(), bcrypt.gensalt(10)).decode()',
  '            defaults = {"password_hash": ph}',
  '            for f in ("name", "role", "status", "phone", "nationality"):',
  '                if u.get(f) is not None and hasattr(User, f):',
  '                    defaults[f] = u[f]',
  '            User.objects.update_or_create(email=u["email"], defaults=defaults)',
  '            n += 1',
  '        self.stdout.write("seed: upserted %d user(s)" % n)',
  '',
].join('\n');

function main() {
  var args = parseArgs(process.argv);
  var dir = path.join(args.target, 'core', 'management', 'commands');
  fs.mkdirSync(dir, { recursive: true });
  ['core/management/__init__.py', 'core/management/commands/__init__.py'].forEach(function (rel) {
    var f = path.join(args.target, rel);
    if (!fs.existsSync(f)) fs.writeFileSync(f, '');
  });
  var file = path.join(dir, 'seed.py');
  if (fs.existsSync(file) && !args.force && fs.readFileSync(file, 'utf-8').indexOf('scaffold-django-seed') < 0) {
    console.log('scaffold-django-seed: seed.py hand-edited — skipping'); return;
  }
  fs.writeFileSync(file, BODY);
  console.log('scaffold-django-seed: wrote core/management/commands/seed.py');
}

main();
