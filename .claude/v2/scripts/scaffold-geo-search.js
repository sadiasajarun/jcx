#!/usr/bin/env node
// scaffold-geo-search.js — GEO-RADIUS-SEARCH capability primitive (Tier 2, NestJS/TypeORM/Postgres).
//
// Radius ("pins near me") search is exact, easy-to-get-subtly-wrong SQL (the earthdistance
// `earth_box(...) @>` bounding-box pre-filter + `earth_distance(...)` precise filter +
// distance sort). Emitting it deterministically beats letting the LLM hand-write geo SQL.
//
// MODULE_PLAN.yaml shape:
//   geo:
//     provider: kakao              # FE map provider (informational)
//     table: instructor_profile    # the table holding lat/lng
//     lat_column: base_pin_lat
//     lng_column: base_pin_lng
//     radius_default_km: 5
//     extra_where: "approval_status = 'APPROVED' AND is_visible = true"   # optional filter
'use strict';

var fs = require('fs');
var path = require('path');
var MARKER = '// Generated by scaffold-geo-search';

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--spec') out.spec = argv[++i];
    else if (a === '--target') out.target = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.spec || !out.target) { console.error('Usage: scaffold-geo-search --spec MODULE_PLAN.yaml --target BACKEND_DIR'); process.exit(1); }
  return out;
}
function loadYaml() {
  try { return require('yaml'); } catch (_) {}
  try { return require(path.join(require('child_process').execSync('npm root -g', { encoding: 'utf-8' }).trim(), 'yaml')); } catch (_) { return null; }
}
// sanitize an SQL identifier (table/column come from MODULE_PLAN, not user input — still clamp)
function ident(s) { return String(s).replace(/[^a-zA-Z0-9_]/g, ''); }

function fileService(G) {
  var lat = ident(G.lat), lng = ident(G.lng), tbl = ident(G.table);
  var extraWhere = G.extraWhere ? ' AND (' + G.extraWhere + ')' : '';
  return [
    MARKER,
    "import { Injectable, OnModuleInit, Logger } from '@nestjs/common';",
    "import { InjectDataSource } from '@nestjs/typeorm';",
    "import { DataSource } from 'typeorm';",
    '',
    "// Radius search via Postgres cube/earthdistance. earth_box(...) @> is the index-",
    "// friendly bounding-box pre-filter; earth_distance(...) is the exact circle filter.",
    "@Injectable()",
    "export class GeoSearchService implements OnModuleInit {",
    "  private readonly logger = new Logger('GeoSearchService');",
    "  constructor(@InjectDataSource() private readonly dataSource: DataSource) {}",
    '',
    "  async onModuleInit(): Promise<void> {",
    "    // idempotent — enable the radius-search extensions if absent",
    "    await this.dataSource.query('CREATE EXTENSION IF NOT EXISTS cube').catch((e) => this.logger.warn('cube ext: ' + e.message));",
    "    await this.dataSource.query('CREATE EXTENSION IF NOT EXISTS earthdistance').catch((e) => this.logger.warn('earthdistance ext: ' + e.message));",
    "  }",
    '',
    "  // Rows within radiusKm of (lat,lng), nearest first, with distance_m.",
    "  async nearby(lat: number, lng: number, radiusKm = " + (Number(G.radiusKm) || 5) + ", limit = 200): Promise<any[]> {",
    "    const radiusM = radiusKm * 1000;",
    "    return this.dataSource.query(",
    "      `SELECT t.*, earth_distance(ll_to_earth($1, $2), ll_to_earth(t." + lat + ", t." + lng + ")) AS distance_m",
    "       FROM " + tbl + " t",
    "       WHERE t." + lat + " IS NOT NULL AND t." + lng + " IS NOT NULL",
    "         AND earth_box(ll_to_earth($1, $2), $3) @> ll_to_earth(t." + lat + ", t." + lng + ")",
    "         AND earth_distance(ll_to_earth($1, $2), ll_to_earth(t." + lat + ", t." + lng + ")) < $3" + extraWhere,
    "       ORDER BY distance_m ASC",
    "       LIMIT $4`,",
    "      [lat, lng, radiusM, limit],",
    "    );",
    "  }",
    "}",
    '',
  ].join('\n');
}

function fileController(G) {
  return [
    MARKER,
    "import { Controller, Get, Query, BadRequestException } from '@nestjs/common';",
    "import { ApiTags, ApiOperation } from '@nestjs/swagger';",
    "import { GeoSearchService } from './geo-search.service';",
    '',
    "@ApiTags('geo-search')",
    "@Controller('search')",
    "export class GeoSearchController {",
    "  constructor(private readonly service: GeoSearchService) {}",
    '',
    "  @Get('nearby')",
    "  @ApiOperation({ summary: 'Radius search — rows within ?radius km of ?lat,?lng (nearest first)' })",
    "  nearby(@Query('lat') lat?: string, @Query('lng') lng?: string, @Query('radius') radius?: string) {",
    "    const la = Number(lat), ln = Number(lng);",
    "    if (!Number.isFinite(la) || !Number.isFinite(ln)) throw new BadRequestException('lat and lng are required');",
    "    const r = radius != null ? Number(radius) : " + (Number(G.radiusKm) || 5) + ";",
    "    return this.service.nearby(la, ln, Number.isFinite(r) ? r : " + (Number(G.radiusKm) || 5) + ");",
    "  }",
    "}",
    '',
  ].join('\n');
}

function fileModule() {
  return [
    MARKER,
    "import { Module } from '@nestjs/common';",
    "import { GeoSearchService } from './geo-search.service';",
    "import { GeoSearchController } from './geo-search.controller';",
    '',
    "@Module({",
    "  controllers: [GeoSearchController],",
    "  providers: [GeoSearchService],",
    "  exports: [GeoSearchService],",
    "})",
    "export class GeoSearchModule {}",
    '',
  ].join('\n');
}

function writeFile(target, rel, content, args) {
  var full = path.join(target, rel);
  if (fs.existsSync(full) && !args.force) {
    var cur = fs.readFileSync(full, 'utf-8');
    if (cur.indexOf(MARKER) === -1) { if (args.verbose) console.log('  skip (hand-authored): ' + rel); return false; }
  }
  if (args.dryRun) { if (args.verbose) console.log('  [dry] ' + rel); return true; }
  var dir = path.dirname(full);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(full, content);
  return true;
}

function main() {
  var args = parseArgs(process.argv);
  if (!fs.existsSync(args.spec)) { console.log('scaffold-geo-search: no MODULE_PLAN — skipping'); return; }
  var yaml = loadYaml();
  if (!yaml) { console.log('scaffold-geo-search: yaml unavailable — skipping'); return; }
  var spec; try { spec = yaml.parse(fs.readFileSync(args.spec, 'utf-8')); } catch (e) { console.log('scaffold-geo-search: bad YAML — skipping'); return; }
  var geo = spec && spec.geo;
  if (!geo || !geo.table) { console.log('scaffold-geo-search: no `geo:` (with table) — skipping'); return; }

  var G = {
    table: geo.table,
    lat: geo.lat_column || 'lat',
    lng: geo.lng_column || 'lng',
    radiusKm: geo.radius_default_km || 5,
    extraWhere: geo.extra_where || '',
  };
  console.log('scaffold-geo-search: radius search on ' + ident(G.table) + '(' + ident(G.lat) + ',' + ident(G.lng) + '), default ' + G.radiusKm + 'km');
  var n = 0;
  [
    ['src/modules/geo-search/geo-search.service.ts', fileService(G)],
    ['src/modules/geo-search/geo-search.controller.ts', fileController(G)],
    ['src/modules/geo-search/geo-search.module.ts', fileModule()],
  ].forEach(function (f) { if (writeFile(args.target, f[0], f[1], args)) n++; });
  console.log('scaffold-geo-search: ' + n + ' file(s) ' + (args.dryRun ? '(dry)' : 'written') + '. Register GeoSearchModule. Postgres cube+earthdistance extensions auto-enabled on boot.');
}

main();
