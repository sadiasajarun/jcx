#!/usr/bin/env node
// scaffold-sentry-wiring.js — v78 wire Sentry init in backend (main.ts)
// and frontend (entry.client.tsx / main.tsx). Reads SENTRY_DSN from env
// at runtime; no-ops cleanly if unset.
//
// Emits:
//   - backend/src/instrument.ts            Sentry.init({ dsn, ...})  loaded first
//   - frontend/app/lib/sentry.ts           Sentry.init wrapper used in entry
// Plus inserts `import './instrument';` as the FIRST line of backend/src/main.ts
// when present. Plus inserts `initSentry();` into FE entry if found.
//
// Adds @sentry/node + @sentry/react to deps when missing.
// Idempotent. Marker: '// Generated by scaffold-sentry-wiring'.
'use strict';

var fs = require('fs');
var path = require('path');

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--target') out.target = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--dry-run') out.dryRun = true;
  }
  if (!out.target) { console.error('Usage: scaffold-sentry-wiring --target PROJECT_ROOT'); process.exit(1); }
  return out;
}

function marker() { return '// Generated by scaffold-sentry-wiring — DO NOT EDIT BY HAND. Re-run to refresh.'; }

function writeIfManaged(file, content, force, dryRun) {
  if (fs.existsSync(file)) {
    var existing = fs.readFileSync(file, 'utf-8');
    if (!/Generated by scaffold-sentry-wiring/.test(existing) && !force) {
      return { written: false, reason: 'exists-handauthored' };
    }
    if (existing === content) return { written: false, reason: 'unchanged' };
  }
  if (dryRun) return { written: false, reason: 'dry-run' };
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return { written: true };
}

function ensureDep(pkgPath, deps, dryRun) {
  if (!fs.existsSync(pkgPath)) return { changed: false, reason: 'no-package-json' };
  var pkg;
  try { pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8')); } catch (_) { return { changed: false, reason: 'parse-error' }; }
  pkg.dependencies = pkg.dependencies || {};
  var added = [];
  Object.keys(deps).forEach(function (k) {
    if (!pkg.dependencies[k] && !(pkg.devDependencies || {})[k]) {
      pkg.dependencies[k] = deps[k];
      added.push(k);
    }
  });
  if (!added.length) return { changed: false, reason: 'already-present' };
  if (dryRun) return { changed: false, reason: 'dry-run', added: added };
  fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
  return { changed: true, added: added };
}

var BE_INSTRUMENT = [
  marker(),
  "import * as Sentry from '@sentry/node';",
  '',
  'const dsn = process.env.SENTRY_DSN;',
  'if (dsn) {',
  '  Sentry.init({',
  '    dsn,',
  "    environment: process.env.NODE_ENV ?? 'development',",
  '    tracesSampleRate: Number(process.env.SENTRY_TRACES_SAMPLE_RATE ?? 0.1),',
  '  });',
  '}',
  '',
].join('\n');

var FE_SENTRY = [
  marker(),
  "import * as Sentry from '@sentry/react';",
  '',
  'export function initSentry() {',
  '  const dsn = import.meta.env.VITE_SENTRY_DSN as string | undefined;',
  '  if (!dsn) return;',
  '  Sentry.init({',
  '    dsn,',
  '    environment: import.meta.env.MODE,',
  '    tracesSampleRate: Number(import.meta.env.VITE_SENTRY_TRACES_SAMPLE_RATE ?? 0.1),',
  '  });',
  '}',
  '',
].join('\n');

function patchBackendMain(backendDir, dryRun) {
  var main = path.join(backendDir, 'src/main.ts');
  if (!fs.existsSync(main)) return { patched: false, reason: 'no-main.ts' };
  var content = fs.readFileSync(main, 'utf-8');
  if (/import\s+['"]\.\/instrument['"]/.test(content)) return { patched: false, reason: 'already-imports' };
  var patched = "import './instrument';\n" + content;
  if (dryRun) return { patched: false, reason: 'dry-run' };
  fs.writeFileSync(main, patched);
  return { patched: true };
}

function patchFrontendEntry(frontendDir, dryRun) {
  // Look for the canonical entry — could be app/entry.client.tsx or app/main.tsx
  var candidates = ['app/entry.client.tsx', 'app/main.tsx', 'src/main.tsx', 'src/entry.client.tsx'];
  for (var i = 0; i < candidates.length; i++) {
    var p = path.join(frontendDir, candidates[i]);
    if (fs.existsSync(p)) {
      var content = fs.readFileSync(p, 'utf-8');
      if (/initSentry\s*\(/.test(content)) return { patched: false, reason: 'already-calls' };
      var importLine = "import { initSentry } from '~/lib/sentry';\ninitSentry();\n";
      var patched = importLine + content;
      if (dryRun) return { patched: false, reason: 'dry-run' };
      fs.writeFileSync(p, patched);
      return { patched: true, file: candidates[i] };
    }
  }
  return { patched: false, reason: 'no-entry-file' };
}

function main() {
  var args = parseArgs(process.argv);
  var beDir = path.join(args.target, 'backend');
  var feDir = path.join(args.target, 'frontend');

  var rBE = { written: false, reason: 'no-backend' };
  var rBEMain = { patched: false, reason: 'no-backend' };
  var rBEDeps = { changed: false, reason: 'no-backend' };
  if (fs.existsSync(beDir)) {
    rBE = writeIfManaged(path.join(beDir, 'src/instrument.ts'), BE_INSTRUMENT, args.force, args.dryRun);
    rBEMain = patchBackendMain(beDir, args.dryRun);
    rBEDeps = ensureDep(path.join(beDir, 'package.json'), { '@sentry/node': '^8.0.0' }, args.dryRun);
  }

  var rFE = { written: false, reason: 'no-frontend' };
  var rFEEntry = { patched: false, reason: 'no-frontend' };
  var rFEDeps = { changed: false, reason: 'no-frontend' };
  if (fs.existsSync(feDir)) {
    rFE = writeIfManaged(path.join(feDir, 'app/lib/sentry.ts'), FE_SENTRY, args.force, args.dryRun);
    rFEEntry = patchFrontendEntry(feDir, args.dryRun);
    rFEDeps = ensureDep(path.join(feDir, 'package.json'), { '@sentry/react': '^8.0.0' }, args.dryRun);
  }

  console.log('scaffold-sentry-wiring:',
    'BE instrument.ts=' + (rBE.written ? 'wrote' : rBE.reason) + ' main.ts=' + (rBEMain.patched ? 'patched' : rBEMain.reason),
    '| FE sentry.ts=' + (rFE.written ? 'wrote' : rFE.reason) + ' entry=' + (rFEEntry.patched ? 'patched(' + (rFEEntry.file || '') + ')' : rFEEntry.reason),
    '| deps: be=' + (rBEDeps.changed ? '+' + rBEDeps.added.join(',') : rBEDeps.reason) + ' fe=' + (rFEDeps.changed ? '+' + rFEDeps.added.join(',') : rFEDeps.reason));
}

main();
