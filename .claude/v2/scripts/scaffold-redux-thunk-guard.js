#!/usr/bin/env node
// scaffold-redux-thunk-guard.js — v132. Remove extraReducers `.addCase(X.pending|
// fulfilled|rejected, ...)` blocks where X is NOT a createAsyncThunk.
//
// THE BUG (v132, live-reproduced): userSlice.ts did
//   import { createUser, fetchUsers } from '~/services/httpServices/userService';
//   extraReducers: b => b.addCase(fetchUsers.pending,...).addCase(createUser.pending,...)
// but per the architecture rules READ ops are createAsyncThunk while MUTATIONS are
// plain async functions — so `createUser` is a plain function, `createUser.pending`
// is `undefined`, and `.addCase(undefined, ...)` throws at STORE CREATION
// (`Cannot read properties of undefined (reading 'type')`) → the whole app
// white-screens on hydration → every interactive story on that store fails.
//
// Fix deterministically: for each slice, resolve each addCase action ref to its
// source export and check if it's a thunk; strip the addCase blocks for non-thunks
// (a mutation has no .pending/.fulfilled/.rejected to reduce on anyway).
'use strict';

var fs = require('fs');
var path = require('path');

var MARKER = '// Generated by scaffold-redux-thunk-guard';

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--target') out.target = argv[++i];
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.target) { console.error('Usage: scaffold-redux-thunk-guard --target FRONTEND_DIR'); process.exit(1); }
  return out;
}

// Resolve a `~/x` or relative import spec to an on-disk file under app/.
function resolveModule(appDir, fromFile, spec) {
  var base;
  if (spec.indexOf('~/') === 0) base = path.join(appDir, spec.slice(2));
  else if (spec.charAt(0) === '.') base = path.join(path.dirname(fromFile), spec);
  else return null; // bare package — not ours
  var cands = [base + '.ts', base + '.tsx', base + '/index.ts', base + '/index.tsx', base];
  for (var i = 0; i < cands.length; i++) if (fs.existsSync(cands[i]) && fs.statSync(cands[i]).isFile()) return cands[i];
  return null;
}

// Classify each exported name in a module as 'thunk' | 'plain' | undefined(unknown),
// FOLLOWING re-exports (`export {x} from './y'`, `export * from './y'`) and local
// aliases. CONSERVATIVE: we only ever STRIP a 'plain' (positively a non-thunk
// function); 'thunk' and unknown are KEPT. A false-keep merely re-crashes (no worse
// than today); a false-strip would delete a real thunk's reducers (a regression) —
// so when in doubt, keep.
var classifyCache = {};
function classifyExports(modFile) {
  if (classifyCache[modFile]) return classifyCache[modFile];
  var map = {};
  classifyCache[modFile] = map; // set early to break cycles
  var src;
  try { src = fs.readFileSync(modFile, 'utf-8'); } catch (e) { return map; }
  var appDir = src.__appDir; // unused; appDir threaded via closure below
  var m;
  // thunks: export const NAME = createAsyncThunk(
  var reThunk = /export\s+const\s+([A-Za-z0-9_$]+)\s*=\s*createAsyncThunk\b/g;
  while ((m = reThunk.exec(src)) !== null) map[m[1]] = 'thunk';
  // plain functions: export async function NAME / export function NAME
  var reFn = /export\s+(?:async\s+)?function\s+([A-Za-z0-9_$]+)/g;
  while ((m = reFn.exec(src)) !== null) if (!map[m[1]]) map[m[1]] = 'plain';
  // local aliases: export const NAME = OTHER;
  var aliases = [];
  var reAlias = /export\s+const\s+([A-Za-z0-9_$]+)\s*=\s*([A-Za-z0-9_$]+)\s*;/g;
  while ((m = reAlias.exec(src)) !== null) aliases.push([m[1], m[2]]);
  // re-exports: export { a, b as c } from './mod';
  var reReexport = /export\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"]/g;
  while ((m = reReexport.exec(src)) !== null) {
    var sub = resolveModule(MOD_APPDIR, modFile, m[2]);
    if (!sub) continue;
    var subMap = classifyExports(sub);
    m[1].split(',').forEach(function (part) {
      var seg = part.trim().split(/\s+as\s+/);
      var srcName = seg[0].trim(), localName = (seg[1] || seg[0]).trim();
      if (srcName && localName && subMap[srcName] && !map[localName]) map[localName] = subMap[srcName];
    });
  }
  // export * from './mod';  → inherit all classifications
  var reStar = /export\s*\*\s*from\s*['"]([^'"]+)['"]/g;
  while ((m = reStar.exec(src)) !== null) {
    var sub2 = resolveModule(MOD_APPDIR, modFile, m[1]);
    if (!sub2) continue;
    var subMap2 = classifyExports(sub2);
    Object.keys(subMap2).forEach(function (k) { if (!map[k]) map[k] = subMap2[k]; });
  }
  // resolve local aliases transitively
  var changed = true;
  while (changed) {
    changed = false;
    for (var i = 0; i < aliases.length; i++) {
      if (!map[aliases[i][0]] && map[aliases[i][1]]) { map[aliases[i][0]] = map[aliases[i][1]]; changed = true; }
    }
  }
  return map;
}
// appDir for module resolution inside classifyExports (set in main)
var MOD_APPDIR = null;

// Map each imported identifier in a slice file to its source module file.
function importMap(appDir, sliceFile, src) {
  var map = {};
  var re = /import\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"]/g, m;
  while ((m = re.exec(src)) !== null) {
    var spec = m[2];
    var mod = resolveModule(appDir, sliceFile, spec);
    if (!mod) continue;
    m[1].split(',').forEach(function (part) {
      var name = part.trim().split(/\s+as\s+/).pop().trim(); // local name (handles `x as y`)
      if (name) map[name] = mod;
    });
  }
  return map;
}

// Find each `.addCase(IDENT.(pending|fulfilled|rejected)` and return ranges to cut
// for the non-thunk ones. Range = from the leading `.addCase` to its matching `)`.
function cutNonThunkAddCases(src, isThunk) {
  var cuts = [];
  var re = /\.addCase\(\s*([A-Za-z0-9_$]+)\s*\.\s*(pending|fulfilled|rejected)\b/g, m;
  while ((m = re.exec(src)) !== null) {
    var ident = m[1];
    if (isThunk(ident)) continue;
    // locate the `(` of this addCase call, then balance-scan to its close `)`
    var openParen = src.indexOf('(', m.index);
    var depth = 0, end = -1;
    for (var p = openParen; p < src.length; p++) {
      var c = src[p];
      if (c === '(') depth++;
      else if (c === ')') { depth--; if (depth === 0) { end = p; break; } }
    }
    if (end < 0) continue;
    cuts.push({ start: m.index, end: end + 1, ident: ident });
  }
  return cuts;
}

function processSlice(appDir, sliceFile, opts) {
  var src = fs.readFileSync(sliceFile, 'utf-8');
  if (!/extraReducers/.test(src) || !/\.addCase\(/.test(src)) return null;
  var imap = importMap(appDir, sliceFile, src);
  // CONSERVATIVE: keep unless positively a plain function. isThunk(ident) returns
  // true (KEEP) for thunks AND for anything we can't positively prove is plain.
  function isThunk(ident) {
    var mod = imap[ident];
    if (!mod) return true;                       // unresolved import → KEEP (don't risk a false strip)
    var cls = classifyExports(mod)[ident];
    return cls !== 'plain';                       // strip ONLY when positively 'plain'
  }
  var cuts = cutNonThunkAddCases(src, isThunk);
  if (cuts.length === 0) return null;
  // apply cuts back-to-front so offsets stay valid
  cuts.sort(function (a, b) { return b.start - a.start; });
  var removed = [];
  for (var i = 0; i < cuts.length; i++) {
    src = src.slice(0, cuts[i].start) + src.slice(cuts[i].end);
    removed.push(cuts[i].ident);
  }
  // tidy: collapse any blank-chain artifacts (builder followed by stray whitespace)
  src = src.replace(/(\bbuilder\b)\s*\.\s*\n/g, '$1\n');
  if (src.indexOf(MARKER) === -1) {
    src = src.replace(/(^|\n)(import )/, '$1' + MARKER + ' (stripped non-thunk addCase: ' +
      Array.from(new Set(removed)).join(', ') + ')\n$2');
  }
  if (opts.dryRun) { if (opts.verbose) console.log('  [dry] ' + path.basename(sliceFile) + ' — would strip: ' + removed.join(', ')); return { file: sliceFile, removed: removed }; }
  fs.writeFileSync(sliceFile, src);
  return { file: sliceFile, removed: removed };
}

function main() {
  var args = parseArgs(process.argv);
  var appDir = path.join(args.target, 'app');
  MOD_APPDIR = appDir; // used by classifyExports for re-export resolution
  var featuresDir = path.join(appDir, 'redux/features');
  if (!fs.existsSync(featuresDir)) { console.log('scaffold-redux-thunk-guard: no redux/features — skipping'); return; }
  var slices = fs.readdirSync(featuresDir).filter(function (f) { return /Slice\.ts$/.test(f); });
  var fixed = 0, total = 0;
  slices.forEach(function (f) {
    var r = processSlice(appDir, path.join(featuresDir, f), args);
    if (r && r.removed.length) {
      fixed++; total += r.removed.length;
      console.log('  ' + f + ': stripped non-thunk addCase(s) for ' + Array.from(new Set(r.removed)).join(', '));
    }
  });
  console.log('scaffold-redux-thunk-guard: ' + fixed + ' slice(s) fixed, ' + total + ' non-thunk addCase block(s) removed');
}

main();
