#!/usr/bin/env node
/**
 * normalize-root-reducer.js — emit canonical rootReducer.ts from on-disk slices.
 *
 * Scans `<frontend>/app/redux/features/*Slice.ts`, extracts the default-exported
 * reducer + the slice name, and writes a `rootReducer.ts` that combines them.
 *
 * v62-att2 evidence: scaffold-crud-pages writes 12 slice files but
 * rootReducer.ts still only has auth+user. TS2339 "Property 'notice' does not
 * exist on type {auth, user}" across multiple pages.
 *
 * Each slice file is expected to:
 *   - createSlice({ name: '<sliceName>', ... })  ← slice name
 *   - export default <something>.reducer          ← the reducer
 *
 * Usage:
 *   node .claude/v2/scripts/normalize-root-reducer.js --target <frontend-dir> [--dry-run] [-v]
 */

'use strict';

const fs = require('fs');
const path = require('path');

function parseArgs(argv) {
  const out = {};
  for (let i = 2; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--target') out.target = argv[++i];
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
    else if (a === '--help' || a === '-h') {
      console.log('Usage: normalize-root-reducer --target <frontend-dir> [--dry-run] [-v]');
      process.exit(0);
    } else {
      console.error(`unknown arg: ${a}`);
      process.exit(1);
    }
  }
  if (!out.target) {
    console.error('--target required');
    process.exit(1);
  }
  return out;
}

function main() {
  const args = parseArgs(process.argv);
  const featuresDir = path.join(args.target, 'app', 'redux', 'features');
  const rootReducerPath = path.join(args.target, 'app', 'redux', 'store', 'rootReducer.ts');

  if (!fs.existsSync(featuresDir)) {
    console.log(`normalize-root-reducer: no features dir at ${featuresDir} — skipping`);
    return;
  }

  const sliceFiles = fs.readdirSync(featuresDir)
    .filter((n) => /Slice\.ts$/.test(n));

  if (sliceFiles.length === 0) {
    console.log('normalize-root-reducer: no slice files — skipping');
    return;
  }

  const slices = [];
  for (const fname of sliceFiles) {
    const filePath = path.join(featuresDir, fname);
    const content = fs.readFileSync(filePath, 'utf-8');
    // Extract slice name from createSlice({ name: 'foo', ... })
    const nameMatch = content.match(/createSlice\(\s*\{[^}]*name\s*:\s*['"]([^'"]+)['"]/);
    // Verify default export exists
    const hasDefault = /export\s+default\b/.test(content);
    if (!nameMatch || !hasDefault) {
      if (args.verbose) console.log(`  skip ${fname} — no createSlice name or no default export`);
      continue;
    }
    const sliceName = nameMatch[1];
    const importIdent = `${sliceName}Reducer`;
    const importPath = `~/redux/features/${fname.replace(/\.ts$/, '')}`;
    slices.push({ sliceName, importIdent, importPath });
  }

  if (slices.length === 0) {
    console.log('normalize-root-reducer: no usable slices — skipping');
    return;
  }

  // Deduplicate by sliceName
  const seen = new Map();
  for (const s of slices) if (!seen.has(s.sliceName)) seen.set(s.sliceName, s);
  const sorted = [...seen.values()].sort((a, b) => a.sliceName.localeCompare(b.sliceName));

  const lines = [];
  lines.push("import { combineReducers } from '@reduxjs/toolkit';");
  for (const s of sorted) {
    lines.push(`import ${s.importIdent} from '${s.importPath}';`);
  }
  lines.push('');
  lines.push('/**');
  lines.push(' * rootReducer.ts — generated by normalize-root-reducer.js.');
  lines.push(' * Combines every slice in ~/redux/features/. Edit slice files,');
  lines.push(' * not this aggregator. Regenerated on each frontend build.');
  lines.push(' */');
  lines.push('const rootReducer = combineReducers({');
  for (const s of sorted) {
    lines.push(`  ${s.sliceName}: ${s.importIdent},`);
  }
  lines.push('});');
  lines.push('');
  lines.push('export type RootState = ReturnType<typeof rootReducer>;');
  lines.push('export default rootReducer;');
  lines.push('');
  const rendered = lines.join('\n');

  if (args.dryRun) {
    console.log(`normalize-root-reducer: would write ${rootReducerPath} (${sorted.length} slices)`);
    if (args.verbose) console.log(rendered);
    return;
  }

  fs.mkdirSync(path.dirname(rootReducerPath), { recursive: true });
  fs.writeFileSync(rootReducerPath, rendered);
  console.log(`normalize-root-reducer: wrote ${rootReducerPath} (${sorted.length} slices)`);
  if (args.verbose) {
    for (const s of sorted) console.log(`  - ${s.sliceName}`);
  }
}

main();
