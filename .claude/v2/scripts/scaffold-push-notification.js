#!/usr/bin/env node
// scaffold-push-notification.js — PUSH-NOTIFICATION capability primitive (Tier 2, NestJS/TypeORM).
//
// Distinct from in-app notification CRUD: this is the SEND side — an FCM adapter + a
// trigger dispatcher that, given a trigger key + recipient + vars, renders the template,
// persists the in-app notification, sends the FCM push (with deeplink), and respects
// quiet-hours. The 25 SpoMatch triggers all funnel through one dispatch() call.
//
// MODULE_PLAN.yaml shape:
//   push:
//     provider: fcm
//     notification_entity: Notification
//     quiet_hours: { start: 22, end: 8 }          # local hours; transactional bypass
//     templates:
//       - { key: booking_requested, title: "...", body: "{studentName} requested...", deeplink: "/x/:id", transactional: true }
//       - { key: review_prompt,     title: "...", body: "...", transactional: false }
'use strict';

var fs = require('fs');
var path = require('path');

var MARKER = '// Generated by scaffold-push-notification';

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--spec') out.spec = argv[++i];
    else if (a === '--target') out.target = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.spec || !out.target) { console.error('Usage: scaffold-push-notification --spec MODULE_PLAN.yaml --target BACKEND_DIR'); process.exit(1); }
  return out;
}
function loadYaml() {
  try { return require('yaml'); } catch (_) {}
  try { return require(path.join(require('child_process').execSync('npm root -g', { encoding: 'utf-8' }).trim(), 'yaml')); } catch (_) { return null; }
}
function toKebab(s) { return String(s).replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/[_\s]+/g, '-').toLowerCase(); }
function jsStr(s) { return JSON.stringify(String(s == null ? '' : s)); }

function fileFcmClient() {
  return [
    MARKER,
    "// FCM adapter via firebase-admin. Lazy-inits the app from GOOGLE_APPLICATION_CREDENTIALS",
    "// (or applicationDefault). send() is best-effort — a push failure must NOT fail the",
    "// triggering transaction (the in-app notification is the source of truth).",
    "import { Injectable, Logger } from '@nestjs/common';",
    "import * as admin from 'firebase-admin';",
    '',
    "@Injectable()",
    "export class FcmClient {",
    "  private readonly logger = new Logger('FcmClient');",
    "  private app: admin.app.App | null = null;",
    '',
    "  private init(): admin.app.App | null {",
    "    if (this.app) return this.app;",
    "    try {",
    "      this.app = admin.apps.length ? admin.app() : admin.initializeApp({ credential: admin.credential.applicationDefault() });",
    "      return this.app;",
    "    } catch (e) {",
    "      this.logger.warn('FCM init failed (push disabled): ' + (e as Error).message);",
    "      return null;",
    "    }",
    "  }",
    '',
    "  async send(token: string, title: string, body: string, data?: Record<string, string>): Promise<boolean> {",
    "    const app = this.init();",
    "    if (!app || !token) return false;",
    "    try {",
    "      await admin.messaging(app).send({ token, notification: { title, body }, data: data || {} });",
    "      return true;",
    "    } catch (e) {",
    "      this.logger.warn('FCM send failed: ' + (e as Error).message);",
    "      return false;",
    "    }",
    "  }",
    "}",
    '',
  ].join('\n');
}

function fileTemplates(templates) {
  var rows = templates.map(function (t) {
    return "  " + jsStr(t.key) + ": { title: " + jsStr(t.title || t.key) + ", body: " + jsStr(t.body || '') +
      ", deeplink: " + jsStr(t.deeplink || '') + ", transactional: " + (t.transactional === false ? 'false' : 'true') + " },";
  }).join('\n');
  return [
    MARKER,
    "// Notification template table — the SINGLE source for push copy (code constant,",
    "// change = deploy). {vars} are runtime-substituted. `transactional` templates bypass",
    "// quiet-hours (booking/payment/dispute); non-transactional (marketing/review) batch.",
    "export interface NotificationTemplate { title: string; body: string; deeplink: string; transactional: boolean; }",
    '',
    "export const NOTIFICATION_TEMPLATES: Record<string, NotificationTemplate> = {",
    rows,
    "};",
    '',
    "export function renderTemplate(key: string, vars: Record<string, string | number> = {}): { title: string; body: string; deeplink: string; transactional: boolean } | null {",
    "  const t = NOTIFICATION_TEMPLATES[key];",
    "  if (!t) return null;",
    "  const sub = (s: string) => s.replace(/\\{(\\w+)\\}/g, (_m, k) => (vars[k] != null ? String(vars[k]) : ''));",
    "  return { title: sub(t.title), body: sub(t.body), deeplink: t.deeplink.replace(/:(\\w+)/g, (_m, k) => (vars[k] != null ? String(vars[k]) : ':' + k)), transactional: t.transactional };",
    "}",
    '',
  ].join('\n');
}

function fileQuietHours(qh) {
  var start = (qh && Number(qh.start)) || 22;
  var end = (qh && Number(qh.end)) || 8;
  return [
    MARKER,
    "// Quiet-hours window (local server time; set TZ). Transactional notifications always",
    "// bypass. Non-transactional pushes landing in the window are deferred to QUIET_END.",
    "export const QUIET_START = " + start + "; // hour",
    "export const QUIET_END = " + end + ";   // hour",
    '',
    "export function inQuietHours(now: Date): boolean {",
    "  const h = now.getHours();",
    "  return QUIET_START < QUIET_END ? h >= QUIET_START && h < QUIET_END : h >= QUIET_START || h < QUIET_END;",
    "}",
    '',
    "// Next send time for a deferred (non-transactional) notification: today/tomorrow QUIET_END.",
    "export function nextSendableAt(now: Date): Date {",
    "  if (!inQuietHours(now)) return now;",
    "  const d = new Date(now);",
    "  if (now.getHours() >= QUIET_START) d.setDate(d.getDate() + 1);",
    "  d.setHours(QUIET_END, 0, 0, 0);",
    "  return d;",
    "}",
    '',
  ].join('\n');
}

function fileDispatcher(P) {
  return [
    MARKER,
    "import { Injectable, Logger } from '@nestjs/common';",
    "import { InjectRepository } from '@nestjs/typeorm';",
    "import { Repository } from 'typeorm';",
    "import { FcmClient } from '../../infrastructure/push/fcm.client';",
    "import { renderTemplate } from './notification-templates';",
    "import { inQuietHours } from './quiet-hours';",
    "import { " + P.entity + " } from '../" + P.entityKebab + "/" + P.entityKebab + ".entity';",
    '',
    "// One funnel for every trigger. Persists the in-app notification (source of truth)",
    "// then best-effort FCM push (skipped when non-transactional + in quiet-hours).",
    "@Injectable()",
    "export class NotificationDispatcher {",
    "  private readonly logger = new Logger('NotificationDispatcher');",
    "  constructor(",
    "    private readonly fcm: FcmClient,",
    "    @InjectRepository(" + P.entity + ") private readonly notifications: Repository<" + P.entity + ">,",
    "  ) {}",
    '',
    "  async dispatch(triggerKey: string, recipient: { userId: string; fcmToken?: string | null }, vars: Record<string, string | number> = {}): Promise<void> {",
    "    const t = renderTemplate(triggerKey, vars);",
    "    if (!t) { this.logger.warn('unknown trigger ' + triggerKey); return; }",
    "    // persist in-app notification (always)",
    "    const n = this.notifications.create({ userId: recipient.userId, type: triggerKey, title: t.title, body: t.body, deeplink: t.deeplink, isRead: false } as any);",
    "    await this.notifications.save(n);",
    "    // push: transactional always; non-transactional skipped during quiet-hours",
    "    if (!t.transactional && inQuietHours(new Date())) return;",
    "    if (recipient.fcmToken) {",
    "      await this.fcm.send(recipient.fcmToken, t.title, t.body, t.deeplink ? { deeplink: t.deeplink } : undefined);",
    "    }",
    "  }",
    "}",
    '',
  ].join('\n');
}

function filePushModule(P) {
  return [
    MARKER,
    "import { Module } from '@nestjs/common';",
    "import { TypeOrmModule } from '@nestjs/typeorm';",
    "import { FcmClient } from '../../infrastructure/push/fcm.client';",
    "import { NotificationDispatcher } from './notification-dispatcher.service';",
    "import { " + P.entity + " } from '../" + P.entityKebab + "/" + P.entityKebab + ".entity';",
    '',
    "@Module({",
    "  imports: [TypeOrmModule.forFeature([" + P.entity + "])],",
    "  providers: [FcmClient, NotificationDispatcher],",
    "  exports: [NotificationDispatcher],",
    "})",
    "export class PushNotificationModule {}",
    '',
  ].join('\n');
}

function ensureDeps(target, dryRun, verbose) {
  var pkgPath = path.join(target, 'package.json');
  if (!fs.existsSync(pkgPath)) return;
  var pkg; try { pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8')); } catch (_) { return; }
  pkg.dependencies = pkg.dependencies || {};
  if (!pkg.dependencies['firebase-admin']) { pkg.dependencies['firebase-admin'] = '^12.0.0';
    if (!dryRun) fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
    if (verbose) console.log('  added firebase-admin to package.json'); }
}

function writeFile(target, rel, content, args) {
  var full = path.join(target, rel);
  if (fs.existsSync(full) && !args.force) {
    var cur = fs.readFileSync(full, 'utf-8');
    if (cur.indexOf(MARKER) === -1) { if (args.verbose) console.log('  skip (hand-authored): ' + rel); return false; }
  }
  if (args.dryRun) { if (args.verbose) console.log('  [dry] ' + rel); return true; }
  var dir = path.dirname(full);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(full, content);
  return true;
}

function main() {
  var args = parseArgs(process.argv);
  if (!fs.existsSync(args.spec)) { console.log('scaffold-push-notification: no MODULE_PLAN — skipping'); return; }
  var yaml = loadYaml();
  if (!yaml) { console.log('scaffold-push-notification: yaml unavailable — skipping'); return; }
  var spec; try { spec = yaml.parse(fs.readFileSync(args.spec, 'utf-8')); } catch (e) { console.log('scaffold-push-notification: bad YAML — skipping'); return; }
  var push = spec && spec.push;
  if (!push) { console.log('scaffold-push-notification: no `push:` — skipping'); return; }
  if (push.provider && push.provider !== 'fcm') { console.log('scaffold-push-notification: provider ' + push.provider + ' not supported (v1=fcm) — skipping'); return; }

  var P = { entity: push.notification_entity || 'Notification' };
  P.entityKebab = toKebab(P.entity);
  var templates = Array.isArray(push.templates) ? push.templates.filter(function (t) { return t && t.key; }) : [];

  console.log('scaffold-push-notification: FCM dispatcher + ' + templates.length + ' template(s) + quiet-hours');
  ensureDeps(args.target, args.dryRun, args.verbose);
  var n = 0;
  [
    ['src/infrastructure/push/fcm.client.ts', fileFcmClient()],
    ['src/modules/notifications/notification-templates.ts', fileTemplates(templates)],
    ['src/modules/notifications/quiet-hours.ts', fileQuietHours(push.quiet_hours)],
    ['src/modules/notifications/notification-dispatcher.service.ts', fileDispatcher(P)],
    ['src/modules/notifications/push-notification.module.ts', filePushModule(P)],
  ].forEach(function (f) { if (writeFile(args.target, f[0], f[1], args)) n++; });
  console.log('scaffold-push-notification: ' + n + ' file(s) ' + (args.dryRun ? '(dry)' : 'written') + '. Register PushNotificationModule + inject NotificationDispatcher.dispatch(triggerKey, recipient, vars).');
}

main();
