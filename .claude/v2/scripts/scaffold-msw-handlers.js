#!/usr/bin/env node
// scaffold-msw-handlers.js — v74 generates MSW mock handlers per route
// in PROJECT_API.md. Pairs with v73's scaffold-frontend-test-config
// (which sets up the MSW server with default catch-all handlers).
// Component tests use these handlers to assert API integration without
// hitting a real backend.
'use strict';

var fs = require('fs');
var path = require('path');

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--api') out.api = argv[++i];
    else if (a === '--target') out.target = argv[++i];
    else if (a === '--api-prefix') out.apiPrefix = argv[++i];
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.api || !out.target) { console.error('Usage: scaffold-msw-handlers --api PROJECT_API.md --target FRONTEND_DIR [--api-prefix api]'); process.exit(1); }
  out.apiPrefix = out.apiPrefix || 'api';
  return out;
}

function extractEndpoints(apiMd) {
  // Match `#### METHOD `/path/...` ` lines.
  var endpoints = [];
  var re = /^####\s+(GET|POST|PATCH|PUT|DELETE)\s+`(\S+)`(.*)$/gm;
  var m;
  while ((m = re.exec(apiMd)) !== null) {
    endpoints.push({ method: m[1], path: m[2], note: (m[3] || '').trim() });
  }
  return endpoints;
}

function defaultResponse(method, route) {
  // 204 for DELETE; created for POST without specific shape; list for GET on collection;
  // object for GET on resource; etc.
  // v89: 'null' body causes TS2322 — MSW v2 HttpResponse signature rejects bare
  // null. Use `new Response(null, ...)` which DOES accept null body.
  if (method === 'DELETE') return { status: 204, body: 'new Response(null, { status: 204 })' };
  if (/\/auth\/login$/.test(route)) {
    return { status: 200, body: "HttpResponse.json({ user: { id: 'mock', email: 'mock@test', role: 'admin' } })" };
  }
  if (/\/auth\/signup$/.test(route)) {
    return { status: 201, body: "HttpResponse.json({ user: { id: 'mock', email: 'mock@test', role: 'user' } }, { status: 201 })" };
  }
  if (/\/auth\/logout$/.test(route)) {
    return { status: 204, body: 'new Response(null, { status: 204 })' };
  }
  if (/\/auth\/me$|\/auth\/status$/.test(route)) {
    return { status: 200, body: "HttpResponse.json({ id: 'mock', email: 'mock@test', role: 'admin' })" };
  }
  if (method === 'GET' && !/\/:[a-z]+/.test(route) && !/\/[a-f0-9-]{8,}/i.test(route)) {
    // Collection GET
    return { status: 200, body: "HttpResponse.json({ items: [], total: 0, page: 1, limit: 10, totalPages: 0 })" };
  }
  if (method === 'GET') {
    return { status: 200, body: "HttpResponse.json({ id: 'mock' })" };
  }
  if (method === 'POST') {
    return { status: 201, body: "HttpResponse.json({ id: 'mock' }, { status: 201 })" };
  }
  if (method === 'PATCH' || method === 'PUT') {
    return { status: 200, body: "HttpResponse.json({ id: 'mock' })" };
  }
  return { status: 200, body: 'HttpResponse.json({})' };
}

function toMswPath(route, apiPrefix) {
  // Convert NestJS `:id` placeholders to MSW `:id` (same syntax). Prefix with /api.
  return '*/' + apiPrefix + route;
}

function main() {
  var args = parseArgs(process.argv);
  if (!fs.existsSync(args.api)) {
    console.log('scaffold-msw-handlers: PROJECT_API.md missing — skipping');
    return;
  }
  var apiMd = fs.readFileSync(args.api, 'utf-8');
  var endpoints = extractEndpoints(apiMd);
  if (endpoints.length === 0) {
    console.log('scaffold-msw-handlers: no endpoints found in ' + args.api);
    return;
  }

  // Group by section (heuristic: first path segment)
  var lines = [
    "/**",
    " * Generated by scaffold-msw-handlers from PROJECT_API.md.",
    " *",
    " * Default-pass handlers for every documented endpoint. Component",
    " * tests can override per-suite via `server.use(http...())`.",
    " *",
    " * Imported by tests/msw-server.ts via `import { handlers } from './msw-handlers'`",
    " * and spread into setupServer(...handlers).",
    " */",
    "import { http, HttpResponse } from 'msw';",
    "",
    "export const handlers = [",
  ];
  var seen = new Set();
  endpoints.forEach(function (ep) {
    var key = ep.method + ' ' + ep.path;
    if (seen.has(key)) return;
    seen.add(key);
    var resp = defaultResponse(ep.method, ep.path);
    var mswPath = toMswPath(ep.path, args.apiPrefix);
    var fn = ep.method.toLowerCase();
    lines.push("  http." + fn + "(" + JSON.stringify(mswPath) + ", () => " + resp.body + "),");
  });
  lines.push("];");
  lines.push("");

  var dst = path.join(args.target, 'tests/msw-handlers.ts');
  if (args.dryRun) {
    console.log('  [dry] would write ' + dst + ' with ' + seen.size + ' handlers');
    return;
  }
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.writeFileSync(dst, lines.join('\n'));
  console.log('scaffold-msw-handlers: wrote ' + seen.size + ' handlers to ' + path.relative(args.target, dst));
}

main();
