#!/usr/bin/env node
// scaffold-service-from-controller.js — v78 walks backend controllers and
// emits matching `app/services/httpServices/<feature>Service.ts` on the
// frontend. Eliminates the v76 "missing endpoint" P0 crashes (frontend
// called a route the backend doesn't expose) and the
// `fetchUserList vs fetchUsers` thunk-name drift class.
//
// Parses:
//   - @Controller('prefix')                       → route prefix
//   - `extends BaseController<E, CreateDto, UpdateDto>`  → inherits 5 CRUD methods
//   - Explicit @Get/@Post/@Put/@Patch/@Delete    → custom methods
//
// Emits per controller, one FE service file with:
//   - createAsyncThunk for READs (findAll/findOne + custom @Get)
//   - plain async function for MUTATIONs (create/update/remove + custom @Post/@Put/@Patch/@Delete)
//   - common name aliases (fetchUserList → fetchUsers, fetchUser → fetchUserById)
//
// Idempotent. Marker: '// Generated by scaffold-service-from-controller'.
// If file exists without marker (LLM-authored), skip unless --force.
'use strict';

var fs = require('fs');
var path = require('path');

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--backend-dir') out.backendDir = argv[++i];
    else if (a === '--target') out.target = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.backendDir || !out.target) {
    console.error('Usage: scaffold-service-from-controller --backend-dir BACKEND --target FRONTEND [--force]');
    process.exit(1);
  }
  return out;
}

function walk(dir, filterFn, out) {
  out = out || [];
  if (!fs.existsSync(dir)) return out;
  fs.readdirSync(dir, { withFileTypes: true }).forEach(function (e) {
    var f = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (/^(node_modules|dist|\.git|coverage|test|__tests__)$/.test(e.name)) return;
      walk(f, filterFn, out);
    } else if (e.isFile() && filterFn(f)) out.push(f);
  });
  return out;
}

function toPascal(s) {
  return s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').split(/[-_\s\/]+/).filter(Boolean).map(function (w) {
    return w[0].toUpperCase() + w.slice(1).toLowerCase();
  }).join('');
}
function toCamel(s) {
  var p = toPascal(s);
  return p[0].toLowerCase() + p.slice(1);
}
// v93: scaffold-api-client-types emits file names as kebab-case
// (e.g. types/refund-record.d.ts). Controller @Controller('refund_records')
// would singularize to 'refund_record' (snake-case) and miss the type file.
// Always normalize to kebab before using as a file path.
function toKebab(s) {
  return s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/[_\s\/]+/g, '-').toLowerCase();
}
function singularize(s) {
  if (/ies$/i.test(s)) return s.replace(/ies$/i, 'y');
  if (/ses$/i.test(s)) return s.replace(/ses$/i, 's');
  if (/s$/i.test(s) && !/ss$/i.test(s)) return s.replace(/s$/i, '');
  return s;
}
function pluralize(s) {
  if (/y$/i.test(s) && !/[aeiou]y$/i.test(s)) return s.replace(/y$/i, 'ies');
  if (/s$/i.test(s)) return s;
  return s + 's';
}

function parseController(content) {
  // Returns { prefix, className, extendsBase: true|false, methods: [{verb, route, name}] }
  var prefix = '';
  var pm = /@Controller\(\s*['"]([^'"]*)['"]\s*\)/.exec(content);
  if (pm) prefix = pm[1];
  var classMatch = /export\s+class\s+(\w+)/.exec(content);
  var className = classMatch ? classMatch[1] : null;
  var extendsBase = /extends\s+BaseController\b/.test(content);
  var methods = [];
  // Match: @Get('path?') ... methodName(...): ReturnType { OR  @Get() methodName(...)
  var re = /@(Get|Post|Put|Patch|Delete)\(\s*(?:['"]([^'"]*)['"])?\s*\)\s*[\s\S]*?(?:^|\n)\s*(?:async\s+)?(\w+)\s*\(/gm;
  var m;
  while ((m = re.exec(content)) !== null) {
    methods.push({ verb: m[1].toUpperCase(), route: m[2] || '', name: m[3] });
  }
  return { prefix: prefix, className: className, extendsBase: extendsBase, methods: methods };
}

function generatedMarker() {
  return '// Generated by scaffold-service-from-controller — DO NOT EDIT BY HAND. Re-run when backend controllers change.';
}

function joinPath(prefix, route) {
  var a = prefix.replace(/^\/+|\/+$/g, '');
  var b = (route || '').replace(/^\/+|\/+$/g, '');
  if (!a && !b) return '/';
  if (!a) return '/' + b;
  if (!b) return '/' + a;
  return '/' + a + '/' + b;
}

function pathWithParams(p) {
  // Convert NestJS `:id` to JS template literal placeholder
  return p.replace(/:([A-Za-z_]\w*)/g, '${' + '$1}');
}

function pathParams(p) {
  var out = [];
  var re = /:([A-Za-z_]\w*)/g; var m;
  while ((m = re.exec(p)) !== null) out.push(m[1]);
  return out;
}

function emitService(feature, entityKebab, parsed) {
  // feature: 'company-management' (controller file basename without .controller.ts)
  // entityKebab: 'company' (singular pulled from route prefix preferably)
  var entityCamel = toCamel(entityKebab); // 'company'
  var entityPascal = toPascal(entityKebab); // 'Company'
  var entityPlural = pluralize(entityCamel); // 'companies' — used for thunk names
  var thunkSlice = entityCamel; // slice name prefix in createAsyncThunk

  var lines = [];
  lines.push(generatedMarker());
  lines.push("import { createAsyncThunk } from '@reduxjs/toolkit';");
  lines.push("import { get } from '~/services/httpMethods/get';");
  lines.push("import { post } from '~/services/httpMethods/post';");
  lines.push("import { put } from '~/services/httpMethods/put';");
  lines.push("import { patch } from '~/services/httpMethods/patch';");
  lines.push("import { del } from '~/services/httpMethods/del';");
  // v97: only emit the canonical CRUD imports when the controller extends
  // BaseController (and we'll actually use Create/Update/Response inline).
  // Non-CRUD controllers (workflow, custom routes) don't have those DTOs
  // in their types file — importing them caused TS2305 "no exported member
  // CreateXxxRequest" in v96 for service-application + similar modules.
  // For non-CRUD, just import everything via wildcard so consumer code that
  // uses specific names still resolves (TS won't complain about unused
  // wildcard imports).
  if (parsed.extendsBase) {
    lines.push("import type {");
    lines.push("  Create" + entityPascal + "Request,");
    lines.push("  Update" + entityPascal + "Request,");
    lines.push("  " + entityPascal + "Response,");
    // v93: force kebab — `entityKebab` here may actually be snake_case if it
    // came from a snake-cased @Controller route. The types file is always
    // kebab-case per scaffold-api-client-types naming.
    lines.push("} from '~/types/" + toKebab(entityKebab) + "';");
  } else {
    // Non-CRUD controllers: emit type-only namespace import so callers
    // (LLM-emitted page files, custom hooks) can still reference
    // `XxxTypes.SomeMember` as a TYPE. Don't add a `void XxxTypes;`
    // suppressor — that's what v99b broke on (TS1361 "X cannot be used
    // as a value because it was imported using 'import type'"). TS doesn't
    // error on unused imports by default, so the suppressor was never
    // needed in the first place.
    lines.push("import type * as " + entityPascal + "Types from '~/types/" + toKebab(entityKebab) + "';");
  }
  lines.push('');

  var prefix = parsed.prefix || pluralize(entityKebab);
  var basePath = '/' + prefix.replace(/^\/+|\/+$/g, '');

  // Standard BaseController methods (always emit if extendsBase)
  if (parsed.extendsBase) {
    // fetchAll
    lines.push('export const fetch' + toPascal(entityPlural) + ' = createAsyncThunk(');
    lines.push("  '" + thunkSlice + "/fetchAll',");
    lines.push('  async (params?: Record<string, unknown>) => {');
    lines.push("    const res = await get<{ items: " + entityPascal + "Response[]; total: number; page: number; limit: number; totalPages: number }>('" + basePath + "', { params });");
    lines.push('    return res;');
    lines.push('  },');
    lines.push(');');
    lines.push('');
    // fetchById
    lines.push('export const fetch' + entityPascal + 'ById = createAsyncThunk(');
    lines.push("  '" + thunkSlice + "/fetchById',");
    lines.push('  async (id: string) => {');
    lines.push("    const res = await get<" + entityPascal + "Response>(`" + basePath + "/${id}`);");
    lines.push('    return res;');
    lines.push('  },');
    lines.push(');');
    lines.push('');
    // create
    lines.push('export async function create' + entityPascal + '(data: Create' + entityPascal + 'Request): Promise<' + entityPascal + 'Response> {');
    lines.push("  const res = await post<" + entityPascal + "Response>('" + basePath + "', data);");
    lines.push('  return res;');
    lines.push('}');
    lines.push('');
    // update
    lines.push('export async function update' + entityPascal + '(id: string, data: Update' + entityPascal + 'Request): Promise<' + entityPascal + 'Response> {');
    lines.push('  const res = await patch<' + entityPascal + 'Response>(`' + basePath + '/${id}`, data);');
    lines.push('  return res;');
    lines.push('}');
    lines.push('');
    // delete
    lines.push('export async function delete' + entityPascal + '(id: string): Promise<void> {');
    lines.push('  await del<void>(`' + basePath + '/${id}`);');
    lines.push('}');
    lines.push('');
    // common aliases LLM-generated pages reach for
    lines.push('// LLM-friendly aliases — same thunk under common alternate names.');
    lines.push('export const fetch' + entityPascal + 'List = fetch' + toPascal(entityPlural) + ';');
    lines.push('export const fetch' + entityPascal + ' = fetch' + entityPascal + 'ById;');
    lines.push('export const remove' + entityPascal + ' = delete' + entityPascal + ';');
    lines.push('');
  }

  // Custom @Get/@Post/@etc methods — skip ones already covered by BaseController
  var seenStandard = parsed.extendsBase ? { findAll: true, findOne: true, create: true, update: true, remove: true } : {};
  parsed.methods.forEach(function (m) {
    if (seenStandard[m.name]) return;
    var fullPath = joinPath(prefix, m.route);
    var params = pathParams(fullPath);
    var paramArgs = params.map(function (p) { return p + ': string'; }).join(', ');
    var pathExpr = '`' + pathWithParams(fullPath) + '`';

    var thunkName = toCamel(m.name);
    if (m.verb === 'GET') {
      // Emit as createAsyncThunk
      var argType = params.length === 0 ? 'void' :
                    params.length === 1 ? 'string' :
                    '{ ' + params.map(function (p) { return p + ': string'; }).join('; ') + ' }';
      // v97: when no params, must emit '()' explicitly. Empty string emits
      // 'async  => {' which fails TS parsing ('await outside async') because
      // 'async' is parsed as an identifier rather than the arrow-fn modifier.
      var thunkPayloadArg = params.length === 0 ? '()' :
                            params.length === 1 ? '(' + params[0] + ': string)' :
                            '(args: { ' + params.map(function (p) { return p + ': string'; }).join('; ') + ' })';
      lines.push('export const ' + thunkName + ' = createAsyncThunk(');
      lines.push("  '" + thunkSlice + "/" + m.name + "',");
      lines.push('  async ' + thunkPayloadArg + ' => {');
      if (params.length === 0) {
        lines.push("    const res = await get('" + fullPath + "');");
      } else if (params.length === 1) {
        lines.push('    const res = await get(`' + pathWithParams(fullPath) + '`);');
      } else {
        lines.push('    const { ' + params.join(', ') + ' } = args;');
        lines.push('    const res = await get(`' + pathWithParams(fullPath) + '`);');
      }
      lines.push('    return res;');
      lines.push('  },');
      lines.push(');');
      lines.push('');
    } else {
      // POST/PUT/PATCH/DELETE — plain async function
      var bodyArg = m.verb === 'DELETE' ? '' : ', data: Record<string, unknown>';
      var allArgs = paramArgs + (bodyArg ? (paramArgs ? bodyArg : bodyArg.slice(2)) : '');
      var verbFn = m.verb === 'POST' ? 'post' : m.verb === 'PUT' ? 'put' : m.verb === 'PATCH' ? 'patch' : 'del';
      lines.push('export async function ' + thunkName + '(' + allArgs + '): Promise<unknown> {');
      if (m.verb === 'DELETE') {
        lines.push('  const res = await del(' + pathExpr + ');');
      } else {
        lines.push('  const res = await ' + verbFn + '(' + pathExpr + ', data);');
      }
      lines.push('  return res;');
      lines.push('}');
      lines.push('');
    }
  });

  // v103: emit naming-convention aliases for LLM-emitted page files that
  // expect the conventional verb-prefixed names. Scaffold emits backend
  // route names verbatim (e.g. `transition`, `availableActions`); LLM
  // pages tend to import `applyTransition`, `fetchAvailableActions`,
  // `fetchList`, etc. Without aliases, TS2305/TS2724 cascades hit every
  // page that uses the service — v102 frontend admin-dashboard cell had
  // multiple of these. The aliases are cheap (one `export const` per
  // method name) and have no runtime cost since they re-export the same
  // function reference.
  var aliasable = [];
  parsed.methods.forEach(function (m) {
    var n = m.name;
    // Skip if already conventional or BaseController-emitted
    if (/^(fetch|create|update|delete|apply|list)/.test(n)) return;
    // Verb prefix to apply based on HTTP method
    var prefix = null;
    if (m.verb === 'GET') prefix = (n === 'availableActions' ? 'fetch' : 'fetch');
    else if (m.verb === 'POST' && /^(transition|action|process|execute|run|trigger)$/.test(n)) prefix = 'apply';
    else if (m.verb === 'POST') prefix = 'create';
    else if (m.verb === 'PUT' || m.verb === 'PATCH') prefix = 'update';
    else if (m.verb === 'DELETE') prefix = 'delete';
    if (!prefix) return;
    var aliasName = prefix + n.charAt(0).toUpperCase() + n.slice(1);
    if (aliasName === n) return;
    aliasable.push({ alias: aliasName, target: n });
  });
  if (aliasable.length > 0) {
    lines.push('// v103: aliases for naming conventions LLM-emitted pages tend to use.');
    lines.push('// No runtime cost — same function reference re-exported under a verb-prefixed name.');
    aliasable.forEach(function (a) {
      lines.push('export const ' + a.alias + ' = ' + a.target + ';');
    });
    lines.push('');
  }

  return lines.join('\n');
}

function writeIfManaged(file, content, force, dryRun) {
  if (fs.existsSync(file)) {
    var existing = fs.readFileSync(file, 'utf-8');
    // Recognize BOTH our own marker AND scaffold-crud-pages' marker as
    // managed — scaffold-crud-pages writes a stub service per entity with
    // `Generated by scaffold-crud-pages` on line 1. Without this we'd skip
    // every crud-pages service in v78, defeating the whole purpose of
    // this scaffold.
    var isManaged = /Generated by scaffold-service-from-controller/.test(existing)
                  || /Generated by scaffold-crud-pages/.test(existing);
    if (!isManaged && !force) {
      return { written: false, reason: 'exists-handauthored' };
    }
    if (existing === content) return { written: false, reason: 'unchanged' };
  }
  if (dryRun) return { written: false, reason: 'dry-run' };
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return { written: true };
}

function main() {
  var args = parseArgs(process.argv);
  var modulesDir = path.join(args.backendDir, 'src/modules');
  var controllers = walk(modulesDir, function (f) { return /\.controller\.ts$/.test(f); }, []);
  if (controllers.length === 0) {
    console.log('scaffold-service-from-controller: no controllers under ' + modulesDir);
    return;
  }
  var written = 0, skipped = 0;
  controllers.forEach(function (cf) {
    var content = fs.readFileSync(cf, 'utf-8');
    var parsed = parseController(content);
    if (!parsed.className) {
      if (args.verbose) console.log('  skip (no class): ' + cf);
      return;
    }
    // FE service filename: derive from controller's FILENAME (1:1 mapping),
    // not from @Controller prefix. The prefix can be a deep path like
    // 'admin/payment' which would collide many controllers under one
    // adminService.ts. The controller filename uniquely identifies the
    // controller, so `admin-user.controller.ts` → `adminUserService.ts`.
    var controllerBase = path.basename(cf, '.controller.ts');
    // v115: auth is SPECIAL — the template _auth module ships a self-consistent
    // authService that exports loginThunk/signupThunk/fetchMeThunk, which the
    // template authSlice imports. Regenerating authService from the auth
    // controller as generic CRUD (me/getStatus/fetchMe) breaks those imports →
    // "loginThunk is not exported by authService" → frontend build dies. Leave
    // authService to the template / scaffold-auth-pages.
    if (/^auth$/.test(controllerBase)) {
      if (args.verbose) console.log('  skip (auth — owned by template/scaffold-auth-pages): ' + path.basename(cf));
      skipped++;
      return;
    }
    var fileEntity = toCamel(controllerBase);
    var dst = path.join(args.target, 'app/services/httpServices', fileEntity + 'Service.ts');
    // The exported function names + types still derive from the @Controller
    // route's terminal RESOURCE segment (entity from resource path).
    // v106 fix: skip URL parameter segments (`:id`, `{id}`) — for routes
    // like @Controller('applications/:id'), the last segment is `:id`
    // which produced `import type * as :idTypes from '~/types/:id'`
    // (invalid TS, broke v106 frontend cells with 13 typecheck errors each).
    var typeEntityKebab;
    if (parsed.prefix) {
      var segments = parsed.prefix.replace(/^\/+|\/+$/g, '').split('/')
        .filter(function (s) { return s && !/^[:{]/.test(s); });
      typeEntityKebab = segments.length > 0
        ? singularize(segments[segments.length - 1])
        : controllerBase;
    } else {
      typeEntityKebab = controllerBase;
    }
    var content2 = emitService(controllerBase, typeEntityKebab, parsed);
    var r = writeIfManaged(dst, content2, args.force, args.dryRun);
    if (r.written) written++; else skipped++;
    if (args.verbose) console.log('  ' + path.basename(cf) + ' → ' + fileEntity + 'Service.ts: ' + (r.written ? 'wrote' : r.reason));
  });
  console.log('scaffold-service-from-controller: ' + written + ' written, ' + skipped + ' skipped');
}

main();
