#!/usr/bin/env node
// scaffold-redux-store.js — regenerates frontend/app/redux/store/rootReducer.ts
// to import + combine EVERY <Name>Slice.ts found under app/redux/features/.
//
// Fixes v66 cascade: LLM wrote individual slice files but forgot to wire
// them into rootReducer → useAppSelector((s) => s.auth) fails type check
// (TS2339). The deterministic fix: just enumerate the directory.
'use strict';

var fs = require('fs');
var path = require('path');

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--target') out.target = argv[++i];
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.target) {
    console.error('Usage: scaffold-redux-store --target FRONTEND_DIR');
    process.exit(1);
  }
  return out;
}

function main() {
  var args = parseArgs(process.argv);
  var featuresDir = path.join(args.target, 'app/redux/features');
  if (!fs.existsSync(featuresDir)) {
    console.log('scaffold-redux-store: no app/redux/features — skipping (' + featuresDir + ')');
    return;
  }
  var entries = fs.readdirSync(featuresDir, { withFileTypes: true });
  var slices = [];
  for (var i = 0; i < entries.length; i++) {
    var e = entries[i];
    if (!e.isFile()) continue;
    if (!/Slice\.ts$/.test(e.name)) continue;
    var base = e.name.replace(/\.ts$/, '');           // applicationSlice
    var reducerName = base.replace(/Slice$/, '');     // application
    if (!reducerName) continue;
    slices.push({ base: base, key: reducerName });
  }
  if (slices.length === 0) {
    console.log('scaffold-redux-store: no *Slice.ts files in features/ — skipping');
    return;
  }
  // Stable ordering: alphabetical by key
  slices.sort(function (a, b) { return a.key < b.key ? -1 : (a.key > b.key ? 1 : 0); });

  var imports = slices.map(function (s) {
    return "import " + s.key + "Reducer from '~/redux/features/" + s.base + "';";
  }).join('\n');
  var combine = slices.map(function (s) {
    return '  ' + s.key + ': ' + s.key + 'Reducer,';
  }).join('\n');

  var rootReducer = [
    "// Generated by scaffold-redux-store. Aggregates every <Name>Slice.ts found",
    "// under app/redux/features/. Re-run on each frontend phase to pick up new",
    "// slices the LLM has authored.",
    "import { combineReducers } from '@reduxjs/toolkit';",
    imports,
    "",
    "const rootReducer = combineReducers({",
    combine,
    "});",
    "",
    "export type RootState = ReturnType<typeof rootReducer>;",
    "export default rootReducer;",
    ""
  ].join('\n');

  var dst = path.join(args.target, 'app/redux/store/rootReducer.ts');
  if (args.dryRun) {
    console.log('  [dry] would write ' + path.relative(args.target, dst));
    console.log('  slices wired: ' + slices.map(function (s) { return s.key; }).join(', '));
    return;
  }
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.writeFileSync(dst, rootReducer);
  console.log('scaffold-redux-store: wrote ' + path.relative(args.target, dst) + ' with ' + slices.length + ' slices (' + slices.map(function (s) { return s.key; }).join(', ') + ')');
}

main();
