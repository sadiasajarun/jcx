#!/usr/bin/env node
// scaffold-django-models.js — Django/DRF analog of scaffold-entities.js.
// Derives Django model classes from PROJECT_DATABASE.md tables (the SAME
// stack-agnostic contract doc the NestJS scaffold reads). Multi-stack: selected
// when tech_stack.backend=django via stack-aware findBlueprint.
//
// Output: one `<table>/models.py` per parsed table under <target>/. Each model:
//   - extends BaseModel (core/models.py — UUID pk + timestamps + soft delete),
//     mirroring NestJS BaseEntity
//   - one field per source row with SQL→Django type mapping (VARCHAR→CharField,
//     SMALLINT→SmallIntegerField, BOOLEAN→BooleanField, TIMESTAMPTZ→DateTimeField,
//     UUID→UUIDField, JSONB→JSONField, …)
//   - FK columns (`*_id` with `FK → table(id)`) → models.ForeignKey(... db_column)
//   - Meta.db_table = source table name; Meta.indexes per `IDX_*` declaration
//
// Django field names = snake_case column names (matches the DB), so no camelCase
// remap is needed (unlike the NestJS port). Marker-idempotent + --force.
'use strict';

var fs = require('fs');
var path = require('path');

var MARKER = '# Generated by scaffold-django-models';

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--db') out.db = argv[++i];
    else if (a === '--target') out.target = argv[++i];
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
    else if (a === '--force') out.force = true;
  }
  if (!out.db || !out.target) {
    console.error('Usage: scaffold-django-models --db PROJECT_DATABASE.md --target BACKEND_DIR [--force]');
    process.exit(1);
  }
  return out;
}

function toPascal(s) {
  return s.split(/[-_\s]+/).filter(Boolean).map(function (w) {
    return w[0].toUpperCase() + w.slice(1).toLowerCase();
  }).join('');
}
function singularize(s) {
  if (/ies$/.test(s)) return s.replace(/ies$/, 'y');
  if (/ses$/.test(s)) return s.replace(/es$/, '');
  if (/s$/.test(s)) return s.replace(/s$/, '');
  return s;
}

// --- stack-agnostic contract parser (ported verbatim from scaffold-entities) ---
function parseDatabase(dbMd) {
  var sections = dbMd.split(/^### /m);
  var entities = [];
  for (var i = 1; i < sections.length; i++) {
    var s = sections[i];
    var firstLine = s.split(/\r?\n/)[0].trim();
    if (!/^[a-z][a-z0-9_]*$/i.test(firstLine)) continue;
    if (/Enum$/i.test(firstLine)) continue;
    var entity = { table: firstLine, columns: [], indexes: [] };
    entity.name = singularize(firstLine);
    var lines = s.split(/\r?\n/);
    var inTable = false;
    for (var j = 1; j < lines.length; j++) {
      var line = lines[j];
      if (/^\| Column \| Type/i.test(line)) { inTable = true; continue; }
      if (inTable && /^\|\s*-+/.test(line)) continue;
      if (inTable) {
        if (!/^\|/.test(line)) { inTable = false; continue; }
        var parts = line.split('|').map(function (p) { return p.trim(); });
        if (parts.length < 4) continue;
        entity.columns.push({
          column: parts[1].replace(/`/g, ''),
          type: parts[2] || '',
          constraints: parts[3] || '',
          description: parts[4] || '',
        });
      }
      var idxMatch = /^- `([A-Za-z0-9_]+)`\s+on\s+`([^`]+)`/.exec(line);
      if (idxMatch) entity.indexes.push({ name: idxMatch[1], on: idxMatch[2] });
    }
    if (entity.columns.length === 0) continue;
    entities.push(entity);
  }
  return entities;
}

// SQL type → Django field constructor (without options).
function mapType(typeStr) {
  var t = typeStr.toUpperCase();
  if (/SMALLINT/.test(t)) return { field: 'SmallIntegerField' };
  if (/BIGINT/.test(t)) return { field: 'BigIntegerField' };
  if (/INT|INTEGER/.test(t)) return { field: 'IntegerField' };
  if (/NUMERIC|DECIMAL/.test(t)) return { field: 'DecimalField', extra: ['max_digits=18', 'decimal_places=2'] };
  if (/BOOLEAN/.test(t)) return { field: 'BooleanField' };
  if (/TIMESTAMP/.test(t)) return { field: 'DateTimeField' };
  if (/DATE/.test(t)) return { field: 'DateField' };
  if (/UUID/.test(t)) return { field: 'UUIDField' };
  var v = /VARCHAR\((\d+)\)/i.exec(typeStr);
  if (v) return { field: 'CharField', extra: ['max_length=' + v[1]] };
  if (/TEXT/.test(t)) return { field: 'TextField' };
  if (/JSON/.test(t)) return { field: 'JSONField', json: true };
  return { field: 'CharField', extra: ['max_length=255'] };
}

function pyDefault(defVal, fieldType) {
  var d = defVal.trim();
  if (/NOW\(\)|CURRENT_TIMESTAMP/i.test(d)) return 'timezone.now';
  if (/^TRUE$/i.test(d)) return 'True';
  if (/^FALSE$/i.test(d)) return 'False';
  if (/^\d+$/.test(d)) return d;
  if (/^'([^']*)'$/.test(d)) return '"' + d.replace(/^'|'$/g, '') + '"';
  if (/uuid/i.test(d)) return 'uuid.uuid4';
  return null;
}

function renderModel(entity, allTables) {
  var modelName = toPascal(entity.name);
  var fieldLines = [];
  var needTimezone = false;
  var needUuid = false;

  entity.columns.forEach(function (c) {
    if (/^(id|created_at|updated_at|deleted_at)$/i.test(c.column)) return; // from BaseModel

    var notNull = /NOT NULL/i.test(c.constraints);
    var unique = /UNIQUE/i.test(c.constraints);
    var defMatch = /DEFAULT\s+([^,)]+)/i.exec(c.constraints);

    // Foreign key column → ForeignKey, but ONLY when the target table actually
    // exists. A `*_id` whose target isn't a real table is a POLYMORPHIC ref
    // (e.g. notifications.target_id paired with target_type) — emit it as a plain
    // UUIDField, not a dangling ForeignKey to a nonexistent model.
    var fkTargetTable = null;
    if (/_id$/.test(c.column)) {
      var m = /FK\s*→?\s*([a-z_]+)/.exec(c.constraints);
      var guess = m ? m[1] : c.column.replace(/_id$/, '') + 's';
      if (allTables.indexOf(guess) >= 0) fkTargetTable = guess;
    }
    if (fkTargetTable) {
      var targetTable = fkTargetTable;
      var targetModel = toPascal(singularize(targetTable));
      var fieldName = c.column.replace(/_id$/, '');
      var fkOpts = [
        '"' + targetTable + '.' + targetModel + '"',
        'on_delete=models.CASCADE',
        "db_column='" + c.column + "'",
        "related_name='+'",
      ];
      if (!notNull) fkOpts.push('null=True', 'blank=True');
      if (c.description) fieldLines.push('    # ' + c.description.slice(0, 150));
      fieldLines.push('    ' + fieldName + ' = models.ForeignKey(' + fkOpts.join(', ') + ')');
      fieldLines.push('');
      return;
    }

    var t = mapType(c.type);
    var opts = [];
    if (t.extra) opts = opts.concat(t.extra);
    if (!notNull) opts.push('null=True', 'blank=True');
    if (unique) opts.push('unique=True');
    if (t.json) {
      // JSON columns: a callable default (dict/list), never the DB-default string
      // and never two `default=` args (the duplicate-default boot bug).
      opts.push(/\[\s*\]/.test((defMatch && defMatch[1]) || '') ? 'default=list' : 'default=dict');
    } else if (defMatch) {
      var dv = pyDefault(defMatch[1], t.field);
      if (dv !== null) {
        if (dv === 'timezone.now') needTimezone = true;
        if (dv === 'uuid.uuid4') needUuid = true;
        opts.push('default=' + dv);
      }
    }
    if (c.description) fieldLines.push('    # ' + c.description.slice(0, 150));
    fieldLines.push('    ' + c.column + ' = models.' + t.field + '(' + opts.join(', ') + ')');
    fieldLines.push('');
  });

  // Meta indexes (non-unique IDX_*; UQ_* handled by unique=True on the field).
  // The `on` may be composite — "(user_id, created_at DESC)" — so split on comma,
  // strip parens + ASC/DESC ordering, and keep only fields that are real columns
  // (Django Index.fields must be model field names, not SQL expressions).
  var colSet = {};
  entity.columns.forEach(function (c) { colSet[c.column] = true; });
  var usedNames = {};
  var indexLines = [];
  entity.indexes.forEach(function (idx) {
    if (/^UQ_/.test(idx.name)) return;
    var fields = String(idx.on).replace(/[()]/g, '').split(',').map(function (f) {
      return f.trim().replace(/\s+(ASC|DESC)$/i, '').trim();
    }).filter(function (f) { return colSet[f]; });
    if (fields.length === 0) return;
    var nm = idx.name.slice(0, 30);
    if (usedNames[nm]) { var k = 2; while (usedNames[nm.slice(0, 28) + k]) k++; nm = nm.slice(0, 28) + k; }
    usedNames[nm] = true;
    indexLines.push("            models.Index(fields=[" + fields.map(function (f) { return "'" + f + "'"; }).join(', ') + "], name='" + nm + "'),");
  });

  var head = [];
  head.push('import uuid');
  head.push('');
  head.push('from django.db import models');
  if (needTimezone) head.push('from django.utils import timezone');
  head.push('from core.models import BaseModel');
  head.push('');
  head.push('');
  head.push('class ' + modelName + '(BaseModel):');

  var body = fieldLines.length ? fieldLines : ['    pass', ''];
  var meta = ['    class Meta:', "        db_table = '" + entity.table + "'"];
  if (indexLines.length) {
    meta.push('        indexes = [');
    meta = meta.concat(indexLines);
    meta.push('        ]');
  }

  return MARKER + '\n' + head.join('\n') + '\n' + body.join('\n') + '\n' + meta.join('\n') + '\n';
}

function main() {
  var args = parseArgs(process.argv);
  if (!fs.existsSync(args.db)) { console.error('scaffold-django-models: no PROJECT_DATABASE.md at ' + args.db); process.exit(1); }
  var entities = parseDatabase(fs.readFileSync(args.db, 'utf-8'));
  var allTables = entities.map(function (e) { return e.table; });
  var written = 0, skipped = 0;
  entities.forEach(function (e) {
    var dir = path.join(args.target, e.table);
    var file = path.join(dir, 'models.py');
    if (fs.existsSync(file) && !args.force) {
      var existing = fs.readFileSync(file, 'utf-8');
      if (existing.indexOf(MARKER) !== 0) { skipped++; if (args.verbose) console.log('  skip (hand-edited): ' + e.table); return; }
    }
    var src = renderModel(e, allTables);
    if (args.verbose || args.dryRun) console.log('  ' + (args.dryRun ? '[dry] ' : '') + e.table + '/models.py (' + toPascal(e.name) + ')');
    if (!args.dryRun) { fs.mkdirSync(dir, { recursive: true }); fs.writeFileSync(file, src); }
    written++;
  });
  console.log('scaffold-django-models: ' + written + ' model(s) written, ' + skipped + ' skipped' + (args.dryRun ? ' (dry-run)' : ''));
}

main();
