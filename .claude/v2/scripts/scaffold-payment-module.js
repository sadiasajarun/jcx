#!/usr/bin/env node
// scaffold-payment-module.js — PAYMENT capability primitive (Tier 2, NestJS/TypeORM).
//
// PG-integration + escrow-refund boilerplate is exactly the deterministic grammar
// that must NOT be LLM-invented (a wrong cancel-amount or unverified PG amount = real
// money lost). This scaffold emits, per MODULE_PLAN.yaml `payment:` entry:
//   infrastructure/payment/toss-payments.client.ts  — TossPayments REST adapter
//                                                      (confirm + partial/full cancel)
//   modules/payment/refund-policy.ts                 — refund standard-table + pure calc
//   modules/payment/payment.service.ts               — confirm(verify amount)/refund/preview
//   modules/payment/payment.controller.ts            — confirm / cancel / refund-preview routes
//   modules/payment/payment.module.ts                — wires the above
//
// The adapter + refund-policy are FULLY deterministic (the crown-jewel reliability).
// The service references the project's Payment/Booking entities (names from MODULE_PLAN,
// defaults Payment/Booking) — the entity classes themselves come from scaffold-entities.
//
// MODULE_PLAN.yaml shape:
//   payment:
//     provider: toss            # only toss supported in v1
//     currency: KRW
//     payment_entity: Payment   # entity scaffold-entities generated
//     booking_entity: Booking
//     refund_policy:            # standard-table rows (rate = % refunded)
//       - { when: before_24h,     rate: 100 }
//       - { when: same_day,       rate: 50 }
//       - { when: no_show,        rate: 0 }
//       - { when: provider_fault, rate: 100 }
'use strict';

var fs = require('fs');
var path = require('path');

var MARKER = '// Generated by scaffold-payment-module';

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--spec') out.spec = argv[++i];
    else if (a === '--target') out.target = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.spec || !out.target) { console.error('Usage: scaffold-payment-module --spec MODULE_PLAN.yaml --target BACKEND_DIR'); process.exit(1); }
  return out;
}
function loadYaml() {
  try { return require('yaml'); } catch (_) {}
  try { return require(path.join(require('child_process').execSync('npm root -g', { encoding: 'utf-8' }).trim(), 'yaml')); } catch (_) { return null; }
}

function defaultPolicy() {
  return [
    { when: 'before_24h', rate: 100 },
    { when: 'same_day', rate: 50 },
    { when: 'no_show', rate: 0 },
    { when: 'provider_fault', rate: 100 },
  ];
}

// --- emitted files ---------------------------------------------------------

function fileTossClient() {
  return [
    MARKER,
    "// TossPayments REST adapter. Confirm + cancel (partial/full). Secret-key Basic auth.",
    "// Amount verification is the CALLER's job (PaymentService) — never trust client amount.",
    "import { Injectable, Logger, BadRequestException } from '@nestjs/common';",
    '',
    "export interface TossConfirmResult { paymentKey: string; orderId: string; totalAmount: number; status: string; method?: string; approvedAt?: string; }",
    "export interface TossCancelResult { paymentKey: string; status: string; cancelledAmount: number; transactionKey?: string; }",
    '',
    "@Injectable()",
    "export class TossPaymentsClient {",
    "  private readonly logger = new Logger('TossPaymentsClient');",
    "  private readonly base = 'https://api.tosspayments.com/v1';",
    '',
    "  private authHeader(): string {",
    "    const key = process.env.TOSS_SECRET_KEY;",
    "    if (!key) throw new Error('TOSS_SECRET_KEY is required');",
    "    // Toss uses HTTP Basic with the secret key as username and an empty password.",
    "    return 'Basic ' + Buffer.from(key + ':').toString('base64');",
    "  }",
    '',
    "  private async call(url: string, body: Record<string, unknown>): Promise<any> {",
    "    const res = await fetch(this.base + url, {",
    "      method: 'POST',",
    "      headers: { Authorization: this.authHeader(), 'Content-Type': 'application/json' },",
    "      body: JSON.stringify(body),",
    "    });",
    "    const json = await res.json().catch(() => ({}));",
    "    if (!res.ok) {",
    "      this.logger.warn('toss ' + url + ' failed: ' + res.status + ' ' + JSON.stringify(json));",
    "      throw new BadRequestException({ code: 'PG_ERROR', message: json?.message || 'payment provider error', pgCode: json?.code });",
    "    }",
    "    return json;",
    "  }",
    '',
    "  // Confirm a payment after the client completed the Toss checkout. The server MUST",
    "  // re-verify `amount` against the booking's expected amount before calling this.",
    "  async confirm(paymentKey: string, orderId: string, amount: number): Promise<TossConfirmResult> {",
    "    const r = await this.call('/payments/confirm', { paymentKey, orderId, amount });",
    "    return { paymentKey: r.paymentKey, orderId: r.orderId, totalAmount: r.totalAmount, status: r.status, method: r.method, approvedAt: r.approvedAt };",
    "  }",
    '',
    "  // Cancel (full when cancelAmount omitted, else partial).",
    "  async cancel(paymentKey: string, reason: string, cancelAmount?: number): Promise<TossCancelResult> {",
    "    const body: Record<string, unknown> = { cancelReason: reason };",
    "    if (typeof cancelAmount === 'number') body.cancelAmount = cancelAmount;",
    "    const r = await this.call('/payments/' + encodeURIComponent(paymentKey) + '/cancel', body);",
    "    const last = (r.cancels && r.cancels[r.cancels.length - 1]) || {};",
    "    return { paymentKey: r.paymentKey, status: r.status, cancelledAmount: last.cancelAmount || cancelAmount || r.totalAmount, transactionKey: last.transactionKey };",
    "  }",
    "}",
    '',
  ].join('\n');
}

function fileRefundPolicy(policy, currency) {
  var rows = policy.map(function (p) { return "  { when: '" + p.when + "', rate: " + Number(p.rate) + " },"; }).join('\n');
  return [
    MARKER,
    "// Refund standard-table + pure calculation. SINGLE SOURCE for refund rates —",
    "// the law (KR e-commerce) requires pre-payment disclosure, so this table must be",
    "// the one place rates live. Deterministic: no LLM-invented percentages.",
    "export type RefundReason = 'before_24h' | 'same_day' | 'no_show' | 'provider_fault';",
    '',
    "export const REFUND_POLICY_VERSION = 'v1';",
    "export const REFUND_CURRENCY = '" + (currency || 'KRW') + "';",
    '',
    "export const REFUND_POLICY: { when: RefundReason; rate: number }[] = [",
    rows,
    "];",
    '',
    "export function refundRateFor(reason: RefundReason): number {",
    "  const row = REFUND_POLICY.find((r) => r.when === reason);",
    "  return row ? row.rate : 0;",
    "}",
    '',
    "// Compute the refund for a paid amount given the cancellation reason. Returns the",
    "// refunded amount (rounded down to the minor unit) + the applied rate.",
    "export function computeRefund(paidAmount: number, reason: RefundReason): { refundAmount: number; refundRate: number; policyVersion: string } {",
    "  const rate = refundRateFor(reason);",
    "  return { refundAmount: Math.floor((paidAmount * rate) / 100), refundRate: rate, policyVersion: REFUND_POLICY_VERSION };",
    "}",
    '',
    "// Derive the time-based reason for a student-initiated cancel (>=24h before start =",
    "// full, same day = half). Fault-based reasons (no_show / provider_fault) are decided",
    "// by the caller (dispute / instructor-cancel), not by time.",
    "export function timeBasedReason(lessonStart: Date, now: Date): RefundReason {",
    "  const hoursUntil = (lessonStart.getTime() - now.getTime()) / 3_600_000;",
    "  return hoursUntil >= 24 ? 'before_24h' : 'same_day';",
    "}",
    '',
  ].join('\n');
}

function filePaymentService(P) {
  return [
    MARKER,
    "import { Injectable, BadRequestException, NotFoundException } from '@nestjs/common';",
    "import { InjectRepository } from '@nestjs/typeorm';",
    "import { Repository } from 'typeorm';",
    "import { TossPaymentsClient } from '../../infrastructure/payment/toss-payments.client';",
    "import { computeRefund, timeBasedReason, type RefundReason } from './refund-policy';",
    "import { " + P.payment + " } from '../" + P.paymentKebab + "/" + P.paymentKebab + ".entity';",
    "import { " + P.booking + " } from '../" + P.bookingKebab + "/" + P.bookingKebab + ".entity';",
    '',
    "@Injectable()",
    "export class PaymentService {",
    "  constructor(",
    "    private readonly toss: TossPaymentsClient,",
    "    @InjectRepository(" + P.payment + ") private readonly payments: Repository<" + P.payment + ">,",
    "    @InjectRepository(" + P.booking + ") private readonly bookings: Repository<" + P.booking + ">,",
    "  ) {}",
    '',
    "  // Confirm a Toss checkout. CRITICAL: re-verify the PG amount against the booking's",
    "  // expected amount BEFORE confirming — never trust the client-supplied amount.",
    "  async confirm(input: { paymentKey: string; orderId: string; amount: number; bookingId: string }) {",
    "    const booking = await this.bookings.findOne({ where: { id: input.bookingId } as any });",
    "    if (!booking) throw new NotFoundException('booking not found');",
    "    const expected = (booking as any).amount;",
    "    if (typeof expected === 'number' && expected !== input.amount) {",
    "      throw new BadRequestException({ code: 'AMOUNT_MISMATCH', message: 'payment amount does not match booking' });",
    "    }",
    "    const r = await this.toss.confirm(input.paymentKey, input.orderId, input.amount);",
    "    const payment = this.payments.create({",
    "      bookingId: input.bookingId, tossPaymentKey: r.paymentKey, orderId: r.orderId,",
    "      amount: r.totalAmount, paidAmount: r.totalAmount, refundedAmount: 0, status: 'PAID', method: r.method,",
    "    } as any);",
    "    return this.payments.save(payment);",
    "  }",
    '',
    "  // Preview a refund without executing it (pre-cancel disclosure).",
    "  async refundPreview(bookingId: string, reason?: RefundReason) {",
    "    const payment = await this.payments.findOne({ where: { bookingId } as any });",
    "    if (!payment) throw new NotFoundException('payment not found');",
    "    const booking = await this.bookings.findOne({ where: { id: bookingId } as any });",
    "    const r = reason || (booking ? timeBasedReason(new Date((booking as any).slotStart), new Date()) : 'same_day');",
    "    const { refundAmount, refundRate, policyVersion } = computeRefund((payment as any).paidAmount, r);",
    "    return { refundAmount, refundRate, policyRow: r, policyVersion };",
    "  }",
    '',
    "  // Execute a refund via Toss partial/full cancel + persist.",
    "  async refund(bookingId: string, reason: RefundReason, cancelReason = 'booking cancelled') {",
    "    const payment = await this.payments.findOne({ where: { bookingId } as any });",
    "    if (!payment) throw new NotFoundException('payment not found');",
    "    const { refundAmount, refundRate } = computeRefund((payment as any).paidAmount, reason);",
    "    if (refundAmount > 0) {",
    "      const full = refundAmount >= (payment as any).paidAmount - (payment as any).refundedAmount;",
    "      await this.toss.cancel((payment as any).tossPaymentKey, cancelReason, full ? undefined : refundAmount);",
    "      (payment as any).refundedAmount = ((payment as any).refundedAmount || 0) + refundAmount;",
    "      (payment as any).status = full ? 'REFUNDED' : 'PARTIAL_REFUNDED';",
    "      await this.payments.save(payment);",
    "    }",
    "    return { refundAmount, refundRate };",
    "  }",
    "}",
    '',
  ].join('\n');
}

function filePaymentController() {
  return [
    MARKER,
    "import { Controller, Post, Get, Body, Param, Query } from '@nestjs/common';",
    "import { ApiTags, ApiOperation } from '@nestjs/swagger';",
    "import { PaymentService } from './payment.service';",
    "import type { RefundReason } from './refund-policy';",
    '',
    "@ApiTags('payments')",
    "@Controller('payments')",
    "export class PaymentController {",
    "  constructor(private readonly service: PaymentService) {}",
    '',
    "  @Post('confirm')",
    "  @ApiOperation({ summary: 'Confirm a Toss checkout (server re-verifies amount)' })",
    "  confirm(@Body() body: { paymentKey: string; orderId: string; amount: number; bookingId: string }) {",
    "    return this.service.confirm(body);",
    "  }",
    '',
    "  @Get(':bookingId/refund-preview')",
    "  @ApiOperation({ summary: 'Preview refund amount for a booking (pre-cancel disclosure)' })",
    "  preview(@Param('bookingId') bookingId: string, @Query('reason') reason?: RefundReason) {",
    "    return this.service.refundPreview(bookingId, reason);",
    "  }",
    '',
    "  @Post(':bookingId/refund')",
    "  @ApiOperation({ summary: 'Execute a refund via Toss cancel' })",
    "  refund(@Param('bookingId') bookingId: string, @Body() body: { reason: RefundReason; cancelReason?: string }) {",
    "    return this.service.refund(bookingId, body.reason, body.cancelReason);",
    "  }",
    "}",
    '',
  ].join('\n');
}

