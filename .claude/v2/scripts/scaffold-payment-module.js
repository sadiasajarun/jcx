function toKebab(s) { return String(s).replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/[_\s]+/g, '-').toLowerCase(); }

function writeFile(target, rel, content, args) {
  var full = path.join(target, rel);
  if (fs.existsSync(full) && !args.force) {
    var cur = fs.readFileSync(full, 'utf-8');
    if (cur.indexOf(MARKER) === -1) { if (args.verbose) console.log('  skip (hand-authored): ' + rel); return false; }
  }
  if (args.dryRun) { if (args.verbose) console.log('  [dry] ' + rel); return true; }
  var dir = path.dirname(full);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(full, content);
  return true;
}

function main() {
  var args = parseArgs(process.argv);
  if (!fs.existsSync(args.spec)) { console.log('scaffold-payment-module: no MODULE_PLAN — skipping'); return; }
  var yaml = loadYaml();
  if (!yaml) { console.log('scaffold-payment-module: yaml unavailable — skipping'); return; }
  var spec;
  try { spec = yaml.parse(fs.readFileSync(args.spec, 'utf-8')); } catch (e) { console.log('scaffold-payment-module: bad YAML — skipping'); return; }
  var pay = spec && spec.payment;
  if (!pay) { console.log('scaffold-payment-module: no `payment:` — skipping'); return; }
  if (pay.provider && pay.provider !== 'toss') { console.log('scaffold-payment-module: provider ' + pay.provider + ' not supported (v1=toss) — skipping'); return; }

  var P = {
    payment: pay.payment_entity || 'Payment',
    booking: pay.booking_entity || 'Booking',
  };
  P.paymentKebab = toKebab(P.payment);
  P.bookingKebab = toKebab(P.booking);
  var policy = Array.isArray(pay.refund_policy) && pay.refund_policy.length ? pay.refund_policy : defaultPolicy();
  var currency = pay.currency || 'KRW';

  console.log('scaffold-payment-module: TossPayments adapter + refund-policy (' + policy.map(function (p) { return p.when + '=' + p.rate; }).join(', ') + ')');
  var n = 0;
  [
    ['src/infrastructure/payment/toss-payments.client.ts', fileTossClient()],
    ['src/modules/payment/refund-policy.ts', fileRefundPolicy(policy, currency)],
    ['src/modules/payment/payment.service.ts', filePaymentService(P)],
    ['src/modules/payment/payment.controller.ts', filePaymentController()],
    ['src/modules/payment/payment.module.ts', filePaymentModule(P)],
  ].forEach(function (f) { if (writeFile(args.target, f[0], f[1], args)) n++; });
  console.log('scaffold-payment-module: ' + n + ' file(s) ' + (args.dryRun ? '(dry)' : 'written') + '. Register PaymentModule in AppModule (app-module-registry).');
  console.log('  deps: ensure @nestjs/swagger present; TOSS_SECRET_KEY in env.');
}

main();
