#!/usr/bin/env node
// scaffold-convert-wire-routes.js — v73 deterministic replacement for
// the convert-wire-routes agentic node. Enumerates every
// `app/routes/*.routes.ts` file under a frontend dir + aggregates them
// into the top-level `app/routes.ts`. Pure mechanical work.
//
// LLM convert-wire-routes was taking 5-10min per frontend and sometimes
// missed entries. Deterministic version takes ~50ms.
'use strict';

var fs = require('fs');
var path = require('path');

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--target') out.target = argv[++i];
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.target) {
    console.error('Usage: scaffold-convert-wire-routes --target FRONTEND_DIR');
    process.exit(1);
  }
  return out;
}

function toCamel(s) {
  // v76 fix: preserve existing camel-case boundaries. Old impl lowercased
  // `affiliationRequest` → `affiliationrequest` because the regex only split
  // on `-_\s`. We now insert a `-` between lower→Upper transitions before
  // splitting, so both kebab-case and camelCase inputs round-trip cleanly.
  var parts = s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').split(/[-_\s]+/).filter(Boolean);
  return parts.map(function (w, i) {
    var word = w.toLowerCase();
    return i === 0 ? word : word[0].toUpperCase() + word.slice(1);
  }).join('');
}

function main() {
  var args = parseArgs(process.argv);
  var routesDir = path.join(args.target, 'app/routes');
  var topRoutesPath = path.join(args.target, 'app/routes.ts');

  if (!fs.existsSync(routesDir)) {
    console.log('scaffold-convert-wire-routes: no app/routes dir at ' + routesDir + ' — skipping');
    return;
  }

  // Enumerate <name>.routes.ts files
  var entries = fs.readdirSync(routesDir, { withFileTypes: true });
  var routeModules = [];
  for (var i = 0; i < entries.length; i++) {
    var e = entries[i];
    if (!e.isFile()) continue;
    if (!/\.routes\.ts$/.test(e.name)) continue;
    var base = e.name.replace(/\.routes\.ts$/, '');
    routeModules.push({ base: base, exportName: toCamel(base) + 'Routes' });
  }
  if (routeModules.length === 0) {
    console.log('scaffold-convert-wire-routes: no *.routes.ts files found — leaving routes.ts alone');
    return;
  }
  routeModules.sort(function (a, b) { return a.base < b.base ? -1 : 1; });

  // Inspect existing routes.ts (if any) to find auth/public/etc. semantic
  // groups that we should NOT clobber — only update what we own.
  // We use marker comments to bracket our managed section.
  var existing = fs.existsSync(topRoutesPath) ? fs.readFileSync(topRoutesPath, 'utf-8') : '';

  // Generate imports + array entries
  var imports = routeModules.map(function (m) {
    return "import { " + m.exportName + " } from './routes/" + m.base + ".routes';";
  }).join('\n');

  var entriesYaml = routeModules.map(function (m) {
    return "  ..." + m.exportName + ',';
  }).join('\n');

  var newContent;
  if (existing && /\/\/ scaffold-routes-imports-start/.test(existing)) {
    // Update managed regions only
    newContent = existing
      .replace(/\/\/ scaffold-routes-imports-start[\s\S]*?\/\/ scaffold-routes-imports-end/,
               '// scaffold-routes-imports-start\n' + imports + '\n// scaffold-routes-imports-end')
      .replace(/\/\/ scaffold-routes-spread-start[\s\S]*?\/\/ scaffold-routes-spread-end/,
               '// scaffold-routes-spread-start\n' + entriesYaml + '\n  // scaffold-routes-spread-end');
  } else {
    // Generate a fresh routes.ts using RR7 framework mode conventions
    newContent =
      "/** Generated by scaffold-convert-wire-routes. */\n" +
      "import { type RouteConfig, layout, route } from '@react-router/dev/routes';\n\n" +
      "// scaffold-routes-imports-start\n" +
      imports + "\n" +
      "// scaffold-routes-imports-end\n\n" +
      "// Aggregated route config. Edit the per-feature *.routes.ts files,\n" +
      "// not this file — the convert-wire-routes scaffold regenerates it on\n" +
      "// each frontend phase.\n" +
      "export default [\n" +
      "  // scaffold-routes-spread-start\n" +
      entriesYaml + "\n" +
      "  // scaffold-routes-spread-end\n" +
      "  route('*', 'pages/not-found.tsx'),\n" +
      "] satisfies RouteConfig;\n";
  }

  if (args.dryRun) {
    console.log('  [dry] would update ' + topRoutesPath + ' with ' + routeModules.length + ' route modules');
    return;
  }
  fs.writeFileSync(topRoutesPath, newContent);
  console.log('scaffold-convert-wire-routes: wired ' + routeModules.length + ' route modules into ' + topRoutesPath +
              ' (' + routeModules.map(function (m) { return m.base; }).join(', ') + ')');
}

main();
