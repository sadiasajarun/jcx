#!/usr/bin/env node
// scaffold-django-serializers.js — DRF serializer per table, contract-shaped.
// Analog of scaffold-dto-from-entity. Derives EXPLICIT fields from
// PROJECT_DATABASE.md so the JSON matches the NestJS/TypeORM contract exactly:
//   - FK column `<x>_id` → serializers.UUIDField (exposes `xId` after camelCase,
//     NOT DRF's default relation field `x`)
//   - BIGINT column → serializers.CharField (TypeORM returns bigints as strings;
//     Django BigIntegerField would emit a number → differential-compare DIVERGE)
//   - explicit Meta.fields = the column list (relation objects excluded)
'use strict';
var fs = require('fs');
var path = require('path');
var L = require('./_django-lib');

var MARKER = '# Generated by scaffold-django-serializers';

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--db') out.db = argv[++i];
    else if (a === '--target') out.target = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.db || !out.target) { console.error('Usage: scaffold-django-serializers --db PROJECT_DATABASE.md --target BACKEND_DIR [--force]'); process.exit(1); }
  return out;
}

function render(entity, allTables) {
  var model = L.toPascal(entity.name);
  var declared = [];
  var fieldNames = [];
  entity.columns.forEach(function (c) {
    var col = c.column;
    fieldNames.push(col);
    var nullable = !/NOT NULL/i.test(c.constraints);
    var nullArg = nullable ? ', allow_null=True' : '';
    if (/_id$/.test(col)) {
      // FK id or polymorphic uuid — expose the raw id (→ camelCase `xId`)
      declared.push('    ' + col + ' = serializers.UUIDField(read_only=True' + nullArg + ')');
    } else if (/BIGINT/i.test(c.type)) {
      // TypeORM serializes bigint as string — match it
      declared.push('    ' + col + ' = serializers.CharField(read_only=True' + nullArg + ')');
    }
  });
  var lines = [MARKER, 'from rest_framework import serializers', '', 'from .models import ' + model, '', ''];
  lines.push('class ' + model + 'Serializer(serializers.ModelSerializer):');
  declared.forEach(function (d) { lines.push(d); });
  lines.push('');
  lines.push('    class Meta:');
  lines.push('        model = ' + model);
  lines.push('        fields = [' + fieldNames.map(function (f) { return "'" + f + "'"; }).join(', ') + ']');
  lines.push('');
  return lines.join('\n');
}

function main() {
  var args = parseArgs(process.argv);
  if (!fs.existsSync(args.db)) { console.error('scaffold-django-serializers: no PROJECT_DATABASE.md'); process.exit(1); }
  var entities = L.parseDatabase(fs.readFileSync(args.db, 'utf-8'));
  var allTables = entities.map(function (e) { return e.table; });
  var written = 0, skipped = 0;
  entities.forEach(function (e) {
    var file = path.join(args.target, e.table, 'serializers.py');
    if (!fs.existsSync(path.join(args.target, e.table))) return; // model app must exist
    if (fs.existsSync(file) && !args.force && fs.readFileSync(file, 'utf-8').indexOf(MARKER) !== 0) { skipped++; return; }
    fs.writeFileSync(file, render(e, allTables));
    if (args.verbose) console.log('  ' + e.table + '/serializers.py (' + L.toPascal(e.name) + 'Serializer)');
    written++;
  });
  console.log('scaffold-django-serializers: ' + written + ' serializer(s) written, ' + skipped + ' skipped');
}

main();
