#!/usr/bin/env node
// scaffold-test-fixtures-from-dto.js — v85. For every Create*Dto under
// backend/src/modules/**/dtos/, emit test/fixtures/<entity>-create.fixture.ts
// exporting a function that returns DTO-compliant sample data.
//
// v82 replay evidence: Claude fix-agent got tests from 17 failing → 9
// failing in 60 turns; the remaining 9 all hit `expected 201, got 400`
// on POST create endpoints. Root cause: e2e tests construct request
// bodies inline with incomplete data; missing required fields → DTO
// validation rejects with 400. Not a bug in source code — a gap in
// test fixture quality.
//
// This scaffold reads each DTO's class-validator decorators, generates
// data that satisfies EVERY constraint, and emits a fixture function
// the e2e tests can use:
//
//   import { validCreateUserPayload } from '../fixtures/user-create.fixture';
//   await request(app).post('/users').send(validCreateUserPayload());
//
// Idempotent. Marker: '// Generated by scaffold-test-fixtures-from-dto'.
'use strict';

var fs = require('fs');
var path = require('path');

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--backend-dir') out.backendDir = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.backendDir) {
    console.error('Usage: scaffold-test-fixtures-from-dto --backend-dir BACKEND_DIR [--force]');
    process.exit(1);
  }
  return out;
}

function walk(dir, filterFn, out) {
  out = out || [];
  if (!fs.existsSync(dir)) return out;
  fs.readdirSync(dir, { withFileTypes: true }).forEach(function (e) {
    var f = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (/^(node_modules|dist|\.git|__tests__)$/.test(e.name)) return;
      walk(f, filterFn, out);
    } else if (e.isFile() && filterFn(f)) out.push(f);
  });
  return out;
}

function toKebab(s) {
  return s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/[_\s]+/g, '-').toLowerCase();
}

function findCreateDtos(modulesDir) {
  // Match create-<entity>.dto.ts in any module's dtos/ subdir
  return walk(modulesDir, function (f) {
    return /\/dtos\/create-[a-z0-9-]+\.dto\.ts$/.test(f);
  }, []);
}

function parseDtoFields(content) {
  // Returns [{ name, optional, validators: {...}, tsType }]
  var fields = [];
  var lines = content.split('\n');
  var pending = [];
  var inClass = false;
  for (var i = 0; i < lines.length; i++) {
    var line = lines[i];
    if (!inClass) {
      if (/^export\s+class\s+\w+/.test(line)) inClass = true;
      continue;
    }
    var trimmed = line.trim();
    if (!trimmed) continue;
    if (/^\}/.test(trimmed)) break;
    if (/^@/.test(trimmed)) { pending.push(trimmed); continue; }
    var m = /^(?:readonly\s+)?(\w+)\s*([?!])?:\s*([^;]+);?\s*$/.exec(trimmed);
    if (!m) { pending = []; continue; }
    var blob = pending.join(' ');
    pending = [];
    var v = {
      isString: /@IsString\b/.test(blob),
      isEmail: /@IsEmail\b/.test(blob),
      isUUID: /@IsUUID\b/.test(blob),
      isURL: /@IsUrl\b/.test(blob),
      isInt: /@IsInt\b/.test(blob),
      isNumber: /@IsNumber|@IsInt\b/.test(blob),
      isBoolean: /@IsBoolean\b/.test(blob),
      isDate: /@IsDate(String)?\b/.test(blob),
      isEnum: /@IsEnum\b/.test(blob),
      enumName: (function () { var x = /@IsEnum\(\s*(\w+)\s*\)/.exec(blob); return x ? x[1] : null; })(),
      minLength: (function () { var x = /@MinLength\(\s*(\d+)\s*\)/.exec(blob); return x ? parseInt(x[1], 10) : null; })(),
      maxLength: (function () { var x = /@MaxLength\(\s*(\d+)\s*\)/.exec(blob); return x ? parseInt(x[1], 10) : null; })(),
      min: (function () { var x = /@Min\(\s*(-?\d+)\s*\)/.exec(blob); return x ? parseInt(x[1], 10) : null; })(),
      max: (function () { var x = /@Max\(\s*(-?\d+)\s*\)/.exec(blob); return x ? parseInt(x[1], 10) : null; })(),
      matches: (function () { var x = /@Matches\(\s*(?:\/([^/]+)\/[a-z]*|['"]([^'"]+)['"])\s*\)/.exec(blob); return x ? (x[1] || x[2]) : null; })(),
      isNotEmpty: /@IsNotEmpty\b/.test(blob),
      isOptional: /@IsOptional\b/.test(blob),
    };
    fields.push({
      name: m[1],
      optional: m[2] === '?' || v.isOptional,
      tsType: m[3].trim(),
      validators: v,
    });
  }
  return fields;
}

function findClassName(content) {
  var m = /export\s+class\s+(\w+)/.exec(content);
  return m ? m[1] : null;
}

// Generate a value satisfying the constraints
function sampleFor(field) {
  var v = field.validators;
  var name = field.name.toLowerCase();
  var rawType = field.tsType.replace(/\|.*$/, '').trim();
  // v85b: check tsType + EXPLICIT validators FIRST so name-based heuristics
  // don't override. Example bug: `notificationOptOutEmail: boolean` was
  // emitted as an email string because the name contains "email".
  // Enum: first enum value (caller imports the enum)
  if (v.isEnum && v.enumName) {
    return { value: 'Object.values(' + v.enumName + ')[0]', importEnum: v.enumName };
  }
  // Boolean — check FIRST so name-based "email"/"url" heuristics don't override
  if (v.isBoolean || /^(boolean|bool)$/.test(rawType)) {
    return { value: 'true' };
  }
  // Number — same priority as boolean
  if (v.isInt || v.isNumber || /^(number|int)$/.test(rawType)) {
    var nVal = 1;
    if (v.min !== null && v.min !== undefined) nVal = v.min;
    if (v.max !== null && v.max !== undefined && nVal > v.max) nVal = v.max;
    return { value: String(nVal) };
  }
  // Email (only if NOT already classified as bool/number)
  if (v.isEmail || (rawType === 'string' && /email/.test(name))) {
    return { value: "'fixture-" + Math.random().toString(36).slice(2, 8) + "@example.com'" };
  }
  // UUID
  if (v.isUUID || /^id$|Id$/.test(field.name)) {
    return { value: "'00000000-0000-4000-8000-000000000000'" };
  }
  // URL
  if (v.isURL || (rawType === 'string' && /url/.test(name))) {
    return { value: "'https://example.com/fixture'" };
  }
  // Date
  if (v.isDate || /^Date$/.test(field.tsType.replace(/\|.*$/, '').trim()) || /At$|Date$/.test(field.name)) {
    return { value: "new Date().toISOString()" };
  }
  // Password (heuristic)
  if (/password|passwordhash/i.test(name)) {
    return { value: "'TestPass1!'" };  // matches common strong-password regex
  }
  // Phone (heuristic — matches `010-XXXX-XXXX` Korean pattern + general digits)
  if (/phone/i.test(name)) {
    return { value: "'010-1234-5678'" };
  }
  // Default: string with sensible length
  var minLen = v.minLength || (v.isNotEmpty ? 1 : 0);
  var maxLen = v.maxLength || 100;
  // pick a value between min and max, default ~ 8-12 chars
  var sampleLen = Math.max(minLen, Math.min(maxLen, 8));
  var sample = ('fixture' + field.name).slice(0, sampleLen);
  if (v.matches) {
    // For regex patterns, fall back to a probable match — common patterns:
    if (/\^010/.test(v.matches)) return { value: "'010-1234-5678'" };
    if (/email|@/.test(v.matches)) return { value: "'fixture@example.com'" };
    // Otherwise leave a TODO so the test can override
    return { value: "'fixture-' + Math.random().toString(36).slice(2, 8) /* TODO: match /" + v.matches + "/ */" };
  }
  return { value: "'" + sample + "'" };
}

function generatedMarker() {
  return '// Generated by scaffold-test-fixtures-from-dto — DO NOT EDIT BY HAND. Re-run when DTOs change.';
}

function emitFixture(className, entityKebab, fields, enumImports) {
  var lines = [];
  lines.push(generatedMarker());
  // Imports: enums (relative path from test/fixtures to src/common/enums)
  Object.keys(enumImports).sort().forEach(function (e) {
    var importPath = enumImports[e];
    lines.push("import { " + e + " } from '" + importPath + "';");
  });
  lines.push('');
  // The class name is something like "CreateUserDto" → strip "Create" + "Dto" to get "User"
  var entityName = className.replace(/^Create/, '').replace(/Dto$/, '');
  lines.push('/**');
  lines.push(' * Returns a payload that satisfies every class-validator constraint on ' + className + '.');
  lines.push(' * Use in e2e tests:');
  lines.push(' *   await request(app).post(\'/' + entityKebab + 's\').send(validCreate' + entityName + 'Payload());');
  lines.push(' */');
  lines.push('export function validCreate' + entityName + 'Payload(overrides: Partial<Record<string, unknown>> = {}): Record<string, unknown> {');
  lines.push('  return {');
  fields.forEach(function (f) {
    if (f.optional) return; // skip optional fields by default (overrides can add them)
    var s = sampleFor(f);
    lines.push('    ' + f.name + ': ' + s.value + ',');
  });
  lines.push('    ...overrides,');
  lines.push('  };');
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

function findEnumImports(content) {
  // Re-use the imports from the DTO source — rewrite paths from
  // module-level (../../) to test/fixtures-level (../../).
  var out = {};
  var re = /import\s+\{([^}]+)\}\s+from\s+['"]([^'"]+)['"]/g;
  var m;
  while ((m = re.exec(content)) !== null) {
    var fromPath = m[2];
    if (!/enum$/.test(fromPath) && !/\.enum$/.test(fromPath)) continue;
    m[1].split(',').map(function (s) { return s.trim(); }).filter(Boolean).forEach(function (name) {
      // Adjust relative path. DTO at backend/src/modules/<x>/dtos/create-x.dto.ts imports '../../../common/enums/...'
      // Fixture at backend/test/fixtures/x-create.fixture.ts needs '../../src/common/enums/...'
      if (fromPath.charAt(0) === '.') {
        // Naive rewrite: relative from DTO is "../../../" usually → "../../src/" for fixture
        var rewritten = fromPath.replace(/^\.\.\/\.\.\/\.\.\//, '../../src/');
        out[name] = rewritten;
      } else {
        out[name] = fromPath;
      }
    });
  }
  return out;
}

function writeIfManaged(file, content, force, dryRun) {
  if (fs.existsSync(file)) {
    var existing = fs.readFileSync(file, 'utf-8');
    if (!/Generated by scaffold-test-fixtures-from-dto/.test(existing) && !force) {
      return { written: false, reason: 'exists-handauthored' };
    }
    if (existing === content) return { written: false, reason: 'unchanged' };
  }
  if (dryRun) return { written: false, reason: 'dry-run' };
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return { written: true };
}

function main() {
  var args = parseArgs(process.argv);
  var modulesDir = path.join(args.backendDir, 'src/modules');
  var dtos = findCreateDtos(modulesDir);
  if (dtos.length === 0) {
    console.log('scaffold-test-fixtures-from-dto: no Create*.dto.ts found under ' + modulesDir);
    return;
  }
  var written = 0, skipped = 0;
  dtos.forEach(function (dtoFile) {
    var content = fs.readFileSync(dtoFile, 'utf-8');
    var className = findClassName(content);
    if (!className || !/^Create/.test(className)) return;
    var fields = parseDtoFields(content);
    if (fields.length === 0) return;
    var enumImports = findEnumImports(content);
    // entity kebab: strip "create-" from filename
    var entityKebab = path.basename(dtoFile, '.dto.ts').replace(/^create-/, '');
    var fixtureFile = path.join(args.backendDir, 'test/fixtures', entityKebab + '-create.fixture.ts');
    var r = writeIfManaged(fixtureFile, emitFixture(className, entityKebab, fields, enumImports), args.force, args.dryRun);
    if (r.written) written++; else skipped++;
    if (args.verbose) {
      console.log('  ' + className + ' (' + fields.filter(function (f) { return !f.optional; }).length + ' required fields): ' + (r.written ? 'wrote' : r.reason));
    }
  });
  console.log('scaffold-test-fixtures-from-dto: ' + written + ' fixtures written, ' + skipped + ' skipped');
}

main();
