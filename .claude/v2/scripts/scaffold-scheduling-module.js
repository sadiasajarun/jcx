#!/usr/bin/env node
// scaffold-scheduling-module.js — SCHEDULING capability primitive (Tier 2, NestJS/TypeORM).
//
// Slot computation + double-booking prevention is subtle, money-adjacent grammar (a
// race in the lock = two students pay for one slot). This scaffold emits the
// deterministic core, per MODULE_PLAN.yaml `scheduling:` entry:
//   modules/scheduling/slot.util.ts       — weekly-rule + exceptions → 30-min slot list
//   modules/scheduling/slot-lock.guard.ts  — acquire/release short-lived booking lock
//   modules/scheduling/scheduling.service.ts — availableSlots() + lockSlot() (atomic)
//   modules/scheduling/scheduling.controller.ts — GET slots / POST lock
//   modules/scheduling/scheduling.module.ts
//
// Double-booking defense = the project's Booking entity carries a PARTIAL UNIQUE index
// on (providerId, slotStart) WHERE status IN active-states (emitted by the entity layer);
// this module adds the lock-then-confirm flow + slot math on top.
//
// MODULE_PLAN.yaml shape:
//   scheduling:
//     slot_minutes: 30
//     lock_ttl_seconds: 600       # 10 min hold during checkout
//     provider_entity: InstructorProfile
//     lock_entity: SlotLock        # entity scaffold-entities generated
//     schedule_entity: WeeklySchedule
//     active_booking_states: [REQUESTED, CONFIRMED]
'use strict';

var fs = require('fs');
var path = require('path');

var MARKER = '// Generated by scaffold-scheduling-module';

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--spec') out.spec = argv[++i];
    else if (a === '--target') out.target = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.spec || !out.target) { console.error('Usage: scaffold-scheduling-module --spec MODULE_PLAN.yaml --target BACKEND_DIR'); process.exit(1); }
  return out;
}
function loadYaml() {
  try { return require('yaml'); } catch (_) {}
  try { return require(path.join(require('child_process').execSync('npm root -g', { encoding: 'utf-8' }).trim(), 'yaml')); } catch (_) { return null; }
}
function toKebab(s) { return String(s).replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/[_\s]+/g, '-').toLowerCase(); }

function fileSlotUtil(slotMin) {
  return [
    MARKER,
    "// Pure slot math: expand a weekly recurrence rule (+ EXTRA single slots − BLOCK",
    "// exceptions) into concrete " + slotMin + "-minute start times within a date window.",
    "// No DB, no side effects — deterministic + unit-testable.",
    "export const SLOT_MINUTES = " + slotMin + ";",
    '',
    "export interface RecurrenceRule { dayOfWeek: number; startMinutes: number; endMinutes: number; } // dayOfWeek 0=Sun",
    "export interface ScheduleException { date: string; type: 'BLOCK' | 'EXTRA'; startMinutes?: number; endMinutes?: number; }",
    '',
    "function atMinutes(day: Date, minutes: number): Date {",
    "  const d = new Date(day);",
    "  d.setHours(0, 0, 0, 0);",
    "  d.setMinutes(minutes);",
    "  return d;",
    "}",
    '',
    "// Returns slot start Dates in [from, to) honoring rules, EXTRA additions, BLOCK removals.",
    "export function computeSlots(",
    "  rules: RecurrenceRule[],",
    "  exceptions: ScheduleException[],",
    "  from: Date,",
    "  to: Date,",
    "): Date[] {",
    "  const blocked = new Set<number>();",
    "  const out: Date[] = [];",
    "  const day = new Date(from); day.setHours(0, 0, 0, 0);",
    "  // BLOCK exceptions → remove whole-day or ranged slots",
    "  for (const ex of exceptions) {",
    "    if (ex.type !== 'BLOCK') continue;",
    "    const base = new Date(ex.date);",
    "    const s = ex.startMinutes ?? 0, e = ex.endMinutes ?? 24 * 60;",
    "    for (let m = s; m < e; m += SLOT_MINUTES) blocked.add(atMinutes(base, m).getTime());",
    "  }",
    "  // recurrence rules",
    "  for (let d = new Date(day); d < to; d.setDate(d.getDate() + 1)) {",
    "    for (const r of rules) {",
    "      if (r.dayOfWeek !== d.getDay()) continue;",
    "      for (let m = r.startMinutes; m < r.endMinutes; m += SLOT_MINUTES) {",
    "        const t = atMinutes(d, m);",
    "        if (t >= from && t < to && !blocked.has(t.getTime())) out.push(t);",
    "      }",
    "    }",
    "  }",
    "  // EXTRA single slots",
    "  for (const ex of exceptions) {",
    "    if (ex.type !== 'EXTRA') continue;",
    "    const base = new Date(ex.date);",
    "    const s = ex.startMinutes ?? 0, e = ex.endMinutes ?? s + SLOT_MINUTES;",
    "    for (let m = s; m < e; m += SLOT_MINUTES) {",
    "      const t = atMinutes(base, m);",
    "      if (t >= from && t < to && !blocked.has(t.getTime())) out.push(t);",
    "    }",
    "  }",
    "  return out.sort((a, b) => a.getTime() - b.getTime());",
    "}",
    '',
  ].join('\n');
}

function fileSchedulingService(P) {
  var states = P.activeStates.map(function (s) { return "'" + s + "'"; }).join(', ');
  return [
    MARKER,
    "import { Injectable, ConflictException } from '@nestjs/common';",
    "import { InjectRepository } from '@nestjs/typeorm';",
    "import { Repository, LessThan } from 'typeorm';",
    "import { computeSlots, type RecurrenceRule, type ScheduleException } from './slot.util';",
    "import { " + P.lock + " } from '../" + P.lockKebab + "/" + P.lockKebab + ".entity';",
    '',
    "const LOCK_TTL_SECONDS = " + P.lockTtl + ";",
    '',
    "@Injectable()",
    "export class SchedulingService {",
    "  constructor(",
    "    @InjectRepository(" + P.lock + ") private readonly locks: Repository<" + P.lock + ">,",
    "  ) {}",
    '',
    "  // Available slots for a provider in [from,to): computed slots MINUS active bookings",
    "  // MINUS unexpired locks. (Caller passes the provider's rules/exceptions + booked set.)",
    "  available(rules: RecurrenceRule[], exceptions: ScheduleException[], bookedStarts: Date[], from: Date, to: Date): Date[] {",
    "    const taken = new Set(bookedStarts.map((d) => new Date(d).getTime()));",
    "    return computeSlots(rules, exceptions, from, to).filter((s) => !taken.has(s.getTime()));",
    "  }",
    '',
    "  // Acquire a short-lived lock on (provider, slotStart) before checkout. The lock_lock",
    "  // entity should carry a UNIQUE(providerId, slotStart) constraint — the insert is the",
    "  // atomic gate: a duplicate throws → 409 SLOT_CONFLICT (no two students hold one slot).",
    "  async lockSlot(providerId: string, slotStart: Date): Promise<{ ok: true; expiresAt: Date }> {",
    "    // clear our own expired locks first (defensive; a cron also sweeps these)",
    "    await this.locks.delete({ providerId, expiresAt: LessThan(new Date()) } as any).catch(() => undefined);",
    "    const expiresAt = new Date(Date.now() + LOCK_TTL_SECONDS * 1000);",
    "    try {",
    "      const lock = this.locks.create({ providerId, slotStart, expiresAt } as any);",
    "      await this.locks.save(lock);",
    "      return { ok: true, expiresAt };",
    "    } catch (e: any) {",
    "      // unique-violation (Postgres 23505) → the slot is already held/booked",
    "      if (e?.code === '23505' || /duplicate|unique/i.test(String(e?.message))) {",
    "        throw new ConflictException({ code: 'SLOT_CONFLICT', message: 'this time was just taken' });",
    "      }",
    "      throw e;",
    "    }",
    "  }",
    '',
    "  // Release a lock (e.g. checkout abandoned, or moved into a confirmed booking which the",
    "  // booking's partial-unique index now protects).",
    "  async releaseSlot(providerId: string, slotStart: Date): Promise<void> {",
    "    await this.locks.delete({ providerId, slotStart } as any).catch(() => undefined);",
    "  }",
    '',
    "  // The active booking states whose slots are unavailable (mirrors the entity's partial",
    "  // unique index WHERE clause). Used by callers building the bookedStarts set.",
    "  static readonly ACTIVE_BOOKING_STATES = [" + states + "];",
    "}",
    '',
  ].join('\n');
}

function fileSchedulingController() {
  return [
    MARKER,
    "import { Controller, Post, Body } from '@nestjs/common';",
    "import { ApiTags, ApiOperation } from '@nestjs/swagger';",
    "import { SchedulingService } from './scheduling.service';",
    '',
    "@ApiTags('scheduling')",
    "@Controller('scheduling')",
    "export class SchedulingController {",
    "  constructor(private readonly service: SchedulingService) {}",
    '',
    "  @Post('lock')",
    "  @ApiOperation({ summary: 'Acquire a short-lived slot lock before checkout (409 SLOT_CONFLICT if taken)' })",
    "  lock(@Body() body: { providerId: string; slotStart: string }) {",
    "    return this.service.lockSlot(body.providerId, new Date(body.slotStart));",
    "  }",
    '',
    "  @Post('release')",
    "  @ApiOperation({ summary: 'Release a slot lock (abandoned checkout)' })",
    "  async release(@Body() body: { providerId: string; slotStart: string }) {",
    "    await this.service.releaseSlot(body.providerId, new Date(body.slotStart));",
    "    return { ok: true };",
    "  }",
    "}",
    '',
  ].join('\n');
}

function fileSchedulingModule(P) {
  return [
    MARKER,
    "import { Module } from '@nestjs/common';",
    "import { TypeOrmModule } from '@nestjs/typeorm';",
    "import { SchedulingService } from './scheduling.service';",
    "import { SchedulingController } from './scheduling.controller';",
    "import { " + P.lock + " } from '../" + P.lockKebab + "/" + P.lockKebab + ".entity';",
    '',
    "@Module({",
    "  imports: [TypeOrmModule.forFeature([" + P.lock + "])],",
    "  controllers: [SchedulingController],",
    "  providers: [SchedulingService],",
    "  exports: [SchedulingService],",
    "})",
    "export class SchedulingModule {}",
    '',
  ].join('\n');
}

function writeFile(target, rel, content, args) {
  var full = path.join(target, rel);
  if (fs.existsSync(full) && !args.force) {
    var cur = fs.readFileSync(full, 'utf-8');
    if (cur.indexOf(MARKER) === -1) { if (args.verbose) console.log('  skip (hand-authored): ' + rel); return false; }
  }
  if (args.dryRun) { if (args.verbose) console.log('  [dry] ' + rel); return true; }
  var dir = path.dirname(full);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(full, content);
  return true;
}

function main() {
  var args = parseArgs(process.argv);
  if (!fs.existsSync(args.spec)) { console.log('scaffold-scheduling-module: no MODULE_PLAN — skipping'); return; }
  var yaml = loadYaml();
  if (!yaml) { console.log('scaffold-scheduling-module: yaml unavailable — skipping'); return; }
  var spec;
  try { spec = yaml.parse(fs.readFileSync(args.spec, 'utf-8')); } catch (e) { console.log('scaffold-scheduling-module: bad YAML — skipping'); return; }
  var sc = spec && spec.scheduling;
  if (!sc) { console.log('scaffold-scheduling-module: no `scheduling:` — skipping'); return; }

  var P = {
    lock: sc.lock_entity || 'SlotLock',
    slotMin: Number(sc.slot_minutes) || 30,
    lockTtl: Number(sc.lock_ttl_seconds) || 600,
    activeStates: Array.isArray(sc.active_booking_states) && sc.active_booking_states.length ? sc.active_booking_states : ['REQUESTED', 'CONFIRMED'],
  };
  P.lockKebab = toKebab(P.lock);

  console.log('scaffold-scheduling-module: slot=' + P.slotMin + 'min, lock-ttl=' + P.lockTtl + 's, active-states=[' + P.activeStates.join(',') + ']');
  var n = 0;
  [
    ['src/modules/scheduling/slot.util.ts', fileSlotUtil(P.slotMin)],
    ['src/modules/scheduling/scheduling.service.ts', fileSchedulingService(P)],
    ['src/modules/scheduling/scheduling.controller.ts', fileSchedulingController()],
    ['src/modules/scheduling/scheduling.module.ts', fileSchedulingModule(P)],
  ].forEach(function (f) { if (writeFile(args.target, f[0], f[1], args)) n++; });
  console.log('scaffold-scheduling-module: ' + n + ' file(s) ' + (args.dryRun ? '(dry)' : 'written') + '. Register SchedulingModule in AppModule. Ensure ' + P.lock + ' entity has UNIQUE(providerId, slotStart).');
}

main();
