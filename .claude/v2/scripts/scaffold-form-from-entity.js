#!/usr/bin/env node
// scaffold-form-from-entity.js — v78 fills the crud-pages templates' empty
// marker comments with entity-aware form fields. Walks backend entities,
// parses @Column declarations, and substitutes:
//   - __CREATE_SCHEMA_IMPORTS__  → zod schema import + UI primitive imports
//   - __CREATE_SCHEMA__          → (empty — schema is imported)
//   - __CREATE_DEFAULTS__        → defaultValues per field
//   - __CREATE_FORM_FIELDS__     → <FormField> per column
//   - same set for __EDIT_*__
//
// KILLS THE v76 ROOT CAUSE: UserEditPage stripped `import { Input }` because
// the EditPage template ships WITHOUT the Input import (only CreatePage has
// it pre-wired). When LLM convert-pages adds Input fields, it had to also
// add the import — and didn't.
//
// Also injects: Select for enums, Checkbox/Switch for booleans, Input
// type="number" for numbers, Input type="date" for dates, Input type="email"
// for email fields. FK columns (*Id) get a plain text Input with a TODO
// comment to convert to a Combobox once relation-aware scaffolds exist.
//
// Idempotent. Marker check: only modifies files whose first line contains
// "Generated by scaffold-crud-pages" or "Generated by scaffold-form-from-entity".
// LLM-authored pages (no marker) are skipped unless --force.
'use strict';

var fs = require('fs');
var path = require('path');

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--backend-dir') out.backendDir = argv[++i];
    else if (a === '--target') out.target = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.backendDir || !out.target) {
    console.error('Usage: scaffold-form-from-entity --backend-dir BACKEND --target FRONTEND [--force]');
    process.exit(1);
  }
  return out;
}

function toPascal(s) {
  return s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').split(/[-_\s]+/).filter(Boolean).map(function (w) {
    return w[0].toUpperCase() + w.slice(1).toLowerCase();
  }).join('');
}
function toCamel(s) {
  var p = toPascal(s); return p[0].toLowerCase() + p.slice(1);
}
function toKebab(s) {
  return s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/[_\s]+/g, '-').toLowerCase();
}

function findEntityFiles(modulesDir) {
  var out = [];
  if (!fs.existsSync(modulesDir)) return out;
  function walkInModule(modDir, currentDir) {
    fs.readdirSync(currentDir, { withFileTypes: true }).forEach(function (f) {
      var p = path.join(currentDir, f.name);
      if (f.isDirectory()) {
        if (f.name === 'dtos' || f.name === 'dto' || f.name === '__tests__') return;
        walkInModule(modDir, p);
      } else if (f.isFile() && /\.entity\.ts$/.test(f.name)) {
        out.push({ moduleDir: modDir, moduleName: path.basename(modDir), entityFile: p });
      }
    });
  }
  fs.readdirSync(modulesDir, { withFileTypes: true }).forEach(function (e) {
    if (!e.isDirectory()) return;
    walkInModule(path.join(modulesDir, e.name), path.join(modulesDir, e.name));
  });
  return out;
}

function parseEntity(content) {
  // Returns: { className, props: [...] } — same parser as scaffold-dto-from-entity
  var classMatch = /export\s+class\s+(\w+)\s+extends\s+\w+/.exec(content);
  if (!classMatch) return null;
  var className = classMatch[1];
  var props = [];
  var lines = content.split('\n');
  var pending = [];
  var inClass = false;
  for (var i = 0; i < lines.length; i++) {
    var line = lines[i];
    if (!inClass) {
      if (/^export\s+class\s+\w+\s+extends/.test(line)) inClass = true;
      continue;
    }
    var trimmed = line.trim();
    if (!trimmed) continue;
    if (/^(constructor|public|private|protected)\b/.test(trimmed)) { pending = []; continue; }
    if (/^\}/.test(trimmed)) break;
    if (/^@/.test(trimmed)) { pending.push(trimmed); continue; }
    var m = /^(?:readonly\s+)?(\w+)\s*([?!])?:\s*([^;]+);?\s*$/.exec(trimmed);
    if (!m) { pending = []; continue; }
    var name = m[1];
    var optional = m[2] === '?';
    var tsType = m[3].trim();
    var blob = pending.join(' ');
    pending = [];
    if (/@ManyToOne|@OneToMany|@ManyToMany|@OneToOne|@JoinColumn|@JoinTable/.test(blob)) continue;
    if (!/@Column|@PrimaryColumn|@PrimaryGeneratedColumn/.test(blob)) continue;
    if (/^(id|createdAt|updatedAt|deletedAt)$/.test(name)) continue;
    // v89: skip internal-only fields (mirrors scaffold-dto-from-entity strip).
    // Forms should NEVER expose *Hash/*Salt/*Token (security: client shouldn't
    // type a hash; backend derives them) or audit metadata fields. Without
    // this strip, the form would render `passwordHash` as a plain Input → DTO
    // contract mismatch in integrate phase, "no form inputs found" in stories.
    if (/(Hash|Salt|Token)$/.test(name)) continue;
    if (/^last(LoginAt|SeenAt|LoginIp|LoginIP)$/i.test(name)) continue;
    if (/^(emailVerifiedAt|phoneVerifiedAt|verifiedAt)$/.test(name)) continue;
    // Skip FK id columns — they need a dropdown of related entities, out of scope for v1
    if (/Id$/.test(name) && /^(uuid|string)$/.test((/type:\s*['"](\w+)['"]/.exec(blob) || [])[1] || 'string')) {
      // We still emit them as plain Input so the form has SOMETHING — but mark for future Combobox
      props.push({ name: name, tsType: 'string', optional: optional || /nullable:\s*true/.test(blob), kind: 'fk' });
      continue;
    }
    // v89: detect enums via either @Column({type:'enum'}) OR property-type
    // (after scaffold-numeric-enum-doctor converts to type:'int' the column
    // decorator loses 'enum' but the TS property type remains *Enum).
    var isEnum = /type:\s*['"]enum['"]/.test(blob);
    var enumMatch = /enum:\s*(\w+)/.exec(blob);
    var enumName = enumMatch ? enumMatch[1] : null;
    // Fallback: property type matches XxxEnum and we have an import for it
    if (!isEnum && /Enum$/.test(tsType)) {
      isEnum = true;
      enumName = tsType.replace(/\s*\|\s*null/g, '').trim();
    }
    var nullable = /nullable:\s*true/.test(blob);
    var kind = 'string';
    if (isEnum) kind = 'enum';
    else if (/^boolean$/.test(tsType)) kind = 'boolean';
    else if (/^number$/.test(tsType) || /int|numeric|decimal/i.test(blob)) kind = 'number';
    else if (/^Date$/.test(tsType) || /timestamp|date/i.test(blob)) kind = 'date';
    else if (/email/i.test(name)) kind = 'email';
    else kind = 'string';
    props.push({
      name: name,
      tsType: tsType,
      optional: optional || nullable,
      kind: kind,
      enumName: enumName,
    });
  }
  return { className: className, props: props };
}

function findEnumImports(entityContent) {
  // returns map: EnumName → kebab file base (e.g. 'UserStatusEnum' → 'user-status')
  var out = {};
  var re = /import\s+\{([^}]+)\}\s+from\s+['"][^'"]+['"]/g;
  var m;
  while ((m = re.exec(entityContent)) !== null) {
    m[1].split(',').map(function (s) { return s.trim(); }).filter(Boolean).forEach(function (name) {
      if (/Enum$/.test(name)) {
        var stripped = name.replace(/Enum$/, '');
        out[name] = stripped.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
      }
    });
  }
  return out;
}

function defaultsForProps(props) {
  return props.map(function (p) {
    if (p.kind === 'boolean') return '      ' + p.name + ': false,';
    if (p.kind === 'number') return '      ' + p.name + ': 0,';
    if (p.kind === 'enum') return '      ' + p.name + ': undefined as unknown as never,';
    return "      " + p.name + ": ''" + (p.optional ? ' as unknown as never' : '') + ',';
  }).join('\n');
}

function formFieldsFor(props, entityKebab, formCtx) {
  // formCtx: 'create' | 'edit' — for data-testid prefix
  var blocks = [];
  props.forEach(function (p) {
    var testidBase = entityKebab + '-' + formCtx + '-' + toKebab(p.name);
    var label = p.name.replace(/([a-z0-9])([A-Z])/g, '$1 $2');
    label = label.charAt(0).toUpperCase() + label.slice(1);
    if (p.kind === 'enum' && p.enumName) {
      blocks.push([
        '          <FormField',
        '            control={form.control}',
        "            name=\"" + p.name + "\"",
        '            render={({ field }) => (',
        '              <FormItem>',
        '                <FormLabel>' + label + '</FormLabel>',
        '                <FormControl>',
        '                  <Select value={field.value as string | undefined} onValueChange={field.onChange}>',
        '                    <SelectTrigger data-testid="' + testidBase + '-trigger"><SelectValue placeholder="—" /></SelectTrigger>',
        '                    <SelectContent>',
        '                      {Object.values(' + p.enumName + ').filter((v) => typeof v === \'string\').map((v) => (',
        '                        <SelectItem key={String(v)} value={String(v)} data-testid={`' + testidBase + '-opt-${String(v)}`}>{String(v)}</SelectItem>',
        '                      ))}',
        '                    </SelectContent>',
        '                  </Select>',
        '                </FormControl>',
        '                <FormMessage />',
        '              </FormItem>',
        '            )}',
        '          />',
      ].join('\n'));
    } else if (p.kind === 'boolean') {
      blocks.push([
        '          <FormField',
        '            control={form.control}',
        "            name=\"" + p.name + "\"",
        '            render={({ field }) => (',
        '              <FormItem className="flex items-center gap-2">',
        '                <FormControl>',
        '                  <Checkbox checked={!!field.value} onCheckedChange={field.onChange} data-testid="' + testidBase + '" />',
        '                </FormControl>',
        '                <FormLabel className="!mt-0">' + label + '</FormLabel>',
        '                <FormMessage />',
        '              </FormItem>',
        '            )}',
        '          />',
      ].join('\n'));
    } else {
      var inputType =
        p.kind === 'number' ? 'number' :
        p.kind === 'date' ? 'date' :
        p.kind === 'email' ? 'email' :
        /password|passwordhash/i.test(p.name) ? 'password' : 'text';
      var fk = p.kind === 'fk' ? '\n                  {/* TODO: convert to Combobox of related ' + p.name.replace(/Id$/, '') + ' once relation-aware scaffolds exist */}' : '';
      blocks.push([
        '          <FormField',
        '            control={form.control}',
        "            name=\"" + p.name + "\"",
        '            render={({ field }) => (',
        '              <FormItem>',
        '                <FormLabel>' + label + '</FormLabel>',
        '                <FormControl>' + fk,
        '                  <Input type="' + inputType + '" {...field} value={(field.value as string | number | undefined) ?? \'\'} data-testid="' + testidBase + '" />',
        '                </FormControl>',
        '                <FormMessage />',
        '              </FormItem>',
        '            )}',
        '          />',
      ].join('\n'));
    }
  });
  return blocks.join('\n');
}

function uiImportsFor(props) {
  var needs = { Input: false, Select: false, Checkbox: false };
  props.forEach(function (p) {
    if (p.kind === 'enum') needs.Select = true;
    else if (p.kind === 'boolean') needs.Checkbox = true;
    else needs.Input = true;
  });
  var lines = [];
  if (needs.Input) lines.push("import { Input } from '~/components/ui/input';");
  if (needs.Select) lines.push("import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '~/components/ui/select';");
  if (needs.Checkbox) lines.push("import { Checkbox } from '~/components/ui/checkbox';");
  // Form primitives (Edit page template doesn't import all of them by default)
  lines.push("import { FormControl, FormField, FormItem, FormLabel, FormMessage } from '~/components/ui/form';");
  return lines.join('\n');
}

function enumImportsFor(props, enumKebabMap) {
  // Group by file: ~/enums/<kebab>.enum
  var byKebab = {};
  props.forEach(function (p) {
    if (p.kind === 'enum' && p.enumName) {
      var kebab = enumKebabMap[p.enumName] || p.enumName.replace(/Enum$/, '').replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
      if (!byKebab[kebab]) byKebab[kebab] = [];
      if (byKebab[kebab].indexOf(p.enumName) === -1) byKebab[kebab].push(p.enumName);
    }
  });
  return Object.keys(byKebab).map(function (k) {
    return "import { " + byKebab[k].join(', ') + " } from '~/enums/" + k + ".enum';";
  }).join('\n');
}

function substituteMarkers(content, opts) {
  // opts: { schemaImports, schemaInline, defaults, formFields, ctx (create|edit), entityCamel, schemaName }
  var ctxUpper = opts.ctx.toUpperCase();
  var prefix = ctxUpper === 'CREATE' ? 'CREATE' : 'EDIT';
  var newContent = content;
  newContent = newContent.replace(
    new RegExp('//\\s*__' + prefix + '_SCHEMA_IMPORTS__'),
    opts.schemaImports
  );
  newContent = newContent.replace(
    new RegExp('//\\s*__' + prefix + '_SCHEMA__'),
    opts.schemaInline
  );
  newContent = newContent.replace(
    new RegExp('//\\s*__' + prefix + '_DEFAULTS__'),
    opts.defaults
  );
  newContent = newContent.replace(
    new RegExp('\\{/\\*\\s*__' + prefix + '_FORM_FIELDS__\\s*\\*/\\}'),
    opts.formFields
  );
  // Refresh marker on first line so re-runs are detected
  newContent = newContent.replace(
    /^\/\*\* Generated by scaffold-(crud-pages|form-from-entity)\.[^*]*\*\//,
    '/** Generated by scaffold-form-from-entity from entity ' + opts.entityCamel + '. */'
  );
  return newContent;
}

function processPage(filePath, entityKebab, entityCamel, entityPascal, parsed, enumImportsMap, ctx, force, dryRun) {
  if (!fs.existsSync(filePath)) return { written: false, reason: 'no-page-file' };
  var content = fs.readFileSync(filePath, 'utf-8');
  // Marker check
  if (!/Generated by scaffold-(crud-pages|form-from-entity)/.test(content.split('\n')[0]) && !force) {
    return { written: false, reason: 'exists-handauthored' };
  }
  var schemaName = ctx === 'create' ? 'create' + entityPascal + 'Schema' : 'update' + entityPascal + 'Schema';
  var schemaImports = [
    'import { ' + schemaName + ' } from \'~/schemas/' + parsed.moduleNameKebab + '.schema\';',
    uiImportsFor(parsed.props),
    enumImportsFor(parsed.props, enumImportsMap),
  ].filter(Boolean).join('\n');
  var defaults = defaultsForProps(parsed.props);
  var formFields = formFieldsFor(parsed.props, entityKebab, ctx);
  var newContent = substituteMarkers(content, {
    ctx: ctx,
    schemaImports: schemaImports,
    schemaInline: '',
    defaults: defaults,
    formFields: formFields,
    entityCamel: entityCamel,
    schemaName: schemaName,
  });
  if (newContent === content) return { written: false, reason: 'unchanged' };
  if (dryRun) return { written: false, reason: 'dry-run' };
  fs.writeFileSync(filePath, newContent);
  return { written: true };
}

function main() {
  var args = parseArgs(process.argv);
  var modulesDir = path.join(args.backendDir, 'src/modules');
  var entities = findEntityFiles(modulesDir);
  if (entities.length === 0) {
    console.log('scaffold-form-from-entity: no entities under ' + modulesDir);
    return;
  }
  var pagesRoot = path.join(args.target, 'app/pages');
  if (!fs.existsSync(pagesRoot)) {
    console.log('scaffold-form-from-entity: no app/pages dir at ' + pagesRoot);
    return;
  }
  var processed = 0, written = 0, skipped = 0;
  entities.forEach(function (e) {
    var entityContent = fs.readFileSync(e.entityFile, 'utf-8');
    var parsed = parseEntity(entityContent);
    if (!parsed || parsed.props.length === 0) {
      if (args.verbose) console.log('  skip (unparsable): ' + e.moduleName);
      return;
    }
    var className = parsed.className.replace(/Entity$/, '');
    var entityKebab = toKebab(className);
    var entityCamel = toCamel(className);
    var entityPascal = toPascal(className);
    parsed.props = parsed.props; // (kept for clarity)
    parsed.moduleNameKebab = toKebab(e.moduleName); // schema files keyed by module name
    var enumImportsMap = findEnumImports(entityContent);

    // Try a few candidate page dir names (entityKebab, entityCamel, moduleNameKebab)
    var candidates = [entityKebab, entityCamel, toKebab(e.moduleName)];
    var pageDir = null;
    for (var i = 0; i < candidates.length; i++) {
      var d = path.join(pagesRoot, candidates[i]);
      if (fs.existsSync(d)) { pageDir = d; break; }
    }
    if (!pageDir) {
      if (args.verbose) console.log('  skip (no page dir for ' + entityPascal + '): tried ' + candidates.join(', '));
      return;
    }
    processed++;
    var createPath = path.join(pageDir, entityPascal + 'CreatePage.tsx');
    var editPath = path.join(pageDir, entityPascal + 'EditPage.tsx');
    var rC = processPage(createPath, entityKebab, entityCamel, entityPascal, parsed, enumImportsMap, 'create', args.force, args.dryRun);
    var rE = processPage(editPath, entityKebab, entityCamel, entityPascal, parsed, enumImportsMap, 'edit', args.force, args.dryRun);
    [rC, rE].forEach(function (r) { if (r.written) written++; else skipped++; });
    if (args.verbose) {
      console.log('  ' + entityPascal + ' (' + parsed.props.length + ' fields): create=' + (rC.written ? 'wrote' : rC.reason) + ' edit=' + (rE.written ? 'wrote' : rE.reason));
    }
  });
  console.log('scaffold-form-from-entity: ' + processed + ' entities, ' + written + ' pages written, ' + skipped + ' skipped');
}

main();
