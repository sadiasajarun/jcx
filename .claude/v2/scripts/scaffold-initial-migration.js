#!/usr/bin/env node
// scaffold-initial-migration.js — v90 (v114: functional fallback)
//
// Emit an initial TypeORM migration once entities are stable, so the database
// can be deployed without `synchronize: true`.
//
// v87/v88/v89 evidence: database evaluator flagged "migrations directory is
// empty" in every run, costing ~0.15 on the 0-1 score. Schema relies on
// TYPEORM_SYNCHRONIZE which silently drifts in prod.
//
// v107 evidence: `migration:generate` requires a LIVE DB connection to diff
// against — unavailable at the database phase — so it fell through to an EMPTY
// TODO stub (empty up()/down()). The database evaluator scored that a P0:
// "InitialSchema migration is a stub ... a production deploy will start with no
// schema and every query will fail." (database-evaluation.json, migration_safety 0.3)
//
// STRATEGY:
//   1. Verify entities exist + data-source.ts exists
//   2. Run `npx typeorm-ts-node-commonjs migration:generate src/database/migrations/InitialSchema -d src/database/data-source.ts`
//      (falls back to `npx typeorm migration:generate ...` if the ts-node
//      variant isn't available). This is the IDEAL path — explicit CREATE TABLE
//      DDL — but only works when a DB is reachable at scaffold time.
//   3. If generation succeeds, log the new migration file
//   4. If it fails (no DB reachable / no entities), emit a FUNCTIONAL migration
//      whose up() builds the full schema from entity metadata at migration:run
//      time via the connection's schema builder — NOT an empty TODO stub. This
//      runs DDL against the real (live) DB at `migration:run`, is deterministic
//      from the entity set, and needs no generate-time DB connection.
//
// Idempotent: if migrations/ already has any *.ts file, skip.
'use strict';

var fs = require('fs');
var path = require('path');
var child_process = require('child_process');

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--target') out.target = argv[++i];
    else if (a === '--name') out.name = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.target) {
    console.error('Usage: scaffold-initial-migration --target <BACKEND_DIR> [--name InitialSchema] [--force]');
    process.exit(1);
  }
  out.name = out.name || 'InitialSchema';
  return out;
}

// First line written into every scaffold-authored migration. Used to tell OUR
// migration apart from an LLM hand-written one so we can replace the latter.
var SCAFFOLD_MARKER = '// Generated by scaffold-initial-migration';

function migrationFiles(migDir) {
  if (!fs.existsSync(migDir)) return [];
  return fs.readdirSync(migDir).filter(function (f) { return /\.ts$/.test(f); });
}

function hasExistingMigrations(migDir) {
  return migrationFiles(migDir).length > 0;
}

// A migration is "ours" if it carries the scaffold marker. Anything else in the
// initial-migration slot is LLM hand-written (and, per v114 evidence, may contain
// invalid SQL like `CREATE TYPE INTEGER AS ENUM` that fails on first apply).
function isScaffoldAuthored(migDir, file) {
  try {
    return fs.readFileSync(path.join(migDir, file), 'utf-8').indexOf(SCAFFOLD_MARKER) >= 0;
  } catch (_) { return false; }
}

// Functional fallback when `migration:generate` can't reach a DB.
//
// up() asks the connection's RdbmsSchemaBuilder to compute the schema diff at
// migration:run time (when the DB IS live). Against an empty database the diff
// is the full CREATE TABLE / index / FK set for every registered entity. We run
// those upQueries on the SAME queryRunner so they participate in the migration's
// transaction. down() runs the corresponding downQueries (DROPs).
//
// This needs NO generate-time DB connection — the SQL is derived from entity
// metadata when the migration actually executes. It is deterministic from the
// entity set and produces a real, runnable, reversible migration (not a stub).
function emitFunctionalMigration(migDir, name) {
  fs.mkdirSync(migDir, { recursive: true });
  var timestamp = '1' + new Date('2026-01-01').getTime();
  var fileName = timestamp + '-' + name + '.ts';
  var className = name + timestamp;
  var content = [
    '// Generated by scaffold-initial-migration',
    "import { MigrationInterface, QueryRunner } from 'typeorm';",
    '',
    'export class ' + className + ' implements MigrationInterface {',
    "  name = '" + className + "';",
    '',
    '  /**',
    '   * Initial schema. Built from entity metadata at run time via the schema',
    '   * builder, so this migration is independent of any generate-time DB',
    '   * connection. Against an empty database the diff is the full CREATE set.',
    '   */',
    '  public async up(queryRunner: QueryRunner): Promise<void> {',
    "    // BaseEntity uses @PrimaryGeneratedColumn('uuid') → uuid_generate_v4(),",
    '    // which requires the uuid-ossp extension. Ensure it before building schema.',
    '    await queryRunner.query(`CREATE EXTENSION IF NOT EXISTS "uuid-ossp"`);',
    '    const sqlInMemory = await queryRunner.connection.driver',
    '      .createSchemaBuilder()',
    '      .log();',
    '    for (const query of sqlInMemory.upQueries) {',
    '      await queryRunner.query(query.query, query.parameters);',
    '    }',
    '  }',
    '',
    '  public async down(queryRunner: QueryRunner): Promise<void> {',
    '    const sqlInMemory = await queryRunner.connection.driver',
    '      .createSchemaBuilder()',
    '      .log();',
    '    for (const query of sqlInMemory.downQueries) {',
    '      await queryRunner.query(query.query, query.parameters);',
    '    }',
    '  }',
    '}',
    '',
  ].join('\n');
  var dst = path.join(migDir, fileName);
  fs.writeFileSync(dst, content);
  return dst;
}

// Read POSTGRES_* connection params from the backend .env (falling back to
// process.env, then sane defaults). Mirrors scaffold-data-source precedence.
function readConn(target) {
  var env = {};
  var envPath = path.join(target, '.env');
  if (fs.existsSync(envPath)) {
    fs.readFileSync(envPath, 'utf-8').split('\n').forEach(function (line) {
      var m = /^([A-Z][A-Z0-9_]*)\s*=\s*(.*)$/.exec(line.trim());
      if (m) env[m[1]] = m[2].replace(/^["']|["']$/g, '');
    });
  }
  function pick() {
    for (var i = 0; i < arguments.length; i++) {
      var k = arguments[i];
      if (env[k]) return env[k];
      if (process.env[k]) return process.env[k];
    }
    return undefined;
  }
  return {
    host: pick('POSTGRES_HOST', 'DB_HOST') || 'localhost',
    port: pick('POSTGRES_PORT', 'DB_PORT') || '5432',
    user: pick('POSTGRES_USER', 'DB_USERNAME', 'DB_USER') || 'postgres',
    password: pick('POSTGRES_PASSWORD', 'DB_PASSWORD') || '',
    database: pick('POSTGRES_DATABASE', 'DB_DATABASE', 'DB_NAME') || 'app',
  };
}

// PRIMARY path: derive the FULL initial schema deterministically and bake it into
// the migration as STATIC SQL.
//
// How: TypeORM's RdbmsSchemaBuilder.log(), run against an EMPTY database, returns
// the exact CREATE TABLE / index / FK query set for every entity — with correct
// enum types, no hand-written-SQL bugs, no dirty-DB diff. We run it HERE (at
// scaffold time) against a throwaway scratch DB, capture the queries, drop the
// scratch DB, and emit them as a static array the migration replays at run time.
//
// Why not run log() inside the migration (the old "functional" approach)?
// Calling the schema builder mid-migration is unreliable — TypeORM introspects an
// in-flight transaction and can emit spurious DROP INDEX statements that fail on a
// fresh DB (v114 evidence: "index IDX_ash_application_ts does not exist"). Run
// standalone against an empty DB the SAME call is clean (0 drops). So we bake it.
//
// Why not `typeorm migration:generate`? It diffs against whatever DB it connects
// to; at the database phase that DB may be dirty, yielding a broken partial
// migration. The scratch DB guarantees an empty baseline.
function emitStaticMigration(target, name, opts) {
  var conn = readConn(target);
  var scratch = (conn.database || 'app').replace(/[^a-zA-Z0-9_]/g, '_') + '_migscratch';
  var srcDb = path.join(target, 'src/database');
  var dataSource = path.join(srcDb, 'data-source.ts');
  if (!fs.existsSync(dataSource)) return { ok: false, reason: 'no data-source.ts' };

  var pgEnv = Object.assign({}, process.env, {
    PGHOST: conn.host, PGPORT: String(conn.port), PGUSER: conn.user, PGPASSWORD: conn.password,
  });
  function sh(cmd, env) {
    return child_process.execSync(cmd, { cwd: target, encoding: 'utf-8', timeout: 90000, stdio: ['ignore', 'pipe', 'pipe'], env: env });
  }

  var introspectFile = path.join(srcDb, '__mig_introspect.ts');
  var introspectSrc = [
    "import { AppDataSource } from './data-source';",
    '(async () => {',
    '  await AppDataSource.initialize();',
    '  const sql = await AppDataSource.driver.createSchemaBuilder().log();',
    '  const map = (qs: any[]) => qs.map((q) => q.query);',
    '  process.stdout.write(JSON.stringify({ up: map(sql.upQueries), down: map(sql.downQueries) }));',
    '  await AppDataSource.destroy();',
    "})().catch((e) => { process.stderr.write(String(e && e.message || e)); process.exit(1); });",
    '',
  ].join('\n');

  var createdScratch = false;
  try {
    // Fresh scratch DB (drop first in case a prior run left one behind).
    try { sh('dropdb --if-exists ' + scratch, pgEnv); } catch (_) {}
    sh('createdb ' + scratch, pgEnv);
    createdScratch = true;

    fs.writeFileSync(introspectFile, introspectSrc);
    var runEnv = Object.assign({}, pgEnv, { POSTGRES_DATABASE: scratch, DB_DATABASE: scratch, DB_NAME: scratch, MIGRATIONS_AUTO_RUN: 'false', TYPEORM_SYNCHRONIZE: 'false' });
    var out = sh('npx --yes ts-node -r tsconfig-paths/register src/database/__mig_introspect.ts', runEnv);
    var parsed = JSON.parse(out.trim());
    if (!parsed.up || parsed.up.length === 0) return { ok: false, reason: 'empty introspection' };

    var hasDown = parsed.down && parsed.down.length > 0;
    var ts = '1' + new Date('2026-01-01').getTime();
    var className = name + ts;
    var content = [
      SCAFFOLD_MARKER + ' (static DDL baked from TypeORM schema builder)',
      "import { MigrationInterface, QueryRunner } from 'typeorm';",
      '',
      'export class ' + className + ' implements MigrationInterface {',
      "  name = '" + className + "';",
      '',
      '  // Full initial schema as explicit SQL, derived from entity metadata via',
      '  // the TypeORM schema builder against an empty database. Replayed verbatim.',
      '  private readonly upQueries: string[] = ' + JSON.stringify(parsed.up, null, 2).replace(/\n/g, '\n  ') + ';',
      '',
      '  private readonly downQueries: string[] = ' + JSON.stringify(hasDown ? parsed.down : [], null, 2).replace(/\n/g, '\n  ') + ';',
      '',
      '  public async up(queryRunner: QueryRunner): Promise<void> {',
      '    await queryRunner.query(`CREATE EXTENSION IF NOT EXISTS "uuid-ossp"`);',
      '    for (const q of this.upQueries) {',
      '      await queryRunner.query(q);',
      '    }',
      '  }',
      '',
      '  public async down(queryRunner: QueryRunner): Promise<void> {',
      '    for (const q of this.downQueries) {',
      '      await queryRunner.query(q);',
      '    }',
      '  }',
      '}',
      '',
    ].join('\n');

    fs.mkdirSync(path.join(target, 'src/database/migrations'), { recursive: true });
    var dst = path.join(target, 'src/database/migrations', ts + '-' + name + '.ts');
    fs.writeFileSync(dst, content);
    return { ok: true, path: dst, count: parsed.up.length };
  } catch (e) {
    if (opts && opts.verbose) console.log('  static-DDL generation failed: ' + (String(e.stderr || e.message || e)).split('\n')[0].slice(0, 140));
    return { ok: false, reason: 'exception' };
  } finally {
    try { if (fs.existsSync(introspectFile)) fs.unlinkSync(introspectFile); } catch (_) {}
    if (createdScratch) { try { sh('dropdb --if-exists ' + scratch, pgEnv); } catch (_) {} }
  }
}

function tryGenerateMigration(target, name, verbose) {
  var srcDir = path.join(target, 'src');
  var dataSource = path.join(srcDir, 'database/data-source.ts');
  var migrationsDir = path.join(srcDir, 'database/migrations');
  if (!fs.existsSync(dataSource)) {
    if (verbose) console.log('  no data-source.ts — emitting stub migration instead');
    return { generated: false };
  }
  fs.mkdirSync(migrationsDir, { recursive: true });
  var outputPath = path.join('src/database/migrations', name);
  // Use typeorm-ts-node-commonjs (typical NestJS+TypeORM setup). Fall through
  // to plain typeorm if it errors.
  var commands = [
    'npx --yes typeorm-ts-node-commonjs migration:generate ' + JSON.stringify(outputPath) +
      ' -d ' + JSON.stringify('src/database/data-source.ts') + ' 2>&1',
    'npx --yes typeorm migration:generate ' + JSON.stringify(outputPath) +
      ' -d ' + JSON.stringify('src/database/data-source.ts') + ' 2>&1',
  ];
  var lastOutput = '';
  for (var i = 0; i < commands.length; i++) {
    try {
      lastOutput = child_process.execSync(commands[i], {
        cwd: target,
        encoding: 'utf-8',
        timeout: 60000,
        stdio: ['ignore', 'pipe', 'pipe'],
      });
      if (verbose) console.log('  ' + commands[i].split(' ')[1] + ' succeeded');
      return { generated: true, output: lastOutput };
    } catch (e) {
      lastOutput = (e.stdout || '') + (e.stderr || '');
      if (verbose) console.log('  attempt failed: ' + (lastOutput.split('\n')[0] || 'unknown error').slice(0, 100));
    }
  }
  return { generated: false, output: lastOutput };
}

// Stamp the scaffold marker onto a typeorm-generated file (typeorm writes the
// file itself, so we prepend the marker afterwards) so future runs recognize it
// as ours and don't replace it.
function stampMarker(migDir) {
  migrationFiles(migDir).forEach(function (f) {
    var p = path.join(migDir, f);
    var c = fs.readFileSync(p, 'utf-8');
    if (c.indexOf(SCAFFOLD_MARKER) < 0) fs.writeFileSync(p, SCAFFOLD_MARKER + '\n' + c);
  });
}

function deleteAllMigrations(migDir, verbose) {
  migrationFiles(migDir).forEach(function (f) {
    fs.unlinkSync(path.join(migDir, f));
    if (verbose) console.log('  removed migration: ' + f);
  });
}

function main() {
  var args = parseArgs(process.argv);
  var migDir = path.join(args.target, 'src/database/migrations');

  var existing = migrationFiles(migDir);
  if (existing.length > 0) {
    // v114: the LLM `implement` node often hand-writes the initial migration
    // (e.g. 001-initial-schema.ts). v114 evidence: it emitted
    // `CREATE TYPE INTEGER AS ENUM (...)` — invalid SQL (reserved keyword) that
    // fails on first apply → no schema → seed/login/test-api/test-browser cascade.
    // The OLD behavior skipped because "migrations already exist", leaving the
    // broken LLM file in place. Now we OWN the initial migration: if any existing
    // migration lacks our marker (LLM-authored), replace the whole slot with the
    // deterministic schema-builder migration (immune to hand-written SQL bugs).
    var foreign = existing.filter(function (f) { return !isScaffoldAuthored(migDir, f); });
    if (foreign.length === 0 && !args.force) {
      console.log('scaffold-initial-migration: ' + existing.length +
        ' scaffold-authored migration(s) present — skipping');
      return;
    }
    if (args.dryRun) {
      console.log('  [dry] would REPLACE ' + existing.length + ' existing migration(s) (' +
        foreign.length + ' LLM-authored) with the deterministic schema migration');
      return;
    }
    console.log('scaffold-initial-migration: replacing ' + existing.length +
      ' existing migration(s) (' + foreign.length + ' LLM-authored: ' +
      foreign.slice(0, 3).join(', ') + (foreign.length > 3 ? '…' : '') + ')');
    deleteAllMigrations(migDir, args.verbose);
  } else if (args.dryRun) {
    console.log('  [dry] would generate initial migration via typeorm migration:generate');
    return;
  }

  // PRIMARY: bake the full schema as static SQL via a scratch-DB introspection
  // (explicit DDL, evaluator-friendly, immune to LLM SQL bugs / dirty-DB diffs /
  // mid-migration schema-builder quirks).
  var staticRes = emitStaticMigration(args.target, args.name, args);
  if (staticRes.ok) {
    console.log('scaffold-initial-migration: wrote static-DDL migration ' +
      path.relative(args.target, staticRes.path) + ' (' + staticRes.count + ' statements)');
    return;
  }
  // FALLBACK: when no DB is reachable to introspect (can't create a scratch DB),
  // emit the migration that runs the schema builder at migration:run time. Works
  // for simple entity sets; primary path is preferred when a DB is available.
  console.log('scaffold-initial-migration: static-DDL path unavailable (' +
    (staticRes.reason || 'unknown') + ') — falling back to runtime schema-builder migration');
  var migPath = emitFunctionalMigration(migDir, args.name);
  console.log('scaffold-initial-migration: wrote functional schema-builder migration ' +
    path.relative(args.target, migPath));
}

main();
