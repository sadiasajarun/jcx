#!/usr/bin/env node
// scaffold-import-manifest.js — v127 (option A: standardize convert-pages' CONTRACT layer).
//
// convert-pages lets the LLM invent data-layer imports (~/services, ~/types, ~/enums,
// redux actions). When the imported module/symbol was never generated → the build breaks
// (TS2307 "Cannot find module", rollup "not exported by"). This is the dominant failure
// class, esp. on the secondary frontends whose LLM output drifts more.
//
// The fix: the contract is DETERMINISTIC — it's whatever the upstream scaffolds
// (enum-sync, api-client-types, service-from-controller, zod-schema) actually produced.
// This scaffold enumerates every importable module + its named exports under the frontend
// and writes IMPORT_MANIFEST.md. convert-pages is then instructed to import ONLY from it.
// The LLM keeps the creative VISUAL layer; the contract layer is pinned to reality.
//
// Runs per-frontend, AFTER the contract scaffolds and BEFORE convert-pages.
'use strict';

var fs = require('fs');
var path = require('path');

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--target') out.target = argv[++i];
    else if (a === '--out') out.out = argv[++i];
  }
  if (!out.target) { console.error('Usage: scaffold-import-manifest --target FRONTEND_DIR [--out FILE]'); process.exit(1); }
  return out;
}

function walk(dir, test, out) {
  out = out || [];
  if (!fs.existsSync(dir)) return out;
  fs.readdirSync(dir, { withFileTypes: true }).forEach(function (e) {
    if (e.name === 'node_modules' || e.name[0] === '.') return;
    var p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, test, out);
    else if (e.isFile() && test(e.name)) out.push(p);
  });
  return out;
}

// Extract the named exports of a module file (best-effort, regex-based).
function exportsOf(src) {
  var names = {};
  var re1 = /export\s+(?:const|function|async\s+function|let|var|class|type|interface|enum)\s+([A-Za-z_$][\w$]*)/g;
  var re2 = /export\s*\{([^}]+)\}/g;
  var re3 = /export\s+const\s*\{([^}]+)\}\s*=/g; // destructured: export const { a, b } = slice.actions
  var m;
  while ((m = re1.exec(src))) names[m[1]] = true;
  while ((m = re2.exec(src))) m[1].split(',').forEach(function (s) { var n = s.trim().replace(/^type\s+/, '').split(/\s+as\s+/).pop().trim(); if (/^[A-Za-z_$][\w$]*$/.test(n)) names[n] = true; });
  while ((m = re3.exec(src))) m[1].split(',').forEach(function (s) { var n = s.trim().split(/\s*:\s*/)[0].trim(); if (/^[A-Za-z_$][\w$]*$/.test(n)) names[n] = true; });
  if (/export\s+default\b/.test(src)) names['default'] = true;
  return Object.keys(names);
}

// One manifest section per importable dir. alias is the `~/...` import prefix.
function section(app, sub, alias, label, fileTest) {
  var dir = path.join(app, sub);
  var files = walk(dir, fileTest || function (n) { return /\.(ts|tsx)$/.test(n) && !/\.(test|spec)\./.test(n); });
  if (!files.length) return '';
  var lines = ['### ' + label + ' — `' + alias + '/...`'];
  files.sort().forEach(function (f) {
    var rel = path.relative(dir, f).replace(/\\/g, '/').replace(/\.(d\.ts|tsx|ts)$/, '');
    var exps = exportsOf(fs.readFileSync(f, 'utf-8')).filter(function (n) { return n !== 'default' || true; });
    var def = exps.indexOf('default') !== -1;
    var named = exps.filter(function (n) { return n !== 'default'; });
    var parts = [];
    if (named.length) parts.push('{ ' + named.slice(0, 24).join(', ') + (named.length > 24 ? ', …' : '') + ' }');
    if (def) parts.push('default');
    lines.push('- `' + alias + '/' + rel + '` — ' + (parts.length ? parts.join(' + ') : '(no named exports)'));
  });
  return lines.join('\n') + '\n';
}

function main() {
  var args = parseArgs(process.argv);
  var app = path.join(args.target, 'app');
  if (!fs.existsSync(app)) { console.log('scaffold-import-manifest: no app/ at ' + args.target + ' — skipping'); return; }

  var body = [
    '# IMPORT MANIFEST (authoritative — generated by scaffold-import-manifest)',
    '',
    'This lists EVERY module + named export available to import in this frontend.',
    'When converting pages you MUST import ONLY from the paths/symbols below. Importing a',
    'module or symbol NOT listed here breaks the production build (TS2307 / "not exported by").',
    'If the data you need is not here, use the closest listed service or render a placeholder —',
    'never invent an import.',
    '',
    section(app, 'services/httpServices', '~/services/httpServices', 'Data services / thunks (dispatch these for API data)'),
    section(app, 'redux/features', '~/redux/features', 'Redux slices (actions + selectors)'),
    section(app, 'types', '~/types', 'Types'),
    section(app, 'enums', '~/enums', 'Enums'),
    section(app, 'hooks', '~/hooks', 'Hooks'),
    section(app, 'components/ui', '~/components/ui', 'UI primitives (shadcn)'),
    section(app, 'components/shared', '~/components/shared', 'Shared components'),
    section(app, 'lib', '~/lib', 'Lib (cn, utils)'),
  ].filter(Boolean).join('\n');

  var outFile = args.out || path.join(args.target, 'IMPORT_MANIFEST.md');
  fs.writeFileSync(outFile, body + '\n');
  var modCount = (body.match(/^- `/gm) || []).length;
  console.log('scaffold-import-manifest: wrote ' + path.relative(process.cwd(), outFile) + ' (' + modCount + ' importable modules)');
}

main();
