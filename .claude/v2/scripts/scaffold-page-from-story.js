#!/usr/bin/env node
// scaffold-page-from-story.js — v86 safety net; PROMOTED v128 to the PRIMARY
// page-generation path ([[feedback_template_wins_llm]]). Deterministic page
// generator from user_story YAMLs.
//
// v128 (--primary): runs BEFORE convert-pages. Every story gets a deterministic
// page first (compiles by construction, story-spec testids, right API calls).
// convert-pages (LLM) is demoted to visual enhancement in place, scope-locked by
// scaffold-scope-lock-doctor (--snapshot before LLM / --enforce before build).
// The same script still runs in its old post-convert slot WITHOUT --primary as
// the safety net for pages deleted by jsx-balance-doctor.
//
// For each story in user_stories/:
//   1. Compute target page path from story.page + story.role + first AC's ui_route
//   2. If a page already exists at any candidate path → skip (LLM or other
//      scaffold handled it; don't fight them)
//   3. If no page exists → emit a deterministic stub that:
//      - Compiles (uses `unknown[]` for state, no exotic imports)
//      - Renders something testable (one section per AC)
//      - Has data-testids matching RULE-F10 conventions
//      - Handles loading/error/empty per boundary_cases + error_scenarios
//      - Uses Shadcn UI (Button, Card) where available, plain HTML otherwise
//
// Why a stub and not a polished page: the bar is `boots + has the data-testids
// the story spec is looking for + makes the API calls the story expects`.
// LLM can refine later; v85 evidence shows worker has cells where convert-pages
// produces 0 pages and the whole cell crashes. A stub that BOOTS is infinitely
// better than no page at all.
//
// Idempotent. Marker on line 1: `// Generated by scaffold-page-from-story`.
'use strict';

var fs = require('fs');
var path = require('path');

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--stories-dir') out.storiesDir = argv[++i];
    else if (a === '--target') out.target = argv[++i];
    else if (a === '--role-filter') out.roleFilter = argv[++i]; // comma list, e.g. "admin,operator"
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--force') out.force = true;
    else if (a === '--primary') out.primary = true; // v128: deterministic-PRIMARY mode (runs BEFORE convert-pages)
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.storiesDir || !out.target) {
    console.error('Usage: scaffold-page-from-story --stories-dir <path> --target <FRONTEND_DIR> [--role-filter <comma-list>] [--dry-run] [--force] [--verbose]');
    process.exit(1);
  }
  return out;
}

function loadYaml() {
  try { return require('yaml'); } catch (_) {}
  try {
    return require(path.join(
      require('child_process').execSync('npm root -g', { encoding: 'utf-8' }).trim(), 'yaml'
    ));
  } catch (e) {
    console.error('scaffold-page-from-story: yaml package not found globally or locally — skipping');
    process.exit(0);
  }
}

var YAML = loadYaml();
var MARKER = '// Generated by scaffold-page-from-story';

// ── Helpers ─────────────────────────────────────────────────────────────

function kebabToPascal(s) {
  return s.split(/[-_\s]+/).filter(Boolean).map(function (p) {
    return p.charAt(0).toUpperCase() + p.slice(1).toLowerCase();
  }).join('');
}

function pageBaseName(story) {
  // From story.page (e.g. '01-admin-dashboard.html') derive the page slug
  // (e.g. 'admin-dashboard'). Strip leading numeric prefix and .html.
  var p = (story.page || story.id || 'page').toString();
  p = p.replace(/\.html$/i, '').replace(/^\d+-/, '');
  return p.toLowerCase();
}

function inferRoleDir(story) {
  // v90: generic role-dir inference. Uses the FIRST segment of the story's
  // `role` field (lowercase) as the role-dir name. This works for any
  // project's role taxonomy — no hardcoded role names.
  //   role: admin           → admin/
  //   role: foreign_worker  → foreign/  (first segment)
  //   role: company_staff   → company/
  //   role: super_admin     → super/    (caller can override via meta)
  //   role: 'all'           → '' (root, public pages)
  //   role: 'guest'         → '' (root)
  var role = (story.role || '').toLowerCase().trim();
  if (!role || role === 'all' || role === 'public' || role === 'guest' || role === 'any') return '';
  // Use first underscore-separated segment as role-dir.
  var firstSeg = role.split('_')[0];
  // Sanitize: only [a-z0-9-] characters allowed in dir name
  return firstSeg.replace(/[^a-z0-9-]/g, '');
}

function componentName(slug) {
  return kebabToPascal(slug) + 'Page';
}

function candidateOutputPaths(appDir, story) {
  // Generate paths to check (existing file → skip) and to choose for write
  // (first that doesn't exist in a child of roleDir).
  var slug = pageBaseName(story);
  var roleDir = inferRoleDir(story);
  var comp = componentName(slug);
  var paths = [];
  // Primary candidates in priority order
  if (roleDir) {
    paths.push('pages/' + roleDir + '/' + slug + '.tsx');
    paths.push('pages/' + roleDir + '/' + comp + '.tsx');
  }
  paths.push('pages/' + slug + '.tsx');
  paths.push('pages/' + comp + '.tsx');
  // Also check for any tsx anywhere that contains the slug as its filename stem.
  return paths.map(function (p) { return path.join(appDir, p); });
}

function pageExistsForStory(appDir, story) {
  var candidates = candidateOutputPaths(appDir, story);
  for (var i = 0; i < candidates.length; i++) {
    if (fs.existsSync(candidates[i])) return candidates[i];
  }
  // Also do a broader search: any page under app/pages/ whose filename stem
  // (lowercased) contains the slug. Catches LLM creative naming.
  var slug = pageBaseName(story);
  var stemPart = slug.replace(/-/g, '');
  var pagesDir = path.join(appDir, 'pages');
  if (!fs.existsSync(pagesDir)) return null;
  var found = null;
  walkTsx(pagesDir, function (f) {
    if (found) return;
    var stem = path.basename(f, '.tsx').toLowerCase().replace(/[-_]/g, '');
    if (stem === stemPart || stem === (stemPart + 'page')) found = f;
  });
  return found;
}

function walkTsx(dir, cb) {
  if (!fs.existsSync(dir)) return;
  fs.readdirSync(dir, { withFileTypes: true }).forEach(function (e) {
    var p = path.join(dir, e.name);
    if (e.isDirectory()) walkTsx(p, cb);
    else if (e.isFile() && /\.tsx$/.test(e.name)) cb(p);
  });
}

function chooseOutputPath(appDir, story) {
  // Write to the FIRST primary candidate path.
  var candidates = candidateOutputPaths(appDir, story);
  return candidates[0];
}

// ── Endpoint analysis ───────────────────────────────────────────────────

function parseEndpoint(epStr) {
  if (!epStr || typeof epStr !== 'string') return null;
  var m = /^\s*(GET|POST|PATCH|PUT|DELETE)\s+(\/\S+)/i.exec(epStr);
  if (!m) return null;
  return { method: m[1].toUpperCase(), path: m[2] };
}

function endpointToFnName(ep, idx) {
  // GET /companies/:id → loadCompany1
  // PATCH /affiliations/:id/approve → approveAffiliation2
  var verb = ({GET: 'load', POST: 'create', PATCH: 'update', PUT: 'replace', DELETE: 'remove'})[ep.method] || 'call';
  var seg = ep.path.split('/').filter(function (s) { return s && !s.startsWith(':'); });
  // For PATCH /:id/approve → use the last segment as verb if it's a verb-like word
  if ((ep.method === 'PATCH' || ep.method === 'POST') && seg.length >= 2 && /^(approve|reject|cancel|submit|verify|confirm|publish|archive)$/.test(seg[seg.length - 1])) {
    verb = seg.pop();
  }
  var noun = seg.length > 0 ? kebabToPascal(seg[seg.length - 1]) : 'Item';
  // De-pluralize 'companies' → 'Company' if we can keep it short
  var name = verb + noun;
  return name + (idx + 1);
}

function endpointUiKind(ep, expected) {
  var exp = (expected || '').toLowerCase();
  // KPI cards
  if (/kpi|count|total|metric|stat|number of/.test(exp)) return 'kpi';
  // Modal
  if (/modal|dialog|popup/.test(exp)) return 'modal';
  // List/table
  if (ep.method === 'GET' && /list|table|grid|of (\w+)/.test(exp)) return 'list';
  // Action button (approve/reject/confirm)
  if (ep.method !== 'GET' && /button|click|submit|approve|reject|confirm|cancel/.test(exp)) return 'action';
  // Form
  if (ep.method === 'POST' || /form|input|field|submit/.test(exp)) return 'form';
  // Detail view
  if (ep.method === 'GET' && /shows|displays|view|detail/.test(exp)) return 'detail';
  return ep.method === 'GET' ? 'detail' : 'action';
}

// ── Code rendering ──────────────────────────────────────────────────────

function snakeToTestid(slug, ac, kind) {
  // RULE-F10 convention: {page}-{element}[-{action}]
  return slug + '-' + (ac.id || 'ac').toLowerCase() + (kind ? '-' + kind : '');
}

function renderImports(needsForm, needsModal) {
  var lines = [
    "import { useEffect, useState } from 'react';",
    "import { Link } from 'react-router';",
  ];
  // Best-effort Shadcn imports — these may not exist in every cell. Wrap in
  // try/catch via dynamic? No — keep imports static so vite errors loudly if
  // missing. scaffold-page-imports-doctor will add stubs if components are
  // missing. For safety, use plain <button>/<input> here instead of Shadcn.
  // (Stub-quality > broken-import.)
  return lines.join('\n');
}

function renderACSection(slug, ac, idx) {
  var ep = parseEndpoint(ac.endpoint);
  var fnName = ep ? endpointToFnName(ep, idx) : null;
  var stateName = 'data' + (idx + 1);
  var loadingName = 'loading' + (idx + 1);
  var errorName = 'error' + (idx + 1);
  var kind = ep ? endpointUiKind(ep, ac.expected) : 'static';
  var testidBase = slug + '-' + ((ac.id || 'ac' + (idx + 1)).toLowerCase());

  var sections = {
    state: [],
    effects: [],
    handlers: [],
    jsx: [],
  };

  if (!ep) {
    // Static AC (no endpoint) — just render description + expected as visible text
    sections.jsx.push(
      '          <section className="rounded border border-gray-200 p-4" data-testid="' + testidBase + '">',
      '            <h2 className="mb-2 text-lg font-semibold">' + escapeJsx(ac.description || ac.id || 'Section ' + (idx + 1)) + '</h2>',
      '            <p className="text-sm text-gray-600">' + escapeJsx(ac.expected || '') + '</p>',
      '          </section>'
    );
    return sections;
  }

  // GET endpoint → fetch on mount
  if (ep.method === 'GET') {
    sections.state.push(
      '  const [' + stateName + ', set' + capitalize(stateName) + '] = useState<unknown>(null);',
      '  const [' + loadingName + ', set' + capitalize(loadingName) + '] = useState<boolean>(true);',
      '  const [' + errorName + ', set' + capitalize(errorName) + '] = useState<string | null>(null);'
    );
    sections.effects.push(
      '  useEffect(() => {',
      '    let cancelled = false;',
      '    set' + capitalize(loadingName) + '(true);',
      '    set' + capitalize(errorName) + '(null);',
      '    fetch(' + JSON.stringify('/api' + interpolatePath(ep.path)) + ', { credentials: \'include\' })',
      '      .then((r) => r.ok ? r.json() : Promise.reject(new Error(\'HTTP \' + r.status)))',
      '      .then((d) => { if (!cancelled) set' + capitalize(stateName) + '(d); })',
      '      .catch((e) => { if (!cancelled) set' + capitalize(errorName) + '((e as Error).message); })',
      '      .finally(() => { if (!cancelled) set' + capitalize(loadingName) + '(false); });',
      '    return () => { cancelled = true; };',
      '  }, []);'
    );

    if (kind === 'list') {
      // Render as list with empty + loading + error states
      sections.jsx.push(
        '          <section className="rounded border border-gray-200 p-4" data-testid="' + testidBase + '">',
        '            <h2 className="mb-2 text-lg font-semibold">' + escapeJsx(ac.description || '') + '</h2>',
        '            {' + loadingName + ' && <p data-testid="' + testidBase + '-loading">Loading...</p>}',
        '            {' + errorName + ' && (',
        '              <div data-testid="' + testidBase + '-error" className="text-red-600">',
        '                <p>Unable to load: {' + errorName + '}</p>',
        '                <button onClick={() => window.location.reload()} className="mt-2 rounded bg-blue-600 px-3 py-1 text-white" data-testid="' + testidBase + '-retry">Retry</button>',
        '              </div>',
        '            )}',
        '            {!' + loadingName + ' && !' + errorName + ' && (() => {',
        '              const items = Array.isArray((' + stateName + ' as { items?: unknown[] })?.items) ? (' + stateName + ' as { items: unknown[] }).items : (Array.isArray(' + stateName + ') ? (' + stateName + ' as unknown[]) : []);',
        '              if (items.length === 0) return <p data-testid="' + testidBase + '-empty" className="text-gray-500">No items yet.</p>;',
        '              return (',
        '                <ul data-testid="' + testidBase + '-list" className="divide-y">',
        '                  {items.map((item, i) => (',
        '                    <li key={i} data-testid={`' + testidBase + '-item-${i}`} className="py-2">',
        '                      <pre className="text-xs">{JSON.stringify(item, null, 2)}</pre>',
        '                    </li>',
        '                  ))}',
        '                </ul>',
        '              );',
        '            })()}',
        '          </section>'
      );
    } else if (kind === 'kpi') {
      // KPI card grid
      sections.jsx.push(
        '          <section className="rounded border border-gray-200 p-4" data-testid="' + testidBase + '">',
        '            <h2 className="mb-2 text-lg font-semibold">' + escapeJsx(ac.description || '') + '</h2>',
        '            {' + loadingName + ' && <p data-testid="' + testidBase + '-loading">Loading...</p>}',
        '            {' + errorName + ' && <p data-testid="' + testidBase + '-error" className="text-red-600">Unable to load</p>}',
        '            {!' + loadingName + ' && !' + errorName + ' && (',
        '              <div className="grid grid-cols-1 gap-4 sm:grid-cols-3" data-testid="' + testidBase + '-kpis">',
        '                {Object.entries((' + stateName + ' && typeof ' + stateName + ' === \'object\') ? ' + stateName + ' as Record<string, unknown> : {}).slice(0, 6).map(([key, value]) => (',
        '                  <div key={key} data-testid={`' + testidBase + '-kpi-${key}`} className="rounded bg-gray-50 p-3">',
        '                    <p className="text-xs text-gray-500">{key}</p>',
        '                    <p className="text-2xl font-bold">{typeof value === \'number\' || typeof value === \'string\' ? String(value) : \'-\'}</p>',
        '                  </div>',
        '                ))}',
        '              </div>',
        '            )}',
        '          </section>'
      );
    } else {
      // Detail view
      sections.jsx.push(
        '          <section className="rounded border border-gray-200 p-4" data-testid="' + testidBase + '">',
        '            <h2 className="mb-2 text-lg font-semibold">' + escapeJsx(ac.description || '') + '</h2>',
        '            {' + loadingName + ' && <p data-testid="' + testidBase + '-loading">Loading...</p>}',
        '            {' + errorName + ' && <p data-testid="' + testidBase + '-error" className="text-red-600">Unable to load</p>}',
        '            {!' + loadingName + ' && !' + errorName + ' && (',
        '              <pre className="overflow-auto text-xs" data-testid="' + testidBase + '-detail">{JSON.stringify(' + stateName + ', null, 2)}</pre>',
        '            )}',
        '          </section>'
      );
    }
  } else {
    // Mutation endpoint — render action button
    var handlerName = fnName;
    sections.handlers.push(
      '  const [' + loadingName + ', set' + capitalize(loadingName) + '] = useState<boolean>(false);',
      '  const ' + handlerName + ' = async () => {',
      '    set' + capitalize(loadingName) + '(true);',
      '    try {',
      '      const r = await fetch(' + JSON.stringify('/api' + interpolatePath(ep.path)) + ', { method: ' + JSON.stringify(ep.method) + ', credentials: \'include\', headers: { \'Content-Type\': \'application/json\' }, body: \'{}\' });',
      '      if (!r.ok) throw new Error(\'HTTP \' + r.status);',
      '      // success — TODO: refresh related list / show success toast',
      '    } catch (e) {',
      '      // TODO: show error toast',
      '      console.error(e);',
      '    } finally {',
      '      set' + capitalize(loadingName) + '(false);',
      '    }',
      '  };'
    );
    sections.jsx.push(
      '          <section className="rounded border border-gray-200 p-4" data-testid="' + testidBase + '">',
      '            <h2 className="mb-2 text-lg font-semibold">' + escapeJsx(ac.description || '') + '</h2>',
      '            <button',
      '              type="button"',
      '              onClick={' + handlerName + '}',
      '              disabled={' + loadingName + '}',
      '              className="rounded bg-blue-600 px-4 py-2 text-white disabled:opacity-50"',
      '              data-testid="' + testidBase + '-action"',
      '            >',
      '              {' + loadingName + ' ? \'Submitting...\' : \'' + actionVerb(ep) + '\'}',
      '            </button>',
      '          </section>'
    );
  }

  return sections;
}

function interpolatePath(p) {
  // Replace :foo with 'PLACEHOLDER' for the literal URL. Keeps the URL VALID
  // (a string), tests can mock. Better: use a route param if available.
  return p.replace(/:[a-zA-Z][a-zA-Z0-9]*/g, '__PLACEHOLDER__');
}

function actionVerb(ep) {
  var p = ep.path.toLowerCase();
  if (/approve/.test(p)) return 'Approve';
  if (/reject/.test(p)) return 'Reject';
  if (/cancel/.test(p)) return 'Cancel';
  if (/submit/.test(p)) return 'Submit';
  if (/verify/.test(p)) return 'Verify';
  if (/confirm/.test(p)) return 'Confirm';
  if (ep.method === 'POST') return 'Create';
  if (ep.method === 'DELETE') return 'Delete';
  return 'Save';
}

function capitalize(s) { return s.charAt(0).toUpperCase() + s.slice(1); }

function escapeJsx(s) {
  return String(s || '').replace(/[<>{}]/g, function (c) {
    return ({'<': '&lt;', '>': '&gt;', '{': '&#123;', '}': '&#125;'})[c];
  }).slice(0, 500);
}

function renderPage(story, primary) {
  var slug = pageBaseName(story);
  var compName = componentName(slug);
  var acs = Array.isArray(story.acceptance_criteria) ? story.acceptance_criteria : [];

  var sections = acs.map(function (ac, i) { return renderACSection(slug, ac, i); });

  var state = sections.flatMap(function (s) { return s.state; });
  var effects = sections.flatMap(function (s) { return s.effects; });
  var handlers = sections.flatMap(function (s) { return s.handlers; });
  var jsx = sections.flatMap(function (s) { return s.jsx; });

  var feature = story.feature || story.id || slug;
  var goal = (story.goal || '').replace(/\r?\n/g, ' ').slice(0, 200);

  var lines = [
    MARKER + ' from user_stories/' + (story.__file || (story.id + '.yaml')),
    '// Story: ' + (story.id || ''),
    '// Role:  ' + (story.role || 'all'),
    '// Feature: ' + feature,
    '// Goal: ' + goal,
    '//',
    primary
      ? '// PRIMARY deterministic page (v128): generated BEFORE convert-pages. It\n' +
        '// compiles by construction, carries the story-spec data-testids, and makes\n' +
        '// the API calls the story expects. convert-pages (LLM) may RESTYLE this file\n' +
        '// in place but is scope-locked: data-testids + default export must survive\n' +
        '// (enforced by scaffold-scope-lock-doctor — violations restore this version).'
      : '// SAFETY-NET stub: this file is emitted when no other scaffold or LLM\n' +
        '// produced a page for this story. It renders one section per acceptance\n' +
        '// criterion with data-testids matching the story-spec selectors. Quality\n' +
        '// is intentionally minimal — bar is `boots + makes the right API calls`.',
    '',
    "import { useEffect, useState } from 'react';",
    "import { Link } from 'react-router';",
    '',
    'export default function ' + compName + '() {',
  ];

  lines.push.apply(lines, state);
  if (state.length > 0) lines.push('');
  lines.push.apply(lines, effects);
  if (effects.length > 0) lines.push('');
  lines.push.apply(lines, handlers);
  if (handlers.length > 0) lines.push('');

  lines.push(
    '  return (',
    '    <div className="min-h-screen bg-white" data-testid="' + slug + '-page">',
    '      <header className="border-b border-gray-200 p-4">',
    '        <Link to="/" className="text-sm text-gray-500" data-testid="' + slug + '-home-link">Home</Link>',
    '        <h1 className="mt-2 text-2xl font-bold" data-testid="' + slug + '-heading">' + escapeJsx(feature) + '</h1>',
    '      </header>',
    '      <main className="space-y-4 p-4" data-testid="' + slug + '-main">'
  );
  if (jsx.length === 0) {
    lines.push('        <p className="text-gray-500" data-testid="' + slug + '-empty">No acceptance criteria defined.</p>');
  } else {
    lines.push.apply(lines, jsx);
  }
  lines.push(
    '      </main>',
    '    </div>',
    '  );',
    '}',
    ''
  );

  return lines.join('\n');
}

// ── Story discovery + main ──────────────────────────────────────────────

function repairYaml(raw) {
  // Mirrors scaffold-story-specs repair logic. LLM-authored YAMLs commonly have:
  //   (a) `expected: "X" Y Z` — quoted scalar followed by unquoted text
  //   (b) `description: User selects from options: A, B` — inner `:` (followed
  //       by space) makes YAML parse it as a nested mapping.
  // Repair: wrap such values in single quotes.
  return raw.split('\n').map(function (line) {
    var m = /^(\s*(?:-\s+)?[a-zA-Z_][\w-]*\s*:\s*)(.+)$/.exec(line);
    if (!m) return line;
    var key = m[1], value = m[2];
    var trimmed = value.trim();
    if (/^[|>!&*#]/.test(trimmed)) return line;
    if (/^"[^"]*"$/.test(trimmed) || /^'[^']*'$/.test(trimmed)) return line;
    if (/^(true|false|null|~|-?\d+(\.\d+)?)$/.test(trimmed)) return line;
    var hasInnerQuote = /"/.test(value) && !/^"[^"]*"\s*$/.test(trimmed);
    var hasInnerColonSpace = /:\s/.test(value);
    if (hasInnerQuote || hasInnerColonSpace) {
      var escaped = value.replace(/'/g, "''");
      return key + "'" + escaped + "'";
    }
    return line;
  }).join('\n');
}

function loadStory(filePath) {
  var raw;
  try { raw = fs.readFileSync(filePath, 'utf-8'); } catch (_) { return null; }
  var doc;
  try {
    doc = YAML.parse(raw);
  } catch (e) {
    try {
      doc = YAML.parse(repairYaml(raw));
    } catch (e2) {
      if (process.env.DEBUG) console.error('  yaml parse failed for ' + filePath + ': ' + e.message);
      return null;
    }
  }
  if (!doc || typeof doc !== 'object') return null;
  doc.__file = path.basename(filePath);
  return doc;
}

function storyMatchesRoleFilter(story, filter) {
  if (!filter) return true;
  var roles = filter.split(',').map(function (s) { return s.trim().toLowerCase(); });
  var id = (story.id || '').toLowerCase();
  var role = (story.role || '').toLowerCase();
  return roles.some(function (r) {
    if (r === role) return true;
    // Match by id prefix: 'admin' matches US-ADMIN-*, 'company' matches US-COMPANY-*, etc.
    if (id.includes('-' + r + '-') || id.endsWith('-' + r)) return true;
    return false;
  });
}

function deriveRoutePath(story, outRelPath) {
  // outRelPath is e.g. 'pages/admin/admin-dashboard.tsx'.
  // First AC's ui_route is the user-intended URL. Sanitize:
  // - strip leading /
  // - strip query strings (RR7 routes don't include `?foo=bar`)
  // - strip trailing /
  // - empty/falsy → fall back to filename slug
  var acs = Array.isArray(story.acceptance_criteria) ? story.acceptance_criteria : [];
  var url = acs[0] && acs[0].ui_route ? String(acs[0].ui_route).trim() : null;
  if (url) {
    url = url.split('?')[0].split('#')[0];      // drop query/hash
    url = url.replace(/^\//, '').replace(/\/$/, '');
    // Only accept paths that look like a real route segment: [a-zA-Z0-9_:/-]+
    if (url && /^[a-zA-Z0-9_:/-]+$/.test(url)) return url;
  }
  // Fall back to filename slug
  var slug = pageBaseName(story);
  var roleDir = inferRoleDir(story);
  return (roleDir ? roleDir + '/' : '') + slug;
}

function renderRoutesFile(entries) {
  var lines = [
    MARKER + ' — routes for stub pages emitted by scaffold-page-from-story.',
    '//',
    '// Each entry maps story.acceptance_criteria[0].ui_route → page path.',
    '// scaffold-convert-wire-routes aggregates this into top-level routes.ts.',
    '// SAFE TO DELETE: regenerated on next pipeline run if no stubs are emitted.',
    '',
    "import { route } from '@react-router/dev/routes';",
    '',
    'export const safetyNetRoutes = [',
  ];
  entries.forEach(function (e) {
    if (e.routePath === null || e.routePath === '') {
      // Skip index routes — too risky to override existing index. The page exists at the file path; routes-prune will catch dangling refs anyway.
      lines.push('  // index route skipped for ' + e.componentPath + ' (avoid colliding with existing index)');
      return;
    }
    lines.push('  route(' + JSON.stringify(e.routePath) + ', ' + JSON.stringify(e.componentPath) + ', { id: ' + JSON.stringify('safety-net-' + e.id) + ' }),');
  });
  lines.push('];');
  lines.push('');
  return lines.join('\n');
}

function main() {
  var args = parseArgs(process.argv);
  if (!fs.existsSync(args.storiesDir)) {
    console.log('scaffold-page-from-story: stories dir not found: ' + args.storiesDir);
    return;
  }
  var appDir = path.join(args.target, 'app');
  if (!fs.existsSync(appDir)) {
    console.log('scaffold-page-from-story: target app/ not found: ' + appDir);
    return;
  }
  fs.mkdirSync(path.join(appDir, 'pages'), { recursive: true });

  var files = fs.readdirSync(args.storiesDir)
    .filter(function (f) { return /\.ya?ml$/.test(f) && !/^_/.test(f); })
    .map(function (f) { return path.join(args.storiesDir, f); });

  var written = 0, skippedExisting = 0, skippedRole = 0, failed = 0, routeEntries = [];
  files.forEach(function (filePath) {
    var story = loadStory(filePath);
    if (!story) { failed++; return; }
    if (!storyMatchesRoleFilter(story, args.roleFilter)) {
      skippedRole++;
      return;
    }
    var existing = pageExistsForStory(appDir, story);
    if (existing && !args.force) {
      if (args.verbose) console.log('  skip ' + story.id + ' (exists: ' + path.relative(appDir, existing) + ')');
      skippedExisting++;
      return;
    }
    var outPath = chooseOutputPath(appDir, story);
    fs.mkdirSync(path.dirname(outPath), { recursive: true });
    var content = renderPage(story, args.primary);
    var outRelToApp = path.relative(appDir, outPath);
    var routePath = deriveRoutePath(story, outRelToApp);
    var componentPath = outRelToApp.replace(/\\/g, '/'); // win-safe (we write to mac/linux but be safe)
    if (args.dryRun) {
      console.log('  [dry] would write ' + outRelToApp + ' (' + content.split('\n').length + ' lines, route=' + (routePath || '(index)') + ')');
    } else {
      fs.writeFileSync(outPath, content);
      if (args.verbose) console.log('  wrote ' + outRelToApp + ' (' + story.id + ', route=' + (routePath || '(index)') + ')');
    }
    routeEntries.push({
      id: (story.id || pageBaseName(story)).toLowerCase().replace(/[^a-z0-9]+/g, '-'),
      routePath: routePath,
      componentPath: componentPath,
    });
    written++;
  });

  // Emit safety-net.routes.ts so scaffold-convert-wire-routes picks the pages up
  if (routeEntries.length > 0) {
    var routesDir = path.join(appDir, 'routes');
    fs.mkdirSync(routesDir, { recursive: true });
    var routesFile = path.join(routesDir, 'safety-net.routes.ts');
    var routesContent = renderRoutesFile(routeEntries);
    if (args.dryRun) {
      console.log('  [dry] would write routes/safety-net.routes.ts (' + routeEntries.length + ' entries)');
    } else {
      fs.writeFileSync(routesFile, routesContent);
      if (args.verbose) console.log('  wrote routes/safety-net.routes.ts (' + routeEntries.length + ' entries)');
    }
  }

  console.log('scaffold-page-from-story: ' + written + ' written, ' + skippedExisting + ' skipped (page exists), ' + skippedRole + ' skipped (role filter), ' + failed + ' parse failures');
}

main();
