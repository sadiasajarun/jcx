#!/usr/bin/env node
// scaffold-stray-output-doctor.js — v128.
//
// PROBLEM (v127 evidence): convert-pages fanout cells were told to write under
// the RELATIVE path `{FRONTEND_DIR}/app/pages/`, but every context file in the
// prompt carried an ABSOLUTE path under `<run>/.claude-project/fsp/...`. The
// LLM anchored its Write paths to that prefix and emitted pages into
// `<run>/.claude-project/fsp/<frontend-dir>/app/pages/` — a directory nothing
// builds. v127: admin-dashboard wrote 128 stray pages vs 67 real; company-
// dashboard 58 stray vs 40 real (19 of the 40 real were safety-net stubs that
// only existed because the LLM's actual conversion landed in the stray root).
// scope_guard in blueprints is documentation-only — no deterministic path
// enforcement exists — so the writes succeeded silently.
//
// FIX (deterministic, [[feedback_template_wins_llm]]): after every LLM node
// that writes frontend code, sweep the stray root and RELOCATE the work:
//   stray = <target>/<project-dir>/<frontend-dir>/app/**
//   real  = <target>/<frontend-dir>/app/**
//   - real missing                → move stray in (it IS the intended output)
//   - real is a scaffold-marked stub + stray is LLM-authored (no marker)
//     → adopt stray over the stub, but ONLY for app/pages/** (the
//       enhance-in-place intent landed in the wrong place; the scope-lock
//       enforce node downstream still guards the testid/default-export
//       contract and restores the stub if the LLM broke it)
//   - real exists and is LLM-authored → discard stray (real one already won)
// Then the stray root is deleted — `<project-dir>/<frontend-dir>/` is never a
// legitimate location.
//
// Idempotent: second run finds no stray root and exits 0.
//
// Usage:
//   scaffold-stray-output-doctor --target <RUN_DIR> --frontend-dir <DIR>
//                                [--project-dir .claude-project/fsp] [--verbose]
'use strict';

var fs = require('fs');
var path = require('path');

var MARKER_RE = /^\/\/ Generated by scaffold-/;

function parseArgs(argv) {
  var out = { projectDir: null };
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--target') out.target = argv[++i];
    else if (a === '--frontend-dir') out.frontendDir = argv[++i];
    else if (a === '--project-dir') out.projectDir = argv[++i];
    else if (a === '--verbose' || a === '-v') out.verbose = true;
    else if (a === '--dry-run') out.dryRun = true;
  }
  if (!out.target || !out.frontendDir) {
    console.error('Usage: scaffold-stray-output-doctor --target <RUN_DIR> --frontend-dir <DIR> [--project-dir <DIR>] [--dry-run] [--verbose]');
    process.exit(1);
  }
  return out;
}

// Find the project dir if not given: any <target>/.claude-project/<proj>
// that contains the stray frontend root.
function findProjectDirs(target, frontendDir, explicit) {
  if (explicit) {
    var p = path.join(target, explicit, frontendDir);
    return fs.existsSync(p) ? [path.join(target, explicit)] : [];
  }
  var cpRoot = path.join(target, '.claude-project');
  if (!fs.existsSync(cpRoot)) return [];
  return fs.readdirSync(cpRoot, { withFileTypes: true })
    .filter(function (e) { return e.isDirectory(); })
    .map(function (e) { return path.join(cpRoot, e.name); })
    .filter(function (d) { return fs.existsSync(path.join(d, frontendDir)); });
}

function walk(dir, cb) {
  fs.readdirSync(dir, { withFileTypes: true }).forEach(function (e) {
    var p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, cb);
    else if (e.isFile()) cb(p);
  });
}

function main() {
  var args = parseArgs(process.argv);
  var projDirs = findProjectDirs(args.target, args.frontendDir, args.projectDir);
  if (projDirs.length === 0) {
    console.log('scaffold-stray-output-doctor: no stray root — nothing to do');
    return;
  }
  var realRoot = path.join(args.target, args.frontendDir);
  var moved = 0, adopted = 0, discarded = 0;

  projDirs.forEach(function (projDir) {
    var strayRoot = path.join(projDir, args.frontendDir);
    var strayApp = path.join(strayRoot, 'app');
    if (fs.existsSync(strayApp)) {
      walk(strayApp, function (strayFile) {
        var rel = path.relative(strayRoot, strayFile).replace(/\\/g, '/');
        var real = path.join(realRoot, rel);
        var verdict;
        var isPages = rel.indexOf('app/pages/') === 0;
        // Only pages are relocatable. Routes/layouts/services strays are owned
        // by dedicated scaffold nodes in the real tree — moving an LLM-authored
        // stray in could clobber wiring or add a file with broken imports that
        // fails a build which previously passed.
        if (!isPages) {
          discarded++;
          if (args.verbose) console.log('  discarded (non-pages stray): ' + rel);
          return;
        }
        if (!fs.existsSync(real)) {
          verdict = 'MOVED (real missing)';
          if (!args.dryRun) {
            fs.mkdirSync(path.dirname(real), { recursive: true });
            fs.copyFileSync(strayFile, real);
          }
          moved++;
        } else {
          var realSrc = fs.readFileSync(real, 'utf-8');
          var straySrc = fs.readFileSync(strayFile, 'utf-8');
          if (MARKER_RE.test(realSrc) && !MARKER_RE.test(straySrc)) {
            verdict = 'ADOPTED over scaffold stub (scope-lock enforce still guards contract)';
            if (!args.dryRun) fs.copyFileSync(strayFile, real);
            adopted++;
          } else {
            verdict = 'discarded (real file already LLM-authored or stray is a stub)';
            discarded++;
          }
        }
        if (args.verbose || verdict.indexOf('discarded') !== 0) {
          console.log('  ' + verdict + ': ' + rel);
        }
      });
    }
    if (!args.dryRun) fs.rmSync(strayRoot, { recursive: true, force: true });
    console.log('scaffold-stray-output-doctor: swept ' + path.relative(args.target, strayRoot));
  });

  console.log('scaffold-stray-output-doctor: ' + moved + ' moved, ' + adopted + ' adopted, ' + discarded + ' discarded' + (args.dryRun ? ' (dry-run)' : ''));
}

main();
