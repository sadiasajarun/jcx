#!/usr/bin/env node
// scaffold-pwa-manifest.js — v78 emit public/manifest.webmanifest +
// public/sw.js service worker stub + appends manifest link tag to
// app/root.tsx <head>. Reads app name from PROJECT_KNOWLEDGE.md if present.
//
// Idempotent. Markers: '"_marker"' in manifest, comment in sw.js.
'use strict';

var fs = require('fs');
var path = require('path');

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--target') out.target = argv[++i];
    else if (a === '--knowledge') out.knowledge = argv[++i];
    else if (a === '--name') out.name = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--dry-run') out.dryRun = true;
  }
  if (!out.target) { console.error('Usage: scaffold-pwa-manifest --target FRONTEND_DIR [--knowledge ...] [--name X]'); process.exit(1); }
  return out;
}

function detectAppName(knowledgePath, fallback) {
  if (!knowledgePath || !fs.existsSync(knowledgePath)) return fallback;
  var content = fs.readFileSync(knowledgePath, 'utf-8');
  var m = /^#\s+(.+)$/m.exec(content);
  return m ? m[1].trim() : fallback;
}

function writeIfManaged(file, content, markerRe, force, dryRun) {
  if (fs.existsSync(file)) {
    var existing = fs.readFileSync(file, 'utf-8');
    if (!markerRe.test(existing) && !force) return { written: false, reason: 'exists-handauthored' };
    if (existing === content) return { written: false, reason: 'unchanged' };
  }
  if (dryRun) return { written: false, reason: 'dry-run' };
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return { written: true };
}

var SW_JS = [
  '// Generated by scaffold-pwa-manifest — DO NOT EDIT BY HAND. Re-run to refresh.',
  '// Minimal service worker stub: registers + immediately claims, no caching.',
  '// Replace with Workbox or custom strategy when the app needs offline support.',
  "self.addEventListener('install', () => self.skipWaiting());",
  "self.addEventListener('activate', (e) => e.waitUntil(self.clients.claim()));",
  "self.addEventListener('fetch', () => {});",
  '',
].join('\n');

function patchRoot(target, dryRun) {
  // RR7: app/root.tsx — append <link rel="manifest" href="/manifest.webmanifest" /> and <meta name="theme-color">
  var candidates = ['app/root.tsx', 'app/root.jsx', 'src/root.tsx', 'app/entry.client.tsx', 'src/main.tsx'];
  for (var i = 0; i < candidates.length; i++) {
    var p = path.join(target, candidates[i]);
    if (!fs.existsSync(p)) continue;
    var content = fs.readFileSync(p, 'utf-8');
    if (/manifest\.webmanifest/.test(content)) return { patched: false, reason: 'already-references-manifest', file: candidates[i] };
    // Try to inject inside <Links/> area or before <Meta />. Conservative: just leave a hint comment if we can't.
    // Inject after first `<head>` if classic; for RR7 inject before `<Links` element.
    var injected = false;
    var newContent = content;
    if (/<head[^>]*>/.test(content)) {
      newContent = content.replace(/<head([^>]*)>/, '<head$1>\n        <link rel="manifest" href="/manifest.webmanifest" />\n        <meta name="theme-color" content="#000000" />');
      injected = true;
    } else if (/<Links\s*\/>/.test(content)) {
      newContent = content.replace(/<Links\s*\/>/, '<link rel="manifest" href="/manifest.webmanifest" />\n        <meta name="theme-color" content="#000000" />\n        <Links />');
      injected = true;
    }
    if (!injected) return { patched: false, reason: 'no-head-anchor', file: candidates[i] };
    if (dryRun) return { patched: false, reason: 'dry-run', file: candidates[i] };
    fs.writeFileSync(p, newContent);
    return { patched: true, file: candidates[i] };
  }
  return { patched: false, reason: 'no-root-file' };
}

function main() {
  var args = parseArgs(process.argv);
  var knowledge = args.knowledge || path.join(args.target, '..', '.claude-project/docs/PROJECT_KNOWLEDGE.md');
  var appName = args.name || detectAppName(knowledge, 'App');
  var shortName = appName.split(/\s+/)[0].slice(0, 12);

  var manifest = JSON.stringify({
    "_marker": "Generated by scaffold-pwa-manifest — DO NOT EDIT BY HAND.",
    "name": appName,
    "short_name": shortName,
    "description": appName,
    "start_url": "/",
    "display": "standalone",
    "background_color": "#ffffff",
    "theme_color": "#000000",
    "icons": [
      { "src": "/icon-192.png", "sizes": "192x192", "type": "image/png" },
      { "src": "/icon-512.png", "sizes": "512x512", "type": "image/png" }
    ]
  }, null, 2) + '\n';

  var rM = writeIfManaged(path.join(args.target, 'public/manifest.webmanifest'), manifest, /Generated by scaffold-pwa-manifest/, args.force, args.dryRun);
  var rSW = writeIfManaged(path.join(args.target, 'public/sw.js'), SW_JS, /Generated by scaffold-pwa-manifest/, args.force, args.dryRun);
  var rRoot = patchRoot(args.target, args.dryRun);
  console.log('scaffold-pwa-manifest: manifest=' + (rM.written ? 'wrote' : rM.reason) + ' sw=' + (rSW.written ? 'wrote' : rSW.reason) + ' root=' + (rRoot.patched ? 'patched(' + (rRoot.file || '') + ')' : rRoot.reason));
}

main();
