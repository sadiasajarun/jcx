#!/usr/bin/env node
// scaffold-dto-from-entity.js — v77 derives CreateXDto + UpdateXDto +
// XResponseDto from each `<entity>.entity.ts`. Solves the DeepPartial<X>
// constraint failure (TS2344) the LLM hits when it writes its own DTOs
// with plain `string` where the entity declares an enum.
//
// Strategy:
//   - Walk backend/src/modules/<feature>/<feature>.entity.ts
//   - For each entity, parse @Column declarations to get
//     {name, tsType, optional, isEnum, enumName} per property
//   - Emit dtos/create-<entity>.dto.ts with class-validator decorators
//   - Emit dtos/update-<entity>.dto.ts as `PartialType(CreateXDto)`
//   - Emit dtos/<entity>-response.dto.ts that mirrors entity public fields
//   - Re-export aliases the FE expects: CreateXRequest, UpdateXRequest, XResponse
//
// Idempotency: if the dto file already exists AND starts with the
// "Generated by scaffold-dto-from-entity" marker, overwrite. If it
// exists without the marker (LLM authored), skip unless --force.
'use strict';

var fs = require('fs');
var path = require('path');

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--backend-dir') out.backendDir = argv[++i];
    else if (a === '--target') out.backendDir = argv[++i];
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--force') out.force = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.backendDir) { console.error('Usage: scaffold-dto-from-entity --backend-dir BACKEND_DIR [--force]'); process.exit(1); }
  return out;
}

function toPascal(s) {
  return s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').split(/[-_\s]+/).filter(Boolean).map(function (w) {
    return w[0].toUpperCase() + w.slice(1).toLowerCase();
  }).join('');
}

function findEntityFiles(modulesDir) {
  // Entities may live at either:
  //   backend/src/modules/<feature>/<entity>.entity.ts        (rule-compliant)
  //   backend/src/modules/<feature>/entities/<entity>.entity.ts  (LLM-common)
  // Walk recursively and group by feature dir (1st child of modulesDir).
  var out = [];
  if (!fs.existsSync(modulesDir)) return out;
  function walkInModule(modDir, currentDir) {
    fs.readdirSync(currentDir, { withFileTypes: true }).forEach(function (f) {
      var p = path.join(currentDir, f.name);
      if (f.isDirectory()) {
        // Don't recurse into dtos/ (those aren't entities)
        if (f.name === 'dtos' || f.name === 'dto' || f.name === '__tests__') return;
        walkInModule(modDir, p);
      } else if (f.isFile() && /\.entity\.ts$/.test(f.name)) {
        out.push({ moduleDir: modDir, moduleName: path.basename(modDir), entityFile: p });
      }
    });
  }
  fs.readdirSync(modulesDir, { withFileTypes: true }).forEach(function (e) {
    if (!e.isDirectory()) return;
    walkInModule(path.join(modulesDir, e.name), path.join(modulesDir, e.name));
  });
  return out;
}

function parseEntity(content) {
  // Returns: { className, props: [{name, tsType, optional, columnType, isEnum, enumName, nullable, decorators}] }
  var classMatch = /export\s+class\s+(\w+)\s+extends\s+\w+/.exec(content);
  var className = classMatch ? classMatch[1] : null;
  if (!className) return null;
  var props = [];

  // Match: zero-or-more decorator lines, then `name: type;` or `name?: type;`
  // We scan line by line, accumulating decorator block then property declaration.
  var lines = content.split('\n');
  var pendingDecorators = [];
  var inClassBody = false;
  for (var i = 0; i < lines.length; i++) {
    var line = lines[i];
    if (!inClassBody) {
      if (/^export\s+class\s+\w+\s+extends/.test(line)) inClassBody = true;
      continue;
    }
    var trimmed = line.trim();
    if (!trimmed) continue;
    if (/^(constructor|public|private|protected)\b/.test(trimmed)) { pendingDecorators = []; continue; }
    if (/^\}/.test(trimmed)) break;
    if (/^@/.test(trimmed)) { pendingDecorators.push(trimmed); continue; }
    // Property declaration: name<?|!>: type;
    var m = /^(?:readonly\s+)?(\w+)\s*([?!])?:\s*([^;]+);?\s*$/.exec(trimmed);
    if (!m) { pendingDecorators = []; continue; }
    var name = m[1];
    var optional = m[2] === '?';
    var tsType = m[3].trim();
    var decoratorBlob = pendingDecorators.join(' ');
    pendingDecorators = [];
    // Skip relations (ManyToOne/OneToMany/etc.)
    if (/@ManyToOne|@OneToMany|@ManyToMany|@OneToOne|@JoinColumn|@JoinTable/.test(decoratorBlob)) continue;
    // Only accept properties that have @Column or @PrimaryColumn — base-class fields fall through
    if (!/@Column|@PrimaryColumn|@PrimaryGeneratedColumn/.test(decoratorBlob)) continue;
    // Skip id/createdAt/updatedAt/deletedAt (BaseEntity provides them)
    if (/^(id|createdAt|updatedAt|deletedAt)$/.test(name)) continue;
    // v89: skip internal-only fields. Generic patterns:
    //   - *Hash, *Salt, *Token — credentials (security: never accept from client)
    //   - lastLoginAt, lastSeenAt — audit metadata set server-side
    //   - emailVerifiedAt, phoneVerifiedAt — verification state set by server flow
    // These should NEVER appear in CreateDto / UpdateDto (client payload).
    // ResponseDto would also leak passwordHash if included; ResponseDto could
    // be made more permissive in the future but for now we treat the strip
    // list uniformly across all DTO variants.
    if (/(Hash|Salt|Token)$/.test(name)) continue;
    if (/^last(LoginAt|SeenAt|LoginIp|LoginIP)$/i.test(name)) continue;
    if (/^(emailVerifiedAt|phoneVerifiedAt|verifiedAt)$/.test(name)) continue;
    // v93: skip actor/audit fields that are JWT-injected by the controller
    // (req.user.id), NOT submitted by the client. v92 evidence: CreateNoticeDto
    // and CreateFaqDto declared `createdBy!: string` as required input, but
    // the frontend correctly omits it (controller sets from @CurrentUser).
    // Result: CONTRACT_VALIDATION reports HIGH-severity mismatch every run.
    // The pattern is: <verb>By columns (createdBy, updatedBy, deletedBy,
    // reviewedBy, approvedBy, respondedBy, etc.) are audit columns set
    // server-side. If a project truly wants client-specified actor IDs,
    // it should use a name like `assigneeId` or `ownerId`, not `*By`.
    if (/^(created|updated|deleted|reviewed|approved|rejected|responded|published|archived)By$/.test(name)) continue;
    var isEnum = /type:\s*['"]enum['"]/.test(decoratorBlob);
    var enumMatch = /enum:\s*(\w+)/.exec(decoratorBlob);
    var enumName = enumMatch ? enumMatch[1] : null;
    var nullable = /nullable:\s*true/.test(decoratorBlob);
    props.push({
      name: name,
      tsType: tsType,
      optional: optional || nullable,
      columnType: /type:\s*['"](\w+)['"]/.test(decoratorBlob) ? RegExp.$1 : null,
      isEnum: isEnum,
      enumName: enumName,
      nullable: nullable,
    });
  }
  return { className: className, props: props };
}

function findEnumImports(content) {
  // Collect `import { XxxEnum } from '...';` lines that look like enums
  var enums = [];
  var re = /import\s+\{([^}]+)\}\s+from\s+['"]([^'"]+)['"]/g;
  var m;
  while ((m = re.exec(content)) !== null) {
    var names = m[1].split(',').map(function (s) { return s.trim(); }).filter(Boolean);
    var from = m[2];
    names.forEach(function (n) {
      if (/Enum$/.test(n) || /Status$/.test(n)) enums.push({ name: n, from: from });
    });
  }
  return enums;
}

function validatorForProp(p) {
  // Returns class-validator decorators string
  var dec = [];
  if (p.optional) dec.push('@IsOptional()');
  // v89: detect enum usage via either @Column({type:'enum'}) or via the
  // PROPERTY TYPE matching *Enum. After scaffold-numeric-enum-doctor runs,
  // entity columns use `type: 'int'` but the property type stays as
  // `RoleEnum` (typed reference). Without this fallback the validator would
  // emit only @IsNumber() — letting any integer through (security: role: 9999
  // would create an admin-looking user).
  var tsTypeEnum = /Enum$/.test(p.tsType) ? p.tsType.replace(/\s*\|\s*null/g, '').trim() : null;
  if (p.isEnum && p.enumName) {
    dec.push('@IsEnum(' + p.enumName + ')');
  } else if (tsTypeEnum) {
    dec.push('@IsEnum(' + tsTypeEnum + ')');
  } else if (/^number$/.test(p.tsType)) {
    dec.push('@IsNumber()');
  } else if (/^boolean$/.test(p.tsType)) {
    dec.push('@IsBoolean()');
  } else if (/^Date$/.test(p.tsType)) {
    dec.push('@IsDateString()');
  } else if (/email/i.test(p.name)) {
    dec.push('@IsEmail()');
  } else if (/^string$/.test(p.tsType) || /string\s*\|\s*null/.test(p.tsType)) {
    dec.push('@IsString()');
  }
  return dec.join(' ');
}

function generatedMarker() {
  return '// Generated by scaffold-dto-from-entity — DO NOT EDIT BY HAND. Re-run if entity changes.';
}

function emitCreateDto(className, props, enumImports, entityFilenameNoExt) {
  // className: 'User'  →  CreateUserDto
  var dtoName = 'Create' + className + 'Dto';
  var lines = [];
  lines.push(generatedMarker());
  lines.push("import {");
  var validators = ['IsOptional', 'IsString', 'IsNumber', 'IsBoolean', 'IsEnum', 'IsEmail', 'IsDateString'];
  lines.push('  ' + validators.join(', '));
  lines.push("} from 'class-validator';");
  lines.push("import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';");
  // Bring in enums used by properties — rewrite their import paths relative to dtos/
  var enumsUsed = props.filter(function (p) { return p.isEnum && p.enumName; }).map(function (p) { return p.enumName; });
  var seen = {};
  enumImports.forEach(function (e) {
    if (enumsUsed.indexOf(e.name) === -1) return;
    if (seen[e.name]) return; seen[e.name] = true;
    // Rewrite relative-to-entity-dir → relative-to-dtos-dir (add a `../`)
    var from = e.from;
    if (from.charAt(0) === '.') from = '../' + from;
    lines.push("import { " + e.name + " } from '" + from + "';");
  });
  lines.push('');
  lines.push('export class ' + dtoName + ' {');
  props.forEach(function (p) {
    var dec = validatorForProp(p);
    if (p.optional) lines.push('  @ApiPropertyOptional()');
    else lines.push('  @ApiProperty()');
    if (dec) lines.push('  ' + dec);
    lines.push('  ' + p.name + (p.optional ? '?' : '!') + ': ' + p.tsType + ';');
    lines.push('');
  });
  lines.push('}');
  lines.push('');
  // Alias re-export FE typically expects
  lines.push('export type Create' + className + 'Request = ' + dtoName + ';');
  lines.push('');
  return lines.join('\n');
}

function emitUpdateDto(className) {
  var lines = [];
  lines.push(generatedMarker());
  lines.push("import { PartialType } from '@nestjs/swagger';");
  lines.push("import { Create" + className + "Dto } from './create-" + toKebab(className) + ".dto';");
  lines.push('');
  lines.push('export class Update' + className + 'Dto extends PartialType(Create' + className + "Dto) {}");
  lines.push('');
  lines.push('export type Update' + className + 'Request = Update' + className + 'Dto;');
  lines.push('');
  return lines.join('\n');
}

function emitResponseDto(className, props, enumImports) {
  var lines = [];
  lines.push(generatedMarker());
  lines.push("import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';");
  // v93: response DTO must import enums it references in field types.
  // Without this, `status!: AffiliationRequestStatusEnum` becomes TS2304
  // "Cannot find name 'AffiliationRequestStatusEnum'" — the v92→v93 cascade
  // that broke 4 modules' typecheck. Same enum-import logic as emitCreateDto
  // (rewrite '.' paths from entity-dir → dtos-dir by prepending '../').
  var enumsUsed = props.filter(function (p) { return p.isEnum && p.enumName; }).map(function (p) { return p.enumName; });
  var seenEnums = {};
  (enumImports || []).forEach(function (e) {
    if (enumsUsed.indexOf(e.name) === -1) return;
    if (seenEnums[e.name]) return;
    seenEnums[e.name] = true;
    var from = e.from;
    if (from.charAt(0) === '.') from = '../' + from;
    lines.push("import { " + e.name + " } from '" + from + "';");
  });
  lines.push('');
  lines.push('export class ' + className + 'ResponseDto {');
  lines.push('  @ApiProperty()');
  lines.push("  id!: string;");
  lines.push('');
  props.forEach(function (p) {
    if (p.optional) lines.push('  @ApiPropertyOptional()');
    else lines.push('  @ApiProperty()');
    lines.push('  ' + p.name + (p.optional ? '?' : '!') + ': ' + p.tsType + ';');
    lines.push('');
  });
  lines.push('  @ApiProperty()');
  lines.push('  createdAt!: Date;');
  lines.push('');
  lines.push('  @ApiProperty()');
  lines.push('  updatedAt!: Date;');
  lines.push('}');
  lines.push('');
  lines.push('export type ' + className + 'Response = ' + className + 'ResponseDto;');
  lines.push('');
  return lines.join('\n');
}

function toKebab(s) {
  return s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/[_\s]+/g, '-').toLowerCase();
}

function writeIfManaged(file, content, force, dryRun) {
  if (fs.existsSync(file)) {
    var existing = fs.readFileSync(file, 'utf-8');
    if (!/Generated by scaffold-dto-from-entity/.test(existing) && !force) {
      return { written: false, reason: 'exists-handauthored' };
    }
  }
  if (dryRun) return { written: false, reason: 'dry-run' };
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return { written: true };
}

function main() {
  var args = parseArgs(process.argv);
  var modulesDir = path.join(args.backendDir, 'src/modules');
  var entities = findEntityFiles(modulesDir);
  if (entities.length === 0) {
    console.log('scaffold-dto-from-entity: no entities under ' + modulesDir);
    return;
  }
  var written = 0, skipped = 0;
  entities.forEach(function (e) {
    var content = fs.readFileSync(e.entityFile, 'utf-8');
    var parsed = parseEntity(content);
    if (!parsed || parsed.props.length === 0) {
      if (args.verbose) console.log('  skip (no parsable props): ' + e.moduleName);
      return;
    }
    var enumImports = findEnumImports(content);
    var className = parsed.className.replace(/Entity$/, '');
    var entityKebab = toKebab(className);
    var dtosDir = path.join(e.moduleDir, 'dtos');

    var createFile = path.join(dtosDir, 'create-' + entityKebab + '.dto.ts');
    var updateFile = path.join(dtosDir, 'update-' + entityKebab + '.dto.ts');
    var responseFile = path.join(dtosDir, entityKebab + '-response.dto.ts');

    var rCreate = writeIfManaged(createFile, emitCreateDto(className, parsed.props, enumImports, entityKebab), args.force, args.dryRun);
    var rUpdate = writeIfManaged(updateFile, emitUpdateDto(className), args.force, args.dryRun);
    var rResponse = writeIfManaged(responseFile, emitResponseDto(className, parsed.props, enumImports), args.force, args.dryRun);
    [rCreate, rUpdate, rResponse].forEach(function (r) { if (r.written) written++; else skipped++; });
    if (args.verbose) {
      console.log('  ' + e.moduleName + ' (' + className + '): ' +
        [['create', rCreate], ['update', rUpdate], ['response', rResponse]]
          .map(function (p) { return p[0] + '=' + (p[1].written ? 'wrote' : (p[1].reason || 'skip')); }).join(' '));
    }
  });
  console.log('scaffold-dto-from-entity: ' + written + ' written, ' + skipped + ' skipped (handauthored or unchanged)');
}

main();
