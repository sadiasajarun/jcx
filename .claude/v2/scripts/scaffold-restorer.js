#!/usr/bin/env node
// scaffold-restorer.js — v104
//
// Re-run a curated list of idempotent scaffolds at end-of-phase to restore
// the canonical scaffold-emitted state. Catches the case where fix-agent
// edited a scaffold-protected file to "fix" a runtime failure but broke
// the contract.
//
// v104 evidence: fix-agent edited LoginDto's email + password from
// @IsNotEmpty (required) to @IsOptional, "fixing" verify-green but
// breaking POST /auth/login at runtime — every downstream story (84 of 84)
// failed with HTTP 400 on login.
//
// Each scaffold in the list MUST be idempotent + marker-aware (only
// overwrite files containing its own "Generated by scaffold-X" comment).
// Non-marked files (LLM-authored e2e specs, custom pages, etc.) are
// untouched.
//
// Usage:
//   scaffold-restorer --target <RUN_DIR> --phase <backend|frontend>
//                     [--spec MODULE_PLAN.yaml] [--backend-dir DIR]
//                     [--verbose]
'use strict';

var fs = require('fs');
var path = require('path');
var cp = require('child_process');

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--target') out.target = argv[++i];
    else if (a === '--phase') out.phase = argv[++i];
    else if (a === '--spec') out.spec = argv[++i];
    else if (a === '--backend-dir') out.backendDir = argv[++i];
    else if (a === '--claude-dir') out.claudeDir = argv[++i];
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.target || !out.phase) {
    console.error('Usage: scaffold-restorer --target <RUN_DIR> --phase <backend|frontend> [--spec ...] [--backend-dir ...]');
    process.exit(1);
  }
  return out;
}

// Backend scaffolds whose output is canonical and safe to overwrite.
// Order matters: entity changes → dto regen → module wiring.
var BACKEND_RESTORERS = [
  {
    name: 'auth-module',
    script: 'scaffold-auth-module.js',
    args: function (a) {
      return ['--spec', a.spec, '--target', a.backendDir, '--templates', path.join(a.claudeDir, 'nestjs/templates/modules/_auth')];
    },
    requires: ['spec', 'backendDir'],
  },
  {
    name: 'dto-from-entity',
    script: 'scaffold-dto-from-entity.js',
    args: function (a) { return ['--target', a.backendDir]; },
    requires: ['backendDir'],
  },
  {
    name: 'feature-module-stub',
    script: 'scaffold-feature-module-stub.js',
    args: function (a) { return ['--target', a.backendDir]; },
    requires: ['backendDir'],
  },
];

// Frontend scaffolds (run per-cell). Caller passes --target as the
// frontend cell dir. backendDir is the BE source the FE derives from.
var FRONTEND_RESTORERS = [
  {
    name: 'api-client-types',
    script: 'scaffold-api-client-types.js',
    args: function (a) { return ['--backend-dir', a.backendDir, '--target', a.target, '--force']; },
    requires: ['backendDir'],
  },
  {
    name: 'service-from-controller',
    script: 'scaffold-service-from-controller.js',
    args: function (a) { return ['--backend-dir', a.backendDir, '--target', a.target, '--force']; },
    requires: ['backendDir'],
  },
  // v128: restore the auth-bootstrap triad (AuthBootstrap.tsx + providers
  // wiring + numeric-role guards). Fix-agent "repairs" during typecheck can
  // mangle AuthBootstrap or revert guards to string-role comparison — the
  // exact hydration/403 cascade auth-bootstrap exists to prevent. The scaffold
  // always refreshes its marker file + skips already-correct guards, so
  // re-running here is a pure restore.
  {
    name: 'auth-bootstrap',
    script: 'scaffold-auth-bootstrap.js',
    args: function (a) { return ['--target', a.target]; },
    requires: ['target'],
  },
  // v118: MUST be last. api-client-types + service-from-controller above
  // REGENERATE the type/service files from the backend DTOs, which reverts the
  // contract-doctor's repairs (role→numeric, auth shape, stub-exports, etc.).
  // Re-running the doctor here makes the restored state include those fixes, so
  // the frontend BUILD that follows sees a compiling tree. Without this, the
  // doctor's pre-typecheck pass is silently clobbered (v119: doctor got tsc to
  // 1 error, restorer reverted it → build saw 46 again → HARD-fail).
  {
    name: 'frontend-contract-doctor',
    script: 'scaffold-frontend-contract-doctor.js',
    args: function (a) { return ['--target', a.target]; },
    requires: ['target'],
  },
];

function run(args) {
  var list = args.phase === 'backend' ? BACKEND_RESTORERS
           : args.phase === 'frontend' ? FRONTEND_RESTORERS
           : null;
  if (!list) {
    console.error('Unknown --phase: ' + args.phase + ' (expected backend or frontend)');
    process.exit(1);
  }

  var claudeDir = args.claudeDir || path.resolve(__dirname, '..', '..');
  var ran = 0, skipped = 0;
  list.forEach(function (r) {
    var missing = (r.requires || []).filter(function (k) { return !args[k]; });
    if (missing.length > 0) {
      if (args.verbose) console.log('  skip ' + r.name + ': missing ' + missing.join(','));
      skipped++;
      return;
    }
    var argv = r.args(Object.assign({ claudeDir: claudeDir }, args));
    var script = path.join(claudeDir, 'v2/scripts', r.script);
    if (!fs.existsSync(script)) {
      if (args.verbose) console.log('  skip ' + r.name + ': script missing ' + script);
      skipped++;
      return;
    }
    try {
      var result = cp.spawnSync('node', [script].concat(argv), { encoding: 'utf-8' });
      if (result.status === 0) {
        ran++;
        if (args.verbose) console.log('  ✓ ' + r.name + ' restored');
        // Echo any meaningful tail of the sub-scaffold's stdout
        var lastLine = (result.stdout || '').trim().split('\n').slice(-1)[0];
        if (lastLine && args.verbose) console.log('    > ' + lastLine);
      } else {
        if (args.verbose) console.log('  ⚠ ' + r.name + ' failed: ' + (result.stderr || '').slice(0, 200));
      }
    } catch (e) {
      if (args.verbose) console.log('  ⚠ ' + r.name + ' threw: ' + e.message);
    }
  });
  console.log('scaffold-restorer (' + args.phase + '): ' + ran + ' scaffold(s) re-run, ' + skipped + ' skipped');
}

run(parseArgs(process.argv));
