#!/usr/bin/env node
// scaffold-protected-route-guard.js — v78 ship canonical RR7 route guards
// so the LLM doesn't keep reinventing them inconsistently (some guards
// returning <Navigate/>, others Outlet, missing role checks, etc).
//
// Emits:
//   - app/components/guards/AuthGuard.tsx     redirect to /login if not auth'd
//   - app/components/guards/GuestGuard.tsx    redirect home if auth'd
//   - app/components/guards/RoleGuard.tsx     redirect if role mismatch
//   - app/components/guards/ProtectedLayout.tsx  combo auth + role wrapper
//
// Auth state read from Redux `auth` slice; falls back to looking for an
// AuthContext if no Redux slice (we just call useAuth() and assume any
// project that has scaffold-auth-pages provides one of those two).
// Idempotent. Marker: '// Generated by scaffold-protected-route-guard'.
'use strict';

var fs = require('fs');
var path = require('path');

function parseArgs(argv) {
  var out = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === '--target') out.target = argv[++i];
    else if (a === '--force') out.force = true;
    else if (a === '--dry-run') out.dryRun = true;
    else if (a === '--verbose' || a === '-v') out.verbose = true;
  }
  if (!out.target) { console.error('Usage: scaffold-protected-route-guard --target FRONTEND_DIR'); process.exit(1); }
  return out;
}

function marker() { return '// Generated by scaffold-protected-route-guard — DO NOT EDIT BY HAND. Re-run to refresh.'; }

function writeIfManaged(file, content, force, dryRun) {
  if (fs.existsSync(file)) {
    var existing = fs.readFileSync(file, 'utf-8');
    if (!/Generated by scaffold-protected-route-guard/.test(existing) && !force) {
      return { written: false, reason: 'exists-handauthored' };
    }
    if (existing === content) return { written: false, reason: 'unchanged' };
  }
  if (dryRun) return { written: false, reason: 'dry-run' };
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return { written: true };
}

var AUTH_GUARD = [
  marker(),
  "import { Navigate, Outlet, useLocation } from 'react-router';",
  "import { useAppSelector } from '~/hooks/useAppSelector';",
  '',
  'export function AuthGuard() {',
  '  const location = useLocation();',
  "  const isAuthenticated = useAppSelector((s) => Boolean(s?.auth?.user));",
  "  if (!isAuthenticated) return <Navigate to=\"/login\" state={{ from: location }} replace />;",
  '  return <Outlet />;',
  '}',
  '',
].join('\n');

var GUEST_GUARD = [
  marker(),
  "import { Navigate, Outlet } from 'react-router';",
  "import { useAppSelector } from '~/hooks/useAppSelector';",
  '',
  'export function GuestGuard() {',
  "  const isAuthenticated = useAppSelector((s) => Boolean(s?.auth?.user));",
  "  if (isAuthenticated) return <Navigate to=\"/\" replace />;",
  '  return <Outlet />;',
  '}',
  '',
].join('\n');

var ROLE_GUARD = [
  marker(),
  "import { Navigate, Outlet } from 'react-router';",
  "import { useAppSelector } from '~/hooks/useAppSelector';",
  '',
  'export interface RoleGuardProps {',
  '  allowed: string[];',
  '  redirectTo?: string;',
  '}',
  '',
  'export function RoleGuard({ allowed, redirectTo = \'/\' }: RoleGuardProps) {',
  "  const role = useAppSelector((s) => s?.auth?.user?.role) as string | undefined;",
  "  if (!role || !allowed.includes(role)) return <Navigate to={redirectTo} replace />;",
  '  return <Outlet />;',
  '}',
  '',
].join('\n');

var PROTECTED_LAYOUT = [
  marker(),
  "import { Navigate, Outlet, useLocation } from 'react-router';",
  "import { useAppSelector } from '~/hooks/useAppSelector';",
  '',
  'export interface ProtectedLayoutProps {',
  '  /** Optional list of role names; omit to require only authentication. */',
  '  roles?: string[];',
  '  /** Where to send unauthenticated users. */',
  '  loginPath?: string;',
  '  /** Where to send authenticated-but-wrong-role users. */',
  '  forbiddenPath?: string;',
  '}',
  '',
  "export function ProtectedLayout({ roles, loginPath = '/login', forbiddenPath = '/' }: ProtectedLayoutProps) {",
  '  const location = useLocation();',
  "  const user = useAppSelector((s) => s?.auth?.user) as { role?: string } | null | undefined;",
  '  if (!user) return <Navigate to={loginPath} state={{ from: location }} replace />;',
  '  if (roles && roles.length > 0 && (!user.role || !roles.includes(user.role))) {',
  '    return <Navigate to={forbiddenPath} replace />;',
  '  }',
  '  return <Outlet />;',
  '}',
  '',
].join('\n');

function main() {
  var args = parseArgs(process.argv);
  var files = [
    { p: 'app/components/guards/AuthGuard.tsx', c: AUTH_GUARD },
    { p: 'app/components/guards/GuestGuard.tsx', c: GUEST_GUARD },
    { p: 'app/components/guards/RoleGuard.tsx', c: ROLE_GUARD },
    { p: 'app/components/guards/ProtectedLayout.tsx', c: PROTECTED_LAYOUT },
  ];
  var written = 0, skipped = 0;
  files.forEach(function (f) {
    var r = writeIfManaged(path.join(args.target, f.p), f.c, args.force, args.dryRun);
    if (r.written) written++; else skipped++;
    if (args.verbose) console.log('  ' + f.p + ': ' + (r.written ? 'wrote' : r.reason));
  });
  console.log('scaffold-protected-route-guard: ' + written + ' written, ' + skipped + ' skipped');
}

main();
